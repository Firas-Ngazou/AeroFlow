class SimulationEngine(QObject):
    """
    Core physics engine for AeroFlow, managing the lattice-Boltzmann fluid dynamics simulation.

    Handles everything from initializing the D2Q9 grid to computing aerodynamic forces (drag, lift)
    around user-drawn shapes. Supports real-time live-editing of the simulation space, automatically
    adjusting momentum and density when the obstacle mask morphs. Runs on an isolated QThread to
    prevent the PySide6 UI from locking up during heavy compute steps.

    :ivar progressUpdated: Signal emitted with an integer indicating the progress percentage.
    :type progressUpdated: Signal(int)
    :ivar statusMessageUpdated: Signal emitted with a string containing a status message.
    :type statusMessageUpdated: Signal(str)
    :ivar iterationCompleted: Signal emitted with a list of results from the completed iteration.
    :type iterationCompleted: Signal(list)
    :ivar maxStepUpdated: Signal emitted with an integer indicating the updated maximum step count.
    :type maxStepUpdated: Signal(int)
    :ivar dragCoefUpdated: Signal emitted with the updated drag coefficient (float).
    :type dragCoefUpdated: Signal(float)
    :ivar liftCoefUpdated: Signal emitted with the updated lift coefficient (float).
    :type liftCoefUpdated: Signal(float)
    :ivar reynoldsUpdated: Signal emitted with the current Reynolds number (float).
    :type reynoldsUpdated: Signal(float)
    :ivar machUpdated: Signal emitted with the current Mach number (float).
    :type machUpdated: Signal(float)
    :ivar kineticEnergyUpdated: Signal emitted indicating the updated kinetic energy of the flow.
    :type kineticEnergyUpdated: Signal(float)
    :ivar pressureDropUpdated: Signal emitted with the updated pressure drop value.
    :type pressureDropUpdated: Signal(float)
    :ivar massUpdated: Signal emitted with the updated mass quantity value.
    :type massUpdated: Signal(float)
    :ivar enstrophyUpdated: Signal emitted with the updated enstrophy measure of the fluid.
    :type enstrophyUpdated: Signal(float)
    :ivar maxVorticityUpdated: Signal emitted with the max vorticity value in the flow.
    :type maxVorticityUpdated: Signal(float)
    :ivar finished: Signal emitted when the simulation has completed all iterations.
    :type finished: Signal

    - Generated by Gemini
    """
    progressUpdated = Signal(int)
    statusMessageUpdated = Signal(str)
    iterationCompleted = Signal(list)
    maxStepUpdated = Signal(int)
    dragCoefUpdated = Signal(float)
    liftCoefUpdated = Signal(float)
    reynoldsUpdated = Signal(float)
    machUpdated = Signal(float)
    kineticEnergyUpdated = Signal(float)
    pressureDropUpdated = Signal(float)
    massUpdated = Signal(float)
    enstrophyUpdated = Signal(float)
    maxVorticityUpdated = Signal(float)

    finished = Signal()

    def __init__(self, parent: QObject | None = None):
        super().__init__(parent)
        self._grid: LatticeGrid | None = None
        self._obstacle = VectorObstacle()
        self._tau = 0.8
        self._boltzmann_k = 1.38 * (10 ** -23)
        self._air_particle_mass = 4.81 * (10 ** -26)
        self._room_temperature = 293
        self._current_step: int = 0
        self._max_step: int = 10
        self._resolution_x: int = 1689
        self._resolution_y: int = 950

        self._allocation = 5000
        self._estimate_time = 0

        self._frame_start_time = datetime.now()
        self._frame_end_time = datetime.now()
        self._last_times = np.array([])

        self._constants = D2Q9Constants()

        # Data
        self._current_drag_force: float = 0.0
        self._current_lift_force: float = 0.0
        self._last_drag_coef: float = 0.0
        self._last_lift_coef: float = 0.0
        self._u_ref: float = 0.0
        self._rho_ref: float = 1.0
        self._coef_reference_area: float = 0.0
        self._viscosity: float = 0.014

        # Live-edit settings
        self._live_edit = False
        self._pause_requested = False
        self._previous_obstacle_mask: np.ndarray | None = None
        self._pending_live_edit_vertices: np.ndarray | None = None
        self._live_edit_lock = threading.Lock()
        self._live_edit_interval = 1

    def run(self, data: list[float | int]):
        """
        Kicks off the simulation sequence using the provided initial parameters.

        Configures the target resolution, extracts the starting velocity, and triggers
        the maximum step evaluation before dropping into the main time-step loop.

        :param data: Expected to contain [initial_velocity, initial_resolution].
        :type data: list[float | int]
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        initial_velocity = data[0]
        initial_res = data[1]

        self._obstacle.initial_res = initial_res

        self._resolution_x = self._obstacle.binary_mask.shape[0]
        self._resolution_y = self._obstacle.binary_mask.shape[1]

        if not self._live_edit: self._max_step = self._evaluate_max_steps()

        boltzmann_velocity = self._get_boltzmann_v(initial_velocity)
        self._initialize(boltzmann_velocity)
        self._execute_time_step()

    def _get_boltzmann_v(self, initial_velocity: float) -> float:
        """
        Converts the raw input velocity into a normalized lattice velocity.

        We derive this factor using standard room temperature (293K) and the
        estimated mass of an air particle to keep the simulation grounded in physical reality.

        :param initial_velocity: Raw physical velocity requested by the user.
        :type initial_velocity: float
        :return: The normalized lattice velocity.
        :rtype: float

        - Generated by Gemini
        """
        factor = math.sqrt(2 * self._boltzmann_k * self._room_temperature / self._air_particle_mass)
        return initial_velocity / factor

    def _initialize(self, initial_velocity: float):
        """
        Allocates the LatticeGrid and pre-bakes the initial state.

        We set a uniform inflow across the entire domain, compute the base equilibrium
        distributions, and strictly zero out any initial properties inside the masked obstacle region.

        :param initial_velocity: The normalized starting velocity for the inflow.
        :type initial_velocity: float
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._grid = LatticeGrid(self._resolution_x, self._resolution_y)
        self._grid.macro_velocity_x[:, :] = initial_velocity
        self._grid.macro_density[:, :] = 1.0

        self._u_ref = initial_velocity
        self._rho_ref = 1.0

        obstacle_mask = self._obstacle.binary_mask.copy()
        self._previous_obstacle_mask = obstacle_mask.copy()
        self._coef_reference_area = self._coef_initial_checks(obstacle_mask)

        f_eq = self._get_f_eq()
        self._grid.distributions = f_eq

        for i in range(9):
            self._grid.distributions[obstacle_mask, i] = 0.0

        self._grid.macro_velocity_x[obstacle_mask] = 0.0
        self._grid.macro_velocity_y[obstacle_mask] = 0.0
        self._grid.macro_density[obstacle_mask] = 0.0

    def _execute_time_step(self):
        """
        The main engine execution loop.

        Iterates through the core LBM steps: streaming, boundary application, macroscopic updates,
        and collisions. Also safely handles UI pauses, thread interruptions, and live-edit geometry
        swaps per frame.

        :raises KeyboardInterrupt: If the thread is forcibly stopped from the UI.
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        i = 0

        while i < self._max_step:
            if QThread.current_thread().is_interruption_requested():
                self.reset()
                break

            if not self._pause_requested:
                if not self._live_edit: i += 1
                self._frame_start_time = datetime.now()

                self._apply_pending_live_edit_vertices()
                obstacle_mask = self._apply_live_obstacle_changes()

                self.__apply_streaming()
                self.__apply_boundaries(obstacle_mask)
                self._grid.update_macroscopic()
                self.__apply_collision(obstacle_mask)
                self.__end_current_frame(obstacle_mask)

            else:
                QThread.current_thread().msleep(50)

        self.finished.emit()

    def _evaluate_max_steps(self) -> int:
        """
        Calculates the maximum safe iteration count based on available system memory.

        We compute the exact float32 byte footprint of our D2Q9 density arrays and macroscopic
        matrices, capping the buffer at 80% of our designated allocation limit to avoid out-of-memory crashes.

        :return: The maximum number of steps the engine can safely simulate.
        :rtype: int

        - Generated by Gemini
        """
        width = self._resolution_x
        height = self._resolution_y

        bytes_per_float32 = 4
        densities_bytes = width * height * 9 * bytes_per_float32 * 2
        velocity_bytes = width * height * 3 * bytes_per_float32

        mb_engine = (densities_bytes + velocity_bytes) / (1024 ** 2)

        step_bytes = width * height * 4 * bytes_per_float32
        mb_per_step = step_bytes / (1024 ** 2)

        safe_allocation = self._allocation * 0.8
        available_memory = safe_allocation - mb_engine

        estimation = int(available_memory / mb_per_step)
        self.maxStepUpdated.emit(estimation)
        return estimation

    def _calculate_drag_coef(self, obstacle_mask: np.ndarray):
        """
        Computes the aerodynamic drag coefficient acting against the obstacle.

        During live-edits, we apply an 85/15 exponential moving average to smooth out the
        noise caused by sudden geometrical clipping.

        :param obstacle_mask: 2D boolean array representing the drawn shape.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        # C_D = F_D / ((1/2) * rho_ref * U^2 * D)
        area = self._coef_reference_area if self._live_edit else self._coef_initial_checks(obstacle_mask)
        if area == 0:
            coef = 0.0
            self.dragCoefUpdated.emit(coef)
            return

        coef = self._current_drag_force / (0.5 * self._rho_ref * (self._u_ref ** 2) * area)
        if self._live_edit:
            coef = (0.85 * self._last_drag_coef) + (0.15 * coef)
        self._last_drag_coef = coef
        self.dragCoefUpdated.emit(coef)

    def _calculate_lift_coef(self, obstacle_mask: np.ndarray):
        """
        Computes the aerodynamic lift coefficient based on perpendicular momentum transfer.

        Uses the same projected frontal area logic and exponential smoothing buffer as the
        drag coefficient calculation.

        :param obstacle_mask: 2D boolean array representing the drawn shape.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        # C_L = F_L / ((1/2) * rho_ref * U^2 * D)
        area = self._coef_reference_area if self._live_edit else self._coef_initial_checks(obstacle_mask)
        if area == 0:
            coef = 0.0
            self.liftCoefUpdated.emit(coef)
            return

        coef = self._current_lift_force / (0.5 * self._rho_ref * (self._u_ref ** 2) * area)
        if self._live_edit:
            coef = (0.85 * self._last_lift_coef) + (0.15 * coef)
        self._last_lift_coef = coef
        self.liftCoefUpdated.emit(coef)

    def _coef_initial_checks(self, obstacle_mask: np.ndarray) -> float:
        """
        Determines the projected 1D frontal area (width in pixels) of the obstacle.

        This is the characteristic length 'D' needed for our dimensionless coefficients.
        Failsafes to 0.0 if the grid is empty or flow speed is stagnant.

        :param obstacle_mask: The boolean map of solid cells.
        :type obstacle_mask: np.ndarray
        :return: The characteristic area span.
        :rtype: float

        - Generated by Gemini
        """
        mask_y = np.where(obstacle_mask)[1]
        if len(mask_y) > 0:
            area = int(np.max(mask_y)) - int(np.min(mask_y)) + 1
        else:
            return 0.0
        if self._u_ref == 0:
            return 0.0

        return area

    def _calculate_reynolds_number(self, obstacle_mask: np.ndarray):
        """
        Calculates the fluid's Reynolds number for the current frame.

        Used to characterize the flow regime (laminar vs turbulent) based on the
        reference velocity, characteristic length, and chosen kinematic viscosity.

        :param obstacle_mask: The boolean map of solid cells.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        area = self._coef_initial_checks(obstacle_mask)

        if area == 0.0:
            number = 0.0
            self.reynoldsUpdated.emit(number)
            return

        if self._viscosity <= 0:
            self.reynoldsUpdated.emit(float('inf'))
            return

        number = (self._u_ref * area) / self._viscosity
        self.reynoldsUpdated.emit(number)

    def _calculate_max_mach(self):
        """
        Monitors the peak Mach number in the grid to ensure LBM validity.

        We enforce an incompressible limit. If this creeps too high relative to the
        lattice speed of sound (approx 0.577), the simulation will likely destabilize.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        c_s = 0.57735  # Speed of sound in LBM engine
        v_sq = self._grid.macro_velocity_x ** 2 + self._grid.macro_velocity_y ** 2
        max_velocity = math.sqrt(float(np.max(v_sq)))

        number = max_velocity / c_s
        self.machUpdated.emit(number)

    def _calculate_kinetic_energy(self):
        """
        Integrates the total kinetic energy over the entire simulation grid.

        Helps track global energy dissipation, especially useful when analyzing turbulent wakes.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        v_sq = self._grid.macro_velocity_x ** 2 + self._grid.macro_velocity_y ** 2

        energy = float(0.5 * np.sum(self._grid.macro_density * v_sq))
        self.kineticEnergyUpdated.emit(energy)

    def _calculate_pressure_drop(self):
        """
        Measures the raw pressure differential strictly across the obstacle's bounding box.

        We sample a sliver of density columns exactly 5 units upstream and downstream
        to track structural pressure loading.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        mask_x = np.where(self._obstacle.binary_mask)[0]
        if len(mask_x) == 0:
            self.pressureDropUpdated.emit(0.0)
            return

        front_x = int(np.min(mask_x))
        back_x = int(np.max(mask_x))

        upstream_x = max(0, front_x - 5)
        downstream_x = min(self._resolution_x - 1, back_x + 5)

        pressure_upstream = np.mean(self._grid.macro_density[upstream_x, :]) / 3
        pressure_downstream = np.mean(self._grid.macro_density[downstream_x, :]) / 3

        drop = pressure_upstream - pressure_downstream
        self.pressureDropUpdated.emit(drop)

    def _calculate_total_mass(self):
        """
        Calculates the aggregate grid mass to verify numerical conservation.

        A perfectly stable collision operator shouldn't leak any density over time.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        mass = np.sum(self._grid.macro_density)
        self.massUpdated.emit(mass)

    def _calculate_total_enstrophy(self):
        """
        Calculates the total enstrophy (integral of squared vorticity).

        Provides a great single-number metric for the total rotational energy and
        turbulence intensity in the fluid wake.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        vorticity = self._get_vorticity()

        enstrophy = float(0.5 * np.sum(vorticity ** 2))
        self.enstrophyUpdated.emit(enstrophy)

    def _calculate_max_vorticity(self):
        """
        Extracts the absolute peak vorticity magnitude from the current frame.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        vorticity = self._get_vorticity()

        max_vorticity = float(np.max(np.abs(vorticity)))
        self.maxVorticityUpdated.emit(max_vorticity)

    def _get_vorticity(self) -> np.ndarray:
        """
        Computes the 2D spatial curl of the macroscopic velocity field.

        We use a standard numpy central difference gradient across the X and Y arrays
        to map out rotational flow.

        :return: 2D array of localized vorticity values.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        du_y_dx = np.gradient(self._grid.macro_velocity_y, axis = 0)
        du_x_dy = np.gradient(self._grid.macro_velocity_x, axis = 1)
        return du_y_dx - du_x_dy

    def __apply_streaming(self):
        """
        Executes the LBM streaming phase.

        Shifts the discrete distribution functions along their respective D2Q9 lattice vectors.
        We immediately clamp the inlet, outlet, and top/bottom walls back to their
        reference values to simulate an infinite wind-tunnel bounds.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        new_f = np.zeros_like(self._grid.distributions)
        for i in range(9):
            new_f[:, :, i] = np.roll(self._grid.distributions[:, :, i],
                                     (self._constants.E_X[i], self._constants.E_Y[i]), axis = (0, 1))

        self._grid.distributions = new_f

        self._grid.distributions[-1, :, :] = self._grid.distributions[-2, :, :]

        self._grid.macro_velocity_x[0, :] = self._u_ref
        self._grid.macro_velocity_y[0, :] = 0.0
        self._grid.macro_density[0, :] = self._rho_ref

        self._grid.macro_velocity_x[:, 0] = self._u_ref
        self._grid.macro_velocity_y[:, 0] = 0.0
        self._grid.macro_density[:, 0] = self._rho_ref

        self._grid.macro_velocity_x[:, -1] = self._u_ref
        self._grid.macro_velocity_y[:, -1] = 0.0
        self._grid.macro_density[:, -1] = self._rho_ref

        f_eq = self._get_f_eq()
        for i in range(9):
            self._grid.distributions[0, :, i] = f_eq[0, :, i]
            self._grid.distributions[:, 0, i] = f_eq[:, 0, i]
            self._grid.distributions[:, -1, i] = f_eq[:, -1, i]

    def __apply_collision(self, obstacle_mask: np.ndarray) -> None:
        """
        Executes the BGK collision operator on the grid.

        We relax the current particle distributions towards the local equilibrium (f_eq) based on
        our viscosity-derived tau factor. Obstacle cells are strictly bypassed to preserve the
        boundary conditions.

        :param obstacle_mask: 2D boolean array representing the current solid boundaries.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        # on trouve les valeurs de f_eq pour chaque distribution
        f_eq = self._get_f_eq()

        # application du facteur de relaxation
        relaxation = (1 / self._tau) * (f_eq - self._grid.distributions)

        for i in range(9):
            relaxation[obstacle_mask, i] = 0.0

        self._grid.distributions += relaxation

    def __apply_boundaries(self, obstacle_mask: np.ndarray) -> None:
        """
        Enforces the solid bounce-back boundary condition.

        Reverses the incoming particle distributions that hit our vector shape back into the fluid.
        The net momentum delta across this bounce is mathematically aggregated to calculate
        our raw lift and drag forces on the body.

        :param obstacle_mask: The boolean map determining solid impact locations.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        temp_distributions = np.copy(self._grid.distributions)

        momentum_x_before = 0.0
        momentum_y_before = 0.0

        for i in range(9):
            f_in = temp_distributions[obstacle_mask, i]
            momentum_x_before += np.sum(f_in * self._constants.E_X[i])
            momentum_y_before += np.sum(f_in * self._constants.E_Y[i])

        self._current_drag_force = 2 * momentum_x_before
        self._current_lift_force = 2 * momentum_y_before

        for i in range(9):
            opposite = self._constants.OPPOSITES[i]
            # on bouge les particules dans le coter opposee
            self._grid.distributions[obstacle_mask, i] = temp_distributions[obstacle_mask, opposite]

    def _get_f_eq(self) -> np.ndarray:
        """
        Computes the Maxwell-Boltzmann equilibrium distribution (f_eq) for the D2Q9 lattice.

        This matrix represents the theoretical ideal state the fluid wants to relax towards,
        driven purely by the local density and squared velocity magnitudes.

        :return: 3D array of equilibrium weights per lattice node.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        f_eq = np.zeros_like(self._grid.distributions)
        last_term = (self._grid.macro_velocity_x ** 2 +
                     self._grid.macro_velocity_y ** 2)
        for i in range(9):
            term_2 = (self._constants.E_X[i] * self._grid.macro_velocity_x +
                      self._constants.E_Y[i] * self._grid.macro_velocity_y)

            f_eq[:, :, i] = (self._constants.WEIGHTS[i] * self._grid.macro_density *
                             (1 + (3 * term_2) + (4.5 * term_2 ** 2) - (1.5 * last_term)))

        return f_eq

    def __end_current_frame(self, obstacle_mask: np.ndarray) -> None:
        """
        Wraps up the math for the current time step and triggers the UI updates.

        Stacks the macro layers, recalculates all our telemetry (drag, lift, energy, mach),
        and dispatches the payload to the frontend. Live edit throttling happens here to save bandwidth.

        :param obstacle_mask: The obstacle map, passed down for coefficient evaluation.
        :type obstacle_mask: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._current_step += 1

        if self._live_edit and self._current_step % self._live_edit_interval != 0:
            return

        progress = 100 if self._live_edit else int((self._current_step / self._max_step) * 100)
        self.progressUpdated.emit(progress)
        self.__update_status_message()

        macro_velocity_x = self._grid.macro_velocity_x
        macro_velocity_y = self._grid.macro_velocity_y
        macro_density = self._grid.macro_density

        stacked_data = np.stack((macro_velocity_x, macro_velocity_y, macro_density, obstacle_mask), axis = -1)

        self._calculate_drag_coef(obstacle_mask)
        self._calculate_lift_coef(obstacle_mask)
        self._calculate_reynolds_number(obstacle_mask)
        self._calculate_max_mach()
        self._calculate_kinetic_energy()
        self._calculate_pressure_drop()
        self._calculate_total_mass()
        self._calculate_total_enstrophy()
        self._calculate_max_vorticity()
        data = [stacked_data, self._current_step]

        self.iterationCompleted.emit(data)

    def __update_status_message(self) -> None:
        """
        Estimates the remaining processing time for standard runs and pushes it to the UI.

        Keeps a rolling array of delta times per frame to project how long the remaining
        batch of iterations will take. Bypassed entirely when live-edit is toggled.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._live_edit:
            self.statusMessageUpdated.emit("Live")
            return

        self._frame_end_time = datetime.now()
        delta_time = self._frame_end_time - self._frame_start_time
        self._last_times = np.append(self._last_times, delta_time)
        mean_time = np.mean(self._last_times)
        time_left = mean_time * (self._max_step - self._current_step)
        formatted_time = str(time_left).split('.')[0]

        self.statusMessageUpdated.emit(f"Temps restant: {formatted_time}")

    def reset(self) -> None:
        """
        Purges the current grid and zeroes out the entire engine state.

        Called automatically on thread interruptions or when resetting for a fresh batch.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._grid = None
        self._current_step = 0
        self._last_times = np.array([])
        self._frame_start_time = datetime.now()
        self._frame_end_time = datetime.now()
        self._estimate_time = 0
        self._coef_reference_area = 0.0
        self._last_drag_coef = 0.0
        self._last_lift_coef = 0.0
        self.dragCoefUpdated.emit(0.0)
        self.liftCoefUpdated.emit(0.0)
        self.progressUpdated.emit(0)
        self.statusMessageUpdated.emit("Temps restant: 00:00:00")

    def set_reduction_factor(self, factor: float) -> None:
        """
        Tweaks the active geometry reduction factor on our vector layer.

        Dictates how aggressively we simplify or downsample the generated mask array.

        :param factor: Decimal scalar representing the simplification intensity.
        :type factor: float
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._obstacle.reduction_factor = factor

    def _apply_live_obstacle_changes(self) -> np.ndarray:
        """
        The core of our live-edit dynamic meshing logic.

        Diffs the old shape against the new shape mid-simulation. Cells that suddenly become solid
        are instantly zeroed out. Cells that open back up into fluid 'borrow' mass and velocity
        from their valid neighbors to prevent explosive density spikes on the grid.

        :return: The fully processed, current binary obstacle mask.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        obstacle_mask = self._obstacle.binary_mask.copy()

        if self._previous_obstacle_mask is None:
            self._previous_obstacle_mask = obstacle_mask.copy()
            return obstacle_mask

        if obstacle_mask.shape != self._previous_obstacle_mask.shape:
            self._previous_obstacle_mask = obstacle_mask.copy()
            return obstacle_mask

        became_solid = obstacle_mask & ~self._previous_obstacle_mask
        became_air = self._previous_obstacle_mask & ~obstacle_mask

        if np.any(became_air):
            source_fluid = ~obstacle_mask & ~became_air

            density_sum = np.zeros_like(self._grid.macro_density)
            velocity_x_sum = np.zeros_like(self._grid.macro_velocity_x)
            velocity_y_sum = np.zeros_like(self._grid.macro_velocity_y)
            distributions_sum = np.zeros_like(self._grid.distributions)
            neighbor_count = np.zeros_like(self._grid.macro_density)

            for i in range(1, 9):
                shifted_source = np.roll(source_fluid, (self._constants.E_X[i], self._constants.E_Y[i]),
                                         axis = (0, 1))

                density_sum += np.where(
                    shifted_source,
                    np.roll(self._grid.macro_density, (self._constants.E_X[i], self._constants.E_Y[i]),
                            axis = (0, 1)), 0.0)
                velocity_x_sum += np.where(shifted_source, np.roll(self._grid.macro_velocity_x,
                                                                   (self._constants.E_X[i],
                                                                    self._constants.E_Y[i]),
                                                                   axis = (0, 1)), 0.0)
                velocity_y_sum += np.where(shifted_source, np.roll(self._grid.macro_velocity_y,
                                                                   (self._constants.E_X[i],
                                                                    self._constants.E_Y[i]), axis = (0, 1)), 0.0)

                shifted_distributions = np.roll(self._grid.distributions, (self._constants.E_X[i],
                                                                           self._constants.E_Y[i]), axis = (0, 1))
                distributions_sum += np.where(shifted_source[:, :, np.newaxis], shifted_distributions, 0.0)

                neighbor_count += shifted_source.astype(float)

            has_neighbors = became_air & (neighbor_count > 0)
            no_neighbors = became_air & (neighbor_count == 0)

            self._grid.macro_density[has_neighbors] = (density_sum[has_neighbors] / neighbor_count[has_neighbors])
            self._grid.macro_velocity_x[has_neighbors] = (velocity_x_sum[has_neighbors] / neighbor_count[has_neighbors])
            self._grid.macro_velocity_y[has_neighbors] = (velocity_y_sum[has_neighbors] / neighbor_count[has_neighbors])
            self._grid.distributions[has_neighbors, :] = (distributions_sum[has_neighbors, :] /
                                                          neighbor_count[has_neighbors, np.newaxis])

            if np.any(no_neighbors):
                self._grid.macro_velocity_x[no_neighbors] = self._u_ref
                self._grid.macro_velocity_y[no_neighbors] = 0.0
                self._grid.macro_density[no_neighbors] = self._rho_ref

                f_eq = self._get_f_eq()
                for i in range(9):
                    self._grid.distributions[no_neighbors, i] = f_eq[no_neighbors, i]

        if np.any(became_solid):
            self._grid.macro_velocity_x[became_solid] = 0.0
            self._grid.macro_velocity_y[became_solid] = 0.0
            self._grid.macro_density[became_solid] = 0.0

            for i in range(9):
                self._grid.distributions[became_solid, i] = 0.0

        self._previous_obstacle_mask = obstacle_mask.copy()
        return obstacle_mask

    @Slot(np.ndarray)
    def queue_live_edit_vertices(self, to_queue: np.ndarray) -> None:
        """
        Thread-safely receives incoming polygon points from the UI canvas.

        The lock ensures we don't swap the coordinate buffer while the LBM engine
        is halfway through a boundary collision check.

        :param to_queue: Array of vector points sent from the canvas.
        :type to_queue: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        with self._live_edit_lock:
            self._pending_live_edit_vertices = to_queue.copy()

    def _apply_pending_live_edit_vertices(self):
        """
        Flushes the queued vertex points into the primary obstacle object.

        Triggered precisely at the start of a new frame to guarantee synchronous mask generation.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        with self._live_edit_lock:
            if self._pending_live_edit_vertices is None:
                return

            pending = self._pending_live_edit_vertices
            self._pending_live_edit_vertices = None

        self._obstacle.vertices = pending

