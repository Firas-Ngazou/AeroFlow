    def viscosity(self) -> float | None:
        """
        Gets the current kinematic viscosity governing flow separation logic.

        :return: Set viscosity floating value.
        :rtype: float | None

        - Generated by Gemini
        """
        return self._viscosity

    @viscosity.setter
    def viscosity(self, viscosity: float) -> None:
        """
        Sets the kinematic viscosity and derives our collision relaxation time (tau).

        Strict bounds checking is enforced: if tau drops to 0.5 or lower (viscosity <= 0.0035),
        the BGK operator will shatter.

        :param viscosity: The target kinematic viscosity.
        :type viscosity: float
        :raises ValueError: If the requested viscosity breaks numerical bounds.
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        # viscosity = (1/3) * (tau - 0.5)
        # tau = (viscosity * 3) + 0.5
        if viscosity <= 0.0035:
            raise ValueError("Viscosity must be greater than 0.0035 for numerical stability")
        self._viscosity = viscosity
        self._tau = (viscosity * 3) + 0.5

