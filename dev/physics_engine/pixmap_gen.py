import math
from datetime import time, datetime
import cv2

from scipy.ndimage import zoom
from numba import njit, prange

import numpy as np
from PySide6.QtCore import QSize
from PySide6.QtGui import QImage, QPixmap, QPainter, qRgba, Qt, QPen, QColor


class PixmapGen:
    """
    Utility class for generating QPixmap representations of simulation data.

    This class provides static methods to convert NumPy arrays of simulation results
    (velocity, density, etc.) into visual formats like heatmaps, stream lines, and curl plots.
    - Generated by OpenAI's GPT 5.5
    """
    @staticmethod
    @njit(parallel=True, fastmath=True)
    def _apply_heatmap_color_map(data: np.ndarray, base_index: int, transparent_ref: bool = True,
                                 transparent_value: float = 0.0) -> np.ndarray:
        """
        Applies a heatmap color map to the given data array using Numba for acceleration.
        - Generated by OpenAI's GPT 5.5

        :param data: 2D NumPy array of normalized values (0-255).
        :param base_index: The value that corresponds to the base/unaffected state.
        :param transparent_ref: Whether to make values close to base_index transparent.
        :param transparent_value: Specific value to treat as fully transparent.
        :return: A 3D NumPy array of RGBA data.
        """
        w, h = data.shape
        rgba = np.empty((h, w, 4), dtype=np.uint8)

        for x in prange(w):
            for y in range(h):
                value = data[x, y]
                f = value / 255.0
                r = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * (f - 0.5)))))
                g = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * (f - 0.25)))))
                b = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * f))))
                a = 0

                if not transparent_ref and value != transparent_value:
                    a = 255
                elif transparent_ref:
                    difference = abs(value - base_index)
                    a = min(difference**2, 255)

                rgba[y, x, 0] = r
                rgba[y, x, 1] = g
                rgba[y, x, 2] = b
                rgba[y, x, 3] = a

        return rgba

    @staticmethod
    def generate_heatmap(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                         transparent_ref: bool = True) -> QPixmap:
        """
        Generate a heatmap visualization from the input data array using scaled velocity values
        and an optional transparency reference. The generated heatmap is returned as a QPixmap
        object. - Generated by OpenAI's GPT 5.5

        :param data: A numpy array of shape (..., 4) containing macro_velocity_x, macro_velocity_y,
            macro_density, and binary_mask. Each channel represents corresponding attributes of
            the macroscopic fluid or motion data.
        :param target_height: Desired output height of the heatmap in pixels. Default is 1080.
        :param target_width: Desired output width of the heatmap in pixels. Default is 1920.
        :param transparent_ref: A boolean flag indicating whether the generated heatmap will
            include transparency based on its values. Default is True.
        :return: A QPixmap object containing the resulting heatmap visualization.
        :rtype: QPixmap
        """
        macro_velocity_x, macro_velocity_y, macro_density, binary_mask = np.unstack(data, axis=-1)
        speeds = np.sqrt(macro_velocity_x**2 + macro_velocity_y**2)

        high_res_speeds = cv2.resize(speeds, (target_height, target_width), interpolation=cv2.INTER_LINEAR)

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation=cv2.INTER_LINEAR).astype(bool)
            high_res_speeds[high_res_mask] = 0

        unaffected = speeds.shape[1] // 2
        base_speed = speeds[0, unaffected]

        max_speed = np.max(high_res_speeds)
        if max_speed == 0:
            max_speed = 1

        base_index = int((base_speed / max_speed) * 255)
        normalized_speeds = np.clip((high_res_speeds / max_speed) * 255, 0, 255).astype(np.uint8)

        rgba_data = PixmapGen._apply_heatmap_color_map(normalized_speeds, base_index, transparent_ref)

        im_height, im_width, _ = rgba_data.shape
        temp_image = QImage(rgba_data.data, im_width, im_height, im_width * 4, QImage.Format.Format_RGBA8888)
        heatmap_pixmap = QPixmap.fromImage(temp_image.copy())
        return heatmap_pixmap

    @staticmethod
    def generate_density(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                         transparent_ref: bool = True) -> QPixmap:
        """
        Generates a density map as a QPixmap object from the provided data, performing resizing, normalization,
        and color mapping. The method processes the input macro density and binary mask arrays, interpolates to
        the target size, applies normalization, and generates an RGBA-encoded image with a heatmap color
        mapping. The output can be used for various visualization purposes. - Generated by OpenAI's GPT 5.5

        :param data: A numpy ndarray containing four elements along the last axis. This includes the input
            macro density and binary mask arrays needed to compute and map density values.
        :type data: np.ndarray
        :param target_height: The desired height of the output density map. Defaults to 1080.
        :type target_height: int
        :param target_width: The desired width of the output density map. Defaults to 1920.
        :type target_width: int
        :param transparent_ref: A boolean flag determining whether the heatmap uses a transparent reference
            point. Defaults to True.
        :type transparent_ref: bool
        :return: A QPixmap representation of the computed density map.
        :rtype: QPixmap
        """
        _, _, macro_density, binary_mask = np.unstack(data, axis=-1)

        high_res_density = cv2.resize(macro_density, (target_height, target_width),
                                      interpolation=cv2.INTER_LINEAR)

        unaffected = macro_density.shape[1] // 2
        base_density = macro_density[0, unaffected]

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation=cv2.INTER_LINEAR).astype(bool)
            high_res_density[high_res_mask] = base_density

        density_difference = high_res_density - base_density
        max_difference = np.max(np.abs(density_difference))

        if max_difference == 0:
            max_difference = 1

        normalized_densities = np.clip(((density_difference / max_difference) * 127) + 127,
                                       0, 255).astype(np.uint8)

        base_index = 127
        rgba_data = PixmapGen._apply_heatmap_color_map(normalized_densities, base_index, transparent_ref,
                                                       base_index)
        im_height, im_width, _ = rgba_data.shape
        temp_image = QImage(rgba_data.data, im_width, im_height, im_width * 4, QImage.Format.Format_RGBA8888)
        stream_pixmap = QPixmap.fromImage(temp_image.copy())

        return stream_pixmap

    @staticmethod
    def generate_curl(data: np.ndarray, target_height: int = 1080, target_width: int = 1920) -> QPixmap:
        """
        Generates a QPixmap representation of the curl derived from the input flow field data.

        This method computes the curl of a flow field, resizes it to a specified resolution, and normalizes
        it. The result is rendered as a grayscale image with transparency and returned as a QPixmap.
         - Generated by OpenAI's GPT 5.5

        :param data: The input 4D array containing flow field data. Expected to have dimensions where the
            last axis contains at least `ux`, `uy`, and `binary_mask`. `ux` and `uy` represent horizontal
            and vertical components of the flow field, respectively, while `binary_mask` is an optional
            binary mask used to exclude certain regions from the computation.
        :param target_height: The height of the output image in pixels. Default is 1080.
        :param target_width: The width of the output image in pixels. Default is 1920.
        :return: A QPixmap object representing the generated curl visualization.
        :rtype: QPixmap
        """
        ux, uy, _, binary_mask = np.unstack(data, axis=-1)

        # curl = d(uy)/dx - d(ux)/dy
        curls = (np.roll(uy, -1, axis=0) - np.roll(uy, 1, axis=0) -
                 np.roll(ux, -1, axis=1) + np.roll(ux, 1, axis=1))

        high_res_curls = cv2.resize(curls, (target_height, target_width), interpolation=cv2.INTER_LINEAR)

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation=cv2.INTER_LINEAR).astype(bool)
            high_res_curls[high_res_mask] = 0

        max_curl = np.max(np.abs(high_res_curls))

        if max_curl == 0:
            max_curl = 1

        normalized_curls = np.clip(((high_res_curls / max_curl) * 127) + 127, 0, 255).astype(np.uint8)

        image_data = np.ascontiguousarray(normalized_curls.T)
        height, width = image_data.shape

        temp_image = QImage(image_data.data, width, height, width, QImage.Format.Format_Indexed8)

        color_table = []
        base_index = 127
        for i in range(256):
            difference = abs(i - base_index)
            strength = difference

            gray = int(255 * strength)
            alpha = int(np.clip(difference ** 2, 0, 255))

            color_table.append(qRgba(gray, gray, gray, alpha))

        temp_image.setColorTable(color_table)
        curl_pixmap = QPixmap.fromImage(temp_image.copy())

        return curl_pixmap

    @staticmethod
    def generate_stream(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                        count: int = 10) -> QPixmap:
        """
        Generates a QPixmap rendering of a vector field based on input data, target dimensions, and
        line count. The rendered image visualizes the flow and density of the field. - Generated by OpenAI's GPT 5.5

        :param data: A NumPy array with the shape (..., 4), where the last axis represents
            the components of the vector field: velocity_x, velocity_y, macro_density, and binary_mask.
        :param target_height: The target height for the generated image in pixels. Default is 1080.
        :param target_width: The target width for the generated image in pixels. Default is 1920.
        :param count: The number of lines to visualize in the vertical direction. Default is 10.
        :return: A QPixmap object containing the rendered vector field visualization.
        """
        velocity_x, velocity_y, macro_density, binary_mask = np.unstack(data, axis=-1)

        width_grid = velocity_x.shape[0]
        height_grid = velocity_y.shape[1]

        final_pixmap = QPixmap(target_width, target_height)
        final_pixmap.fill(Qt.GlobalColor.transparent)

        painter = QPainter(final_pixmap)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)

        pen = QPen(QColor(230, 230, 230, 150))
        pen.setWidth(2)
        painter.setPen(pen)

        spacing_y = height_grid//count # la distance entre les lignes
        max_steps = 1920  # resolution max
        step_size = 3.0

        scale_x = target_width / width_grid
        scale_y = target_height / height_grid

        for start_y in range(spacing_y // 2, height_grid, spacing_y):
            x = 0.0
            y = float(start_y)

            last_x = None
            last_y = None

            for _ in range(max_steps):
                if not np.isfinite(x) or not np.isfinite(y):
                    break

                rounded_x = int(round(x))
                rounded_y = int(round(y))

                if rounded_x < 0 or rounded_x >= width_grid:
                    break

                if rounded_y < 0 or rounded_y >= height_grid:
                    break

                if binary_mask[rounded_x, rounded_y]:
                    break

                vx = velocity_x[rounded_x, rounded_y]
                vy = velocity_y[rounded_x, rounded_y]
                speed = math.sqrt(vx ** 2 + vy ** 2)

                if speed == 0:
                    break

                screen_x = int(scale_x * x)
                screen_y = int(scale_y * y)

                if last_x is not None and last_y is not None:
                    painter.drawLine(last_x, last_y, screen_x, screen_y)

                last_x = screen_x
                last_y = screen_y

                x += (vx / speed) * step_size
                y += (vy / speed) * step_size

        painter.end()

        return final_pixmap

    @staticmethod
    def stacked_stream(heatmap: QPixmap, stream: QPixmap) -> QPixmap:
        """
        Stacks a stream line pixmap over a heatmap pixmap. - Generated by OpenAI's GPT 5.5

        :param heatmap: The base heatmap pixmap.
        :param stream: The stream line pixmap to stack.
        :return: A new pixmap with combined data.
        """
        pixmap = heatmap.copy()
        painter = QPainter(pixmap)
        painter.setCompositionMode(QPainter.CompositionMode.CompositionMode_DestinationIn)
        painter.drawPixmap(0, 0, stream)
        painter.end()
        return pixmap

