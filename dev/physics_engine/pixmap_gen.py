class PixmapGen:
    """
    Handles the generation of heatmap, density, curl, and streamline visualizations as QPixmap objects.

    This class provides static methods to process 2D numerical simulation data (velocity fields,
    density maps, and boolean masks). It leverages Numba for parallelized array processing and OpenCV
    for rapid interpolation, ultimately producing PySide6-compatible QPixmap objects for direct UI rendering.

    - Generated by Gemini
    """

    @staticmethod
    @njit(parallel = True, fastmath = True)
    def _apply_heatmap_color_map(data: np.ndarray, base_index: int, transparent_ref: bool = True,
                                 transparent_value: float = 0.0) -> np.ndarray:
        """
        Applies a custom RGB and alpha mapping to a normalized 2D data array.

        This method iterates over the provided 2D scalar field and calculates RGBA values based on
        predefined intensity curves. Alpha mapping is handled either by computing the quadratic difference
        from a base reference index or by masking out a specific fixed value.

        :param data: A 2D NumPy array of shape (height, width) containing 8-bit normalized values (0-255).
        :type data: np.ndarray
        :param base_index: The reference value (0-255) used to scale transparency when transparent_ref is True.
        :type base_index: int
        :param transparent_ref: Determines if transparency is calculated relative to base_index. Defaults to True.
        :type transparent_ref: bool
        :param transparent_value: The exact scalar value to render fully transparent if transparent_ref is False.
        :type transparent_value: float
        :return: A 3D NumPy array of shape (height, width, 4) containing the resulting uint8 RGBA values.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        w, h = data.shape
        rgba = np.empty((h, w, 4), dtype = np.uint8)

        for x in prange(w):
            for y in range(h):
                value = data[x, y]
                f = value / 255.0
                r = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * (f - 0.5)))))
                g = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * (f - 0.25)))))
                b = int(255 * max(0, min(1, 1.5 - abs(1 - 4 * f))))
                a = 0

                if not transparent_ref and value != transparent_value:
                    a = 255
                elif transparent_ref:
                    difference = abs(value - base_index)
                    a = min(difference ** 2, 255)

                rgba[y, x, 0] = r
                rgba[y, x, 1] = g
                rgba[y, x, 2] = b
                rgba[y, x, 3] = a

        return rgba

    @staticmethod
    def generate_heatmap(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                         transparent_ref: bool = True) -> QPixmap:
        """
        Generates a velocity magnitude heatmap from raw simulation data.

        Extracts the macroscopic velocity components, calculates the Euclidean speed, and
        upscales the scalar field to the target resolution using bilinear interpolation.
        Speeds are normalized against the maximum observed value and converted into a colored QPixmap.
        Masked boundaries are explicitly zeroed out.

        :param data: A 3D NumPy array containing [macro_velocity_x, macro_velocity_y, macro_density, binary_mask].
        :type data: np.ndarray
        :param target_height: The pixel height of the output map. Defaults to 1080.
        :type target_height: int
        :param target_width: The pixel width of the output map. Defaults to 1920.
        :type target_width: int
        :param transparent_ref: If True, applies variable alpha blending relative to the baseline speed.
        :type transparent_ref: bool
        :return: A compiled QPixmap containing the rendered velocity heatmap.
        :rtype: QPixmap

        - Generated by Gemini
        """
        macro_velocity_x, macro_velocity_y, macro_density, binary_mask = np.unstack(data, axis = -1)
        speeds = np.sqrt(macro_velocity_x ** 2 + macro_velocity_y ** 2)

        high_res_speeds = cv2.resize(speeds, (target_height, target_width), interpolation = cv2.INTER_LINEAR)

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation = cv2.INTER_LINEAR).astype(bool)
            high_res_speeds[high_res_mask] = 0

        unaffected = speeds.shape[1] // 2
        base_speed = speeds[0, unaffected]

        max_speed = np.max(high_res_speeds)
        if max_speed == 0:
            max_speed = 1

        base_index = int((base_speed / max_speed) * 255)
        normalized_speeds = np.clip((high_res_speeds / max_speed) * 255, 0, 255).astype(np.uint8)

        rgba_data = PixmapGen._apply_heatmap_color_map(normalized_speeds, base_index, transparent_ref)

        im_height, im_width, _ = rgba_data.shape
        temp_image = QImage(rgba_data.data, im_width, im_height, im_width * 4, QImage.Format.Format_RGBA8888)
        heatmap_pixmap = QPixmap.from_image(temp_image.copy())
        return heatmap_pixmap

    @staticmethod
    def generate_density(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                         transparent_ref: bool = True) -> QPixmap:
        """
        Generates a density deviation map from raw simulation data.

        Extracts the macroscopic density, upscales it to the requested resolution, and computes
        the spatial deviation from the baseline density. The resulting differences are normalized
        around a center point of 127 (representing no deviation) and mapped to an RGBA QPixmap.

        :param data: A 3D NumPy array containing [macro_velocity_x, macro_velocity_y, macro_density, binary_mask].
        :type data: np.ndarray
        :param target_height: The pixel height of the output map. Defaults to 1080.
        :type target_height: int
        :param target_width: The pixel width of the output map. Defaults to 1920.
        :type target_width: int
        :param transparent_ref: If True, areas with zero density deviation are rendered transparent.
        :type transparent_ref: bool
        :return: A compiled QPixmap containing the rendered density deviation map.
        :rtype: QPixmap

        - Generated by Gemini
        """
        _, _, macro_density, binary_mask = np.unstack(data, axis = -1)

        high_res_density = cv2.resize(macro_density, (target_height, target_width),
                                      interpolation = cv2.INTER_LINEAR)

        unaffected = macro_density.shape[1] // 2
        base_density = macro_density[0, unaffected]

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation = cv2.INTER_LINEAR).astype(bool)
            high_res_density[high_res_mask] = base_density

        density_difference = high_res_density - base_density
        max_difference = np.max(np.abs(density_difference))

        if max_difference == 0:
            max_difference = 1

        normalized_densities = np.clip(((density_difference / max_difference) * 127) + 127,
                                       0, 255).astype(np.uint8)

        base_index = 127
        rgba_data = PixmapGen._apply_heatmap_color_map(normalized_densities, base_index, transparent_ref,
                                                       base_index)
        im_height, im_width, _ = rgba_data.shape
        temp_image = QImage(rgba_data.data, im_width, im_height, im_width * 4, QImage.Format.Format_RGBA8888)
        stream_pixmap = QPixmap.from_image(temp_image.copy())

        return stream_pixmap

    @staticmethod
    def generate_curl(data: np.ndarray, target_height: int = 1080, target_width: int = 1920) -> QPixmap:
        """
        Computes and visualizes the 2D discrete curl (vorticity) of the vector field.

        Calculates the curl using centered finite differences on the velocity components. The
        scalar field is then upscaled and normalized into an 8-bit format. An indexed grayscale
        color table is applied where pixel opacity quadratically scales with curl magnitude.

        :param data: A 3D NumPy array containing [macro_velocity_x, macro_velocity_y, macro_density, binary_mask].
        :type data: np.ndarray
        :param target_height: The pixel height of the output map. Defaults to 1080.
        :type target_height: int
        :param target_width: The pixel width of the output map. Defaults to 1920.
        :type target_width: int
        :return: A compiled QPixmap containing the grayscale curl visualization.
        :rtype: QPixmap

        - Generated by Gemini
        """
        ux, uy, _, binary_mask = np.unstack(data, axis = -1)

        # curl = d(uy)/dx - d(ux)/dy
        curls = (np.roll(uy, -1, axis = 0) - np.roll(uy, 1, axis = 0) -
                 np.roll(ux, -1, axis = 1) + np.roll(ux, 1, axis = 1))

        high_res_curls = cv2.resize(curls, (target_height, target_width), interpolation = cv2.INTER_LINEAR)

        if binary_mask is not None:
            high_res_mask = cv2.resize(binary_mask, (target_height, target_width),
                                       interpolation = cv2.INTER_LINEAR).astype(bool)
            high_res_curls[high_res_mask] = 0

        max_curl = np.max(np.abs(high_res_curls))

        if max_curl == 0:
            max_curl = 1

        normalized_curls = np.clip(((high_res_curls / max_curl) * 127) + 127, 0, 255).astype(np.uint8)

        image_data = np.ascontiguousarray(normalized_curls.T)
        height, width = image_data.shape

        temp_image = QImage(image_data.data, width, height, width, QImage.Format.Format_Indexed8)

        color_table = []
        base_index = 127
        for i in range(256):
            difference = abs(i - base_index)
            strength = difference

            gray = int(255 * strength)
            alpha = int(np.clip(difference ** 2, 0, 255))

            color_table.append(qRgba(gray, gray, gray, alpha))

        temp_image.set_color_table(color_table)
        curl_pixmap = QPixmap.from_image(temp_image.copy())

        return curl_pixmap

    @staticmethod
    def generate_stream(data: np.ndarray, target_height: int = 1080, target_width: int = 1920,
                        count: int = 10) -> QPixmap:
        """
        Traces and renders streamlines to visualize vector field flow dynamics.

        Seeds discrete points along the vertical axis of the grid and performs step-by-step
        Euler integration to trace the flow lines. The coordinates are scaled from grid space
        to screen space and painted directly onto a transparent QPixmap using QPainter.
        Tracing stops if a boundary, mask, or zero-velocity zone is hit.

        :param data: A 3D NumPy array containing [macro_velocity_x, macro_velocity_y, macro_density, binary_mask].
        :type data: np.ndarray
        :param target_height: The pixel height of the output map. Defaults to 1080.
        :type target_height: int
        :param target_width: The pixel width of the output map. Defaults to 1920.
        :type target_width: int
        :param count: The number of vertical seed points generated along the boundary. Defaults to 10.
        :type count: int
        :return: A transparent QPixmap containing the rendered streamlines.
        :rtype: QPixmap

        - Generated by Gemini
        """
        velocity_x, velocity_y, macro_density, binary_mask = np.unstack(data, axis = -1)

        width_grid = velocity_x.shape[0]
        height_grid = velocity_y.shape[1]

        final_pixmap = QPixmap(target_width, target_height)
        final_pixmap.fill(Qt.GlobalColor.transparent)

        painter = QPainter(final_pixmap)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)

        pen = QPen(QColor(230, 230, 230, 150))
        pen.set_width(2)
        painter.set_pen(pen)

        spacing_y = height_grid // count  # la distance entre les lignes
        max_steps = 1920  # resolution max
        step_size = 3.0

        scale_x = target_width / width_grid
        scale_y = target_height / height_grid

        for start_y in range(spacing_y // 2, height_grid, spacing_y):
            x = 0.0
            y = float(start_y)

            last_x = None
            last_y = None

            for _ in range(max_steps):
                if not np.isfinite(x) or not np.isfinite(y):
                    break

                rounded_x = int(round(x))
                rounded_y = int(round(y))

                if rounded_x < 0 or rounded_x >= width_grid:
                    break

                if rounded_y < 0 or rounded_y >= height_grid:
                    break

                if binary_mask[rounded_x, rounded_y]:
                    break

                vx = velocity_x[rounded_x, rounded_y]
                vy = velocity_y[rounded_x, rounded_y]
                speed = math.sqrt(vx ** 2 + vy ** 2)

                if speed == 0:
                    break

                screen_x = int(scale_x * x)
                screen_y = int(scale_y * y)

                if last_x is not None and last_y is not None:
                    painter.draw_line(last_x, last_y, screen_x, screen_y)

                last_x = screen_x
                last_y = screen_y

                x += (vx / speed) * step_size
                y += (vy / speed) * step_size

        painter.end()

        return final_pixmap

    @staticmethod
    def stacked_stream(heatmap: QPixmap, stream: QPixmap) -> QPixmap:
        """
        Composites a streamline visualization directly onto a heatmap via destination-in blending.

        This performs hardware-accelerated pixel blending using QPainter, effectively masking and
        integrating the visual flow data into the scalar background.

        :param heatmap: The base QPixmap serving as the visual background.
        :type heatmap: QPixmap
        :param stream: The streamline overlay QPixmap to blend.
        :type stream: QPixmap
        :return: A new combined QPixmap containing both layers.
        :rtype: QPixmap

        - Generated by Gemini
        """
        pixmap = heatmap.copy()
        painter = QPainter(pixmap)
        painter.set_composition_mode(QPainter.CompositionMode.CompositionMode_DestinationIn)
        painter.draw_pixmap(0, 0, stream)
        painter.end()
        return pixmap

