import numpy as np


class D2Q9Constants:
    """
    Defines the fundamental static parameters for the D2Q9 (2 Dimensions, 9 Velocities) Lattice Boltzmann velocity scheme.

    We use these lattice weights, directional basis vectors, and the speed of sound scalar to strictly govern
    the collision and streaming phases of our fluid simulation. The opposites array maps the collision
    rebound indices for our boundary conditions.
    - Generated by Gemini.

    :ivar WEIGHTS: Equilibrium weights for the nine discrete lattice directions.
    :type WEIGHTS: np.ndarray
    :ivar E_X: The discrete velocity components along the x-axis.
    :type E_X: np.ndarray
    :ivar E_Y: The discrete velocity components along the y-axis.
    :type E_Y: np.ndarray
    :ivar SPEED_OF_SOUND_SQUARED: The squared isothermal speed of sound for the D2Q9 lattice (Cs^2 = 1/3).
    :type SPEED_OF_SOUND_SQUARED: float
    :ivar OPPOSITES: Index mapping for the exact anti-parallel direction of each lattice velocity.
    :type OPPOSITES: np.ndarray
    """
    WEIGHTS: np.ndarray = np.array([4 / 9, 1 / 9, 1 / 9, 1 / 9, 1 / 9, 1 / 36, 1 / 36, 1 / 36, 1 / 36])
    E_X: np.ndarray = np.array([0, 1, 0, -1, 0, 1, -1, -1, 1])
    E_Y: np.ndarray = np.array([0, 0, 1, 0, -1, 1, 1, -1, -1])
    SPEED_OF_SOUND_SQUARED: float = 1 / 3
    OPPOSITES: np.ndarray = np.array([0, 3, 4, 1, 2, 7, 8, 5, 6])


class LatticeGrid:
    """
    Represents the core computational domain for our Lattice Boltzmann solver.

    This class actively manages the microscopic particle distributions alongside the observable
    macroscopic fluid fields (density and velocity vectors) across the discrete 2D grid.
    - Generated by Gemini.
    """

    def __init__(self, width: int, height: int) -> None:
        """
        Allocates the memory matrices for our simulation grid and initializes the physics state.

        We initialize the microscopic probability distribution functions (f_i) to their equilibrium
        rest states using the D2Q9 base weights, and zero out the macroscopic density and velocity fields.
        - Generated by Gemini.

        :param width: The horizontal cell count of our simulation domain.
        :type width: int
        :param height: The vertical cell count of our simulation domain.
        :type height: int
        """
        self._width: int = width
        self._height: int = height
        self._constants: D2Q9Constants = D2Q9Constants()

        self._distributions: np.ndarray = np.zeros((width, height, 9))
        for i in range(9):
            self._distributions[:, :, i] = self._constants.WEIGHTS[i]

        self._macro_density: np.ndarray = np.zeros((width, height), dtype = np.float64)
        self._macro_velocity_x: np.ndarray = np.zeros((width, height), dtype = np.float64)
        self._macro_velocity_y: np.ndarray = np.zeros((width, height), dtype = np.float64)

    def update_macroscopic(self) -> None:
        """
        Integrates the discrete microscopic distributions across all 9 lattice directions to compute
        the observable macroscopic fluid density and velocity vectors for the current time step.

        Includes safe-division handling to prevent divide-by-zero math errors in absolute vacuum
        states by temporarily clamping zero-density zones.
        - Generated by Gemini.
        """
        self._macro_density = np.sum(self._distributions, axis = 2)
        safe_density = np.where(self._macro_density == 0, 1.0, self._macro_density)
        self._macro_velocity_x = np.sum(self._distributions * self._constants.E_X, axis = 2) / safe_density
        self._macro_velocity_y = np.sum(self._distributions * self._constants.E_Y, axis = 2) / safe_density

        self._macro_velocity_x[self._macro_density == 0] = 0.0
        self._macro_velocity_y[self._macro_density == 0] = 0.0

    @property
    def distributions(self) -> np.ndarray:
        """
        Retrieves the current microscopic particle distribution functions (f_i) for the entire grid.
        - Generated by Gemini.

        :return: A 3D tensor containing the 9 directional distributions per cell.
        :rtype: np.ndarray
        """
        return self._distributions

    @distributions.setter
    def distributions(self, new_distributions: np.ndarray) -> None:
        """
        Overwrites the microscopic particle distributions directly.
        - Generated by Gemini.

        :param new_distributions: The incoming 3D tensor of particle states.
        :type new_distributions: np.ndarray
        """
        self._distributions = new_distributions

    @property
    def macro_density(self) -> np.ndarray:
        """
        Retrieves the calculated macroscopic fluid density field (rho).
        - Generated by Gemini.

        :return: A 2D scalar field representing mass density.
        :rtype: np.ndarray
        """
        return self._macro_density

    @macro_density.setter
    def macro_density(self, new_macro_density: np.ndarray) -> None:
        """
        Manually overrides the macroscopic density field.
        - Generated by Gemini.

        :param new_macro_density: The new 2D scalar field.
        :type new_macro_density: np.ndarray
        """
        self._macro_density = new_macro_density

    @property
    def macro_velocity_x(self) -> np.ndarray:
        """
        Retrieves the calculated macroscopic fluid velocity component along the x-axis.
        - Generated by Gemini.

        :return: A 2D vector field containing the horizontal velocity components.
        :rtype: np.ndarray
        """
        return self._macro_velocity_x

    @macro_velocity_x.setter
    def macro_velocity_x(self, new_macro_velocity_x: np.ndarray) -> None:
        """
        Manually overrides the macroscopic horizontal velocity field.
        - Generated by Gemini.

        :param new_macro_velocity_x: The new 2D horizontal velocity matrix.
        :type new_macro_velocity_x: np.ndarray
        """
        self._macro_velocity_x = new_macro_velocity_x

    @property
    def macro_velocity_y(self) -> np.ndarray:
        """
        Retrieves the calculated macroscopic fluid velocity component along the y-axis.
        - Generated by Gemini.

        :return: A 2D vector field containing the vertical velocity components.
        :rtype: np.ndarray
        """
        return self._macro_velocity_y

    @macro_velocity_y.setter
    def macro_velocity_y(self, new_macro_velocity_y: np.ndarray) -> None:
        """
        Manually overrides the macroscopic vertical velocity field.
        - Generated by Gemini.

        :param new_macro_velocity_y: The new 2D vertical velocity matrix.
        :type new_macro_velocity_y: np.ndarray
        """
        self._macro_velocity_y = new_macro_velocity_y