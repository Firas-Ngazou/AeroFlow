import numpy as np

class D2Q9Constants:
    """
    Constants for the D2Q9 lattice model in lattice Boltzmann simulations.

    The class provides key constants used in the D2Q9 lattice model, including
    weights for lattice directions, lattice velocities in both x and y
    directions, speed of sound squared, and opposite direction mapping. These
    constants are integral to defining the behavior of the D2Q9 model.
    - Generated by OpenAI's GPT 5.5

    :ivar WEIGHTS: Weights for the nine lattice directions.
    :type WEIGHTS: numpy.ndarray
    :ivar E_X: Lattice velocity components in the x-direction.
    :type E_X: numpy.ndarray
    :ivar E_Y: Lattice velocity components in the y-direction.
    :type E_Y: numpy.ndarray
    :ivar SPEED_OF_SOUND_SQUARED: Square of the speed of sound for the D2Q9 model.
    :type SPEED_OF_SOUND_SQUARED: float
    :ivar OPPOSITES: Mapping of each direction to its opposite direction.
    :type OPPOSITES: numpy.ndarray
    """
    WEIGHTS = np.array([4/9, 1/9, 1/9, 1/9, 1/9, 1/36, 1/36, 1/36, 1/36])
    E_X = np.array([0, 1, 0, -1, 0, 1, -1, -1, 1])
    E_Y = np.array([0, 0, 1, 0, -1, 1, 1, -1, -1])
    SPEED_OF_SOUND_SQUARED = 1/3
    OPPOSITES = np.array([0, 3, 4, 1, 2, 7, 8, 5, 6])

class LatticeGrid:
    """
    Represents a lattice grid for Lattice Boltzmann Method (LBM) simulations.

    This class manages the distributions, macroscopic density, and macroscopic velocity
    for a 2D grid. - Generated by OpenAI's GPT 5.5
    """
    def __init__(self, width: int, height: int) -> None:
        """
        Initializes the lattice grid with the specified dimensions. - Generated by OpenAI's GPT 5.5

        :param width: Width of the grid.
        :param height: Height of the grid.
        """
        self._width = width
        self._height = height
        self._constants = D2Q9Constants()

        # distribution dans chacune des 9 directions dans chaque cellule (f_i)

        self._distributions = np.zeros((width, height, 9))
        for i in range(9):
            self._distributions[:, :, i] = self._constants.WEIGHTS[i]

        # Les densites dans chaque cellule (rho) (pas la mm chose que distributions)
        self._macro_density = np.zeros((width, height), dtype=np.float64)
        self._macro_velocity_x = np.zeros((width, height), dtype=np.float64)
        self._macro_velocity_y = np.zeros((width, height), dtype=np.float64)

        # print(self._distributions)

    def update_macroscopic(self) -> None:
        """
        Updates the macroscopic density and velocity based on current distributions. - Generated by OpenAI's GPT 5.5
        """
        self._macro_density = np.sum(self._distributions, axis=2)
        safe_density = np.where(self._macro_density == 0, 1.0, self._macro_density)
        self._macro_velocity_x = np.sum(self._distributions*self._constants.E_X, axis=2)/safe_density
        self._macro_velocity_y = np.sum(self._distributions*self._constants.E_Y, axis=2)/safe_density

        self.macro_velocity_x[self._macro_density == 0] = 0.0
        self.macro_velocity_y[self._macro_density == 0] = 0.0

    @property
    def distributions(self) -> np.ndarray:
        """
        Returns the current distributions (f_i) for each cell. - Generated by OpenAI's GPT 5.5
        """
        return self._distributions
    @distributions.setter
    def distributions(self, new_distributions: np.ndarray) -> None:
        """
        Sets new distributions for the grid. - Generated by OpenAI's GPT 5.5
        """
        self._distributions = new_distributions

    @property
    def macro_density(self) -> np.ndarray:
        """
        Returns the current macroscopic density (rho). - Generated by OpenAI's GPT 5.5
        """
        return self._macro_density
    @macro_density.setter
    def macro_density(self, new_macro_density: np.ndarray) -> None:
        """
        Sets a new macroscopic density for the grid. - Generated by OpenAI's GPT 5.5
        """
        self._macro_density = new_macro_density

    @property
    def macro_velocity_x(self) -> np.ndarray:
        """
        Returns the current macroscopic velocity in the X direction. - Generated by OpenAI's GPT 5.5
        """
        return self._macro_velocity_x
    @macro_velocity_x.setter
    def macro_velocity_x(self, new_macro_velocity_x: np.ndarray) -> None:
        """
        Sets a new macroscopic velocity in the X direction. - Generated by OpenAI's GPT 5.5
        """
        self._macro_velocity_x = new_macro_velocity_x

    @property
    def macro_velocity_y(self) -> np.ndarray:
        """
        Returns the current macroscopic velocity in the Y direction. - Generated by OpenAI's GPT 5.5
        """
        return self._macro_velocity_y
    @macro_velocity_y.setter
    def macro_velocity_y(self, new_macro_velocity_y: np.ndarray) -> None:
        """
        Sets a new macroscopic velocity in the Y direction. - Generated by OpenAI's GPT 5.5
        """
        self._macro_velocity_y = new_macro_velocity_y