import numpy as np
from scipy.ndimage import binary_erosion


class VectorObstacle:
    """
    Handles the rasterization and downsampling of continuous vector coordinates into a discrete boolean mask
    for the fluid simulation.

    Binds user-drawn canvas shapes to the underlying physics lattice. It manages the high-resolution reference
    grid, performs aggressive downsampling to match the simulation resolution, and applies morphological
    erosion to mitigate severe grid aliasing on curved boundaries.

    :ivar _initial_res: The absolute dimensions of the high-resolution reference canvas [width, height].
    :type _initial_res: list[int]
    :ivar _vertices: The raw [X, Y] coordinates defining the continuous perimeter of the shape.
    :type _vertices: np.ndarray
    :ivar _binary_mask: The finalized, downsampled boolean array used by the LBM collision operator.
    :type _binary_mask: np.ndarray | None
    :ivar _calculated_area: The exact number of active solid cells in the current grid.
    :type _calculated_area: float
    :ivar _reduction_factor: The scale ratio mapping the canvas resolution to the simulation lattice.
    :type _reduction_factor: float

    - Generated by Gemini
    """

    def __init__(self, initial_res: list[int] | None = None) -> None:
        """
        Initializes the obstacle bounds and allocates the internal state arrays.

        :param initial_res: The reference canvas dimensions [width, height]. Defaults to [1920, 1080].
        :type initial_res: list[int] | None

        - Generated by Gemini
        """
        if initial_res is None:
            initial_res = [1920, 1080]
        self._vertices: np.ndarray = np.array([])

        self._default_grid: np.ndarray | None = None
        self._initial_res: list[int] = initial_res
        self._reduction_factor: float = 0.2

        self._binary_mask: np.ndarray | None = None
        self._calculated_area: float = 0

        self._staircase_effect: bool = False

    def _update_binary_mask(self) -> None:
        """
        Downsamples the high-resolution reference grid to the target physical lattice scale.

        Snaps the current reduction factor to the nearest clean fractional multiplier to prevent
        sub-pixel tearing. The dense grid is blocked into chunks and evaluated using a fast boolean 'any'.
        Unless the staircase effect is toggled, a 2-pass binary erosion is applied to smooth out
        the resulting jagged aliasing artifacts.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._default_grid is None: return

        eligible_factors = [1.0, 0.5, 0.25, 0.2, 0.125]
        new_factor = min(eligible_factors, key = lambda x: abs(x - self._reduction_factor))

        target_width = int(new_factor * self._initial_res[0])
        target_height = int(new_factor * self._initial_res[1])

        # Calculate the actual factor
        factor = int(1 / new_factor)

        # Clean the grid to only keep the relevant part (removes the + 1 added under _update_default_grid)
        clean_height = target_height * factor
        clean_width = target_width * factor
        clean_grid = self._default_grid[:clean_width, :clean_height]

        # Downsampling
        downsampled = clean_grid.reshape(target_width, factor, target_height, factor).any(axis = (1, 3))
        if self._staircase_effect:
            self._binary_mask = downsampled.astype(bool)
        else:
            self._binary_mask = binary_erosion(downsampled, iterations = 2)

    def _update_default_grid(self) -> None:
        """
        Rasterizes the continuous vertex coordinates onto a dense, high-resolution boolean array.

        Zeros out the reference canvas and dynamically maps valid interior points to True.
        Automatically chains into the downsampling sequence to keep the physical mask perfectly synchronized.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        width = self._initial_res[0]
        height = self._initial_res[1]

        self._default_grid = np.zeros((width, height), dtype = bool)
        if self._vertices.size > 0:
            x_coords = self._vertices[:, 0]
            y_coords = self._vertices[:, 1]

            valid = (x_coords >= 0) & (x_coords < width) & (y_coords >= 0) & (y_coords < height)
            self._default_grid[x_coords[valid], y_coords[valid]] = True

        self._update_binary_mask()

    @property
    def vertices(self) -> np.ndarray:
        """
        Retrieves the raw coordinate array defining the perimeter of the shape.

        :return: A 2D array of [X, Y] integer coordinates.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        return self._vertices

    @vertices.setter
    def vertices(self, new_vertices: np.ndarray) -> None:
        """
        Injects a new geometry perimeter and forces a full rasterization update.

        :param new_vertices: The updated list of coordinate pairs.
        :type new_vertices: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._vertices = new_vertices
        self._update_default_grid()

    @property
    def binary_mask(self) -> np.ndarray | None:
        """
        Retrieves the finalized, simulation-ready boolean mask matrix.

        :return: The 2D logical mapping of solid boundary cells.
        :rtype: np.ndarray | None

        - Generated by Gemini
        """
        return self._binary_mask

    @property
    def reduction_factor(self) -> float:
        """
        Retrieves the resolution scaling ratio between the canvas and the physics lattice.

        :return: The active reduction factor decimal.
        :rtype: float

        - Generated by Gemini
        """
        return self._reduction_factor

    @reduction_factor.setter
    def reduction_factor(self, new_factor: float) -> None:
        """
        Adjusts the simulation grid scale and triggers an immediate downsampling recalculation.

        :param new_factor: The decimal target for resolution reduction.
        :type new_factor: float
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._reduction_factor = new_factor
        self._update_binary_mask()

    @property
    def initial_res(self) -> list[int]:
        """
        Retrieves the absolute pixel dimensions of the high-resolution reference canvas.

        :return: The canvas bounding limits as [width, height].
        :rtype: list[int]

        - Generated by Gemini
        """
        return self._initial_res

    @initial_res.setter
    def initial_res(self, new_res: list[int] | tuple[int, int]) -> None:
        """
        Updates the coordinate limits of the reference canvas and forces a grid redraw.

        :param new_res: The new maximum [width, height] boundary.
        :type new_res: list[int] | tuple[int, int]
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._initial_res = list(new_res)
        self._update_default_grid()

    @property
    def staircase_effect(self) -> bool:
        """
        Checks if anti-aliasing (erosion) is currently bypassed on the obstacle boundaries.

        :return: True if voxel-like rigid stepping is active.
        :rtype: bool

        - Generated by Gemini
        """
        return self._staircase_effect

    @staircase_effect.setter
    def staircase_effect(self, new_state: bool) -> None:
        """
        Toggles the morphological erosion smoothing and recomputes the active grid.

        :param new_state: True to enforce raw voxel blocks, False to smooth aliases.
        :type new_state: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._staircase_effect = new_state
        self._update_default_grid()