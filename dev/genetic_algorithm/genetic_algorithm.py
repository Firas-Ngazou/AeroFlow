class GeneticAlgorithm(QObject):
    """
    Orchestrates the evolutionary optimization loop for our aerodynamic profiles.

    We use this class to iteratively mutate and cross-breed airfoil vertices, evaluating
    their fitness against targeted lift or drag coefficients using NeuralFoil. It runs
    on a dedicated thread to prevent the main UI from locking up during heavy generations,
    emitting progress signals as the population evolves.
    - Generated by Gemini.
    """
    iterationCompleted = Signal(np.ndarray, int, float)
    optimizationCompleted = Signal()
    aeroGainUpdated = Signal(float)
    projectedDragUpdated = Signal(float)
    projectedLiftUpdated = Signal(float)

    def __init__(self) -> None:
        """
        Bootstraps the genetic algorithm with baseline hyperparameters.

        These default values dictate the aggressiveness of our mutation engine and the
        size of the gene pool. They are typically overridden by the user via the UI
        before starting a new optimization pass.
        - Generated by Gemini.
        """
        super().__init__()
        self._max_iterations: int = 100
        self._threshold: float = 0.1
        self._constraint_method: str = "SURFACE"
        self._constraint_target: str = "TRAÎNÉ"

        self._population: int = 20
        self._mutation_rate: float = 0.05
        self._magnitude: float = 1.0
        self._type: str = "MAXIMIZE"

        self._estimated_drag: float | None = None
        self._estimated_lift: float | None = None
        self._initial_coef: float | None = None

        self._current_population: list[np.ndarray] = []
        self._best_data: dict = {}
        self._base = None

    def optimize(self, vertices: np.ndarray) -> None:
        """
        Kicks off the main evolutionary loop to optimize a given set of airfoil vertices.

        We capture the baseline aerodynamic coefficient, seed the initial population,
        and run through the specified number of generations. The fittest individual
        dictates the UI updates emitted at the end of every generation cycle.
        - Generated by Gemini.

        :param vertices: The 2D array of coordinates defining our starting airfoil geometry.
        :type vertices: np.ndarray
        """
        self._base = np.copy(vertices)
        self.__initialize_population()

        match self.target:
            case "TRAÎNÉ":
                self._initial_coef = self._get_drag_coefficient(self._base)
            case "PORTANCE":
                self._initial_coef = self._get_lift_coefficient(self._base)
            case _:
                raise ValueError(f"Invalid target: {self.target}")

        for it in range(self.iterations):
            fitness_list: list[float] = []

            for ind in self._current_population:
                fitness = self.__evaluate_fitness(ind)
                fitness_list.append(fitness)

            new_population = self.__generate_new_population(fitness_list)
            self._current_population = new_population

            best_fitness = max(fitness_list)
            best_verts = self._best_data.get("Vertices", self._base)
            best_drag = self._best_data.get("Drag", None)
            best_lift = self._best_data.get("Lift", None)
            best_gain = self._best_data.get("Gain", None)

            self.iterationCompleted.emit(best_verts, it, best_fitness)
            if best_gain is not None:
                self.aeroGainUpdated.emit(best_gain)

            if best_drag is not None:
                self.projectedDragUpdated.emit(best_drag)
            if best_lift is not None:
                self.projectedLiftUpdated.emit(best_lift)

            QThread.current_thread().msleep(50)

        self.optimizationCompleted.emit()

    def __initialize_population(self) -> None:
        """
        Seeds the first generation of our genetic pool.

        We generate exact structural clones of the base geometry and apply standard
        mutations to scatter them across the initial search space, preparing them for
        the upcoming fitness evaluations.
        - Generated by Gemini.

        :param base: The unadulterated starting geometry coordinates.
        """
        self._current_population = []
        for _ in range(self.population):
            mutated = self.__generate_mutation(self._base)
            self._current_population.append(mutated)

    def __generate_new_population(self, fitness_list: list[float]) -> list[np.ndarray]:
        """
        Breeds the next generation of airfoils based on the survival of the fittest.

        We select two parents based on their aerodynamic viability, cross their genetic
        geometry matrices, and occasionally induce random structural noise (mutation)
        to ensure we don't get trapped in a local minimum.
        - Generated by Gemini.

        :param fitness_list: A sequential list of fitness scores mapping to the current population.
        :type fitness_list: list[float]
        :return: The freshly bred array of mutated geometry nodes.
        :rtype: list[np.ndarray]
        """
        new_population: list[np.ndarray] = []
        for _ in range(self.population):
            parent_a_index = self._select_parent(fitness_list)
            parent_b_index = self._select_parent(fitness_list)

            parent_a = self._current_population[parent_a_index]
            parent_b = self._current_population[parent_b_index]

            child = self.__crossover(parent_a, parent_b)
            mutated_child = self.__generate_mutation(child)
            new_population.append(mutated_child)

        return new_population

    @staticmethod
    def _select_parent(fitness_list: list[float]) -> int:
        """
        Picks a valid parent candidate using a weighted roulette wheel selection.

        To prevent mathematical implosions from invalid geometries yielding infinite or NaN
        scores, we sanitize the weights to a strictly positive floor before selection.
        - Generated by Gemini.

        :param fitness_list: The raw fitness scores for the pool.
        :type fitness_list: list[float]
        :return: The index of the selected parent within the population array.
        :rtype: int
        """
        safe_weights: list[float] = []

        for score in fitness_list:
            if math.isfinite(score):
                safe_weights.append(max(0.0001, score))
            else:
                safe_weights.append(0.0001)

        parent_index = random.choices(population = list(range(len(fitness_list))), weights = safe_weights, k = 1)[0]

        return parent_index

    @staticmethod
    def _get_drag_coefficient(vertices: np.ndarray) -> float:
        """
        Extracts the explicit drag coefficient (CD) from the neural solver.
        - Generated by Gemini.

        :param vertices: The geometry to test.
        :type vertices: np.ndarray
        :return: The calculated drag value.
        :rtype: float
        """
        data = GeneticAlgorithm._get_airfoil_data(vertices)
        return data["CD"].item()

    @staticmethod
    def _get_lift_coefficient(vertices: np.ndarray) -> float:
        """
        Extracts the explicit lift coefficient (CL) from the neural solver.
        - Generated by Gemini.

        :param vertices: The geometry to test.
        :type vertices: np.ndarray
        :return: The calculated lift value.
        :rtype: float
        """
        data = GeneticAlgorithm._get_airfoil_data(vertices)
        return data["CL"].item()

    @staticmethod
    def _get_airfoil_data(vertices: np.ndarray) -> dict[str, np.ndarray]:
        """
        Feeds the raw coordinates into AeroSandbox's NeuralFoil engine.

        We suppress warnings here because the neural network often complains about
        heavy geometric self-intersections during the more volatile mutation phases,
        which we handle structurally anyway. We test at a fixed Alpha of 5.0 and Mach 0.1.
        - Generated by Gemini.

        :param vertices: The geometric node map of the airfoil.
        :type vertices: np.ndarray
        :return: A dictionary payload containing the aero coefficients.
        :rtype: dict[str, np.ndarray]
        """
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")

            current_airfoil = asb.Airfoil(name = "GA_Airfoil", coordinates = vertices)
            alpha = 5.0
            re = 1e6
            mach = 0.1

            return current_airfoil.get_aero_from_neuralfoil(alpha = alpha, Re = re, mach = mach)

    def __generate_mutation(self, vertices: np.ndarray) -> np.ndarray:
        """
        Applies vertical scatter to the geometry's Y-coordinates based on our mutation rates.

        If the genetic noise results in an impossible or highly invalid aerodynamic shape
        (e.g., crossing constraints), we discard the mutation and return the original shape
        to maintain pool stability.
        - Generated by Gemini.

        :param vertices: The original structural matrix.
        :type vertices: np.ndarray
        :return: The structurally shifted matrix, or the original if the mutation was lethal.
        :rtype: np.ndarray
        """
        mutated = np.copy(vertices)

        if random.random() < self.mutation_rate:
            y_noise = np.random.uniform(low = -self.magnitude, high = self.magnitude, size = len(vertices))
            mutated[:, 1] = mutated[:, 1] + y_noise
            valid = self._validate(mutated)

            if not valid:
                return vertices

        return mutated

    @staticmethod
    def __crossover(parent_a: np.ndarray, parent_b: np.ndarray) -> np.ndarray:
        """
        Splices two parental geometries together to create a hybrid child.

        We run a 50/50 probability mask across the Y-coordinates, picking structural
        traits uniformly from either parent to ensure a diverse crossover.
        - Generated by Gemini.

        :param parent_a: First geometry matrix.
        :type parent_a: np.ndarray
        :param parent_b: Second geometry matrix.
        :type parent_b: np.ndarray
        :return: The resulting child matrix.
        :rtype: np.ndarray
        """
        child = np.copy(parent_a)

        mask = np.random.rand(len(parent_a)) < 0.5
        child[mask, 1] = parent_b[mask, 1]

        return child

    def __evaluate_fitness(self, individual: np.ndarray) -> float:
        """
        Grades the aerodynamic viability of a single profile.

        Geometries that violate our physical constraints (like area or bounding limits)
        are immediately killed off with a fitness of 0.0. Valid shapes are evaluated
        against the target metric (Lift or Drag), and the best historical performer is cached.
        - Generated by Gemini.

        :param individual: The candidate geometry.
        :type individual: np.ndarray
        :return: The calculated fitness score.
        :rtype: float
        """
        valid = self._validate(individual)
        if not valid:
            return 0.0

        drag: float | None = None
        lift: float | None = None

        match self.target:
            case "TRAÎNÉ":
                drag = self._get_drag_coefficient(individual)
            case "PORTANCE":
                lift = self._get_lift_coefficient(individual)
            case _:
                raise ValueError(f"Invalid target: {self.target}")

        def get_fitness(coef: float, name: str) -> float:
            match self.type:
                case "MINIMUM":
                    if self._best_data.get(name, None) is None or coef < self._best_data[name]:
                        self._update_best_data(individual, coef, name)
                    result = 1.0 / (coef + 0.01)
                case "MAXIMUM":
                    if self._best_data.get(name, None) is None or coef > self._best_data[name]:
                        self._update_best_data(individual, coef, name)
                    result = coef
                case _:
                    raise ValueError(f"Invalid type: {self.type}")
            return result

        if drag is not None:
            fitness = get_fitness(drag, "Drag")
        elif lift is not None:
            fitness = get_fitness(lift, "Lift")
        else:
            raise ValueError("Neither drag nor lift provided for fitness calculation")

        return fitness

    def _update_best_data(self, individual: np.ndarray, coef: float, name: str) -> None:
        """
        Caches the globally best-performing individual from the entire run.

        This saves us from having to recalculate geometry and performance gains when
        broadcasting the final optimum back to the UI.
        - Generated by Gemini.

        :param individual: The geometry matrix of the champion.
        :type individual: np.ndarray
        :param coef: The raw target aerodynamic coefficient achieved.
        :type coef: float
        :param name: The identifier key (e.g., "Drag" or "Lift").
        :type name: str
        """
        self._best_data["Vertices"] = individual
        self._best_data[name] = coef
        self._best_data["Gain"] = self._get_aerodynamic_gain(coef)

    def _validate(self, individual: np.ndarray) -> bool:
        """
        Gatekeeps the geometry based on our selected structural constraints.

        We route the individual matrix through either surface area constraints or
        point-distance bounds depending on the active optimization strategy.
        - Generated by Gemini.

        :param individual: The geometry to test.
        :type individual: np.ndarray
        :return: True if the shape abides by physics, False if it breaks them.
        :rtype: bool
        """
        match self.constraint_method:
            case "SURFACE":
                verdict = self.__verify_area(individual)
            case "DISTANCE":
                verdict = self.__verify_distance(individual)
            case _:
                raise ValueError(f"Invalid constraint method: {self.constraint_method}")

        return verdict

    @staticmethod
    def __calculate_polygon_area(vertices: np.ndarray) -> float:
        """
        Calculates the area of a polygon given its vertices.
        - Generated by Gemini.

        :param vertices: The vertices of the polygon.
        :type vertices: np.ndarray
        :return: The area of the polygon.
        :rtype: float
        """
        x = vertices[:, 0]
        y = vertices[:, 1]
        return 0.5 * np.abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))

    def __verify_distance(self, vertices: np.ndarray) -> bool:
        """
        Validates that the shifted points don't violate distance-based collision constraints.
        - Generated by Gemini.

        :param vertices: The points to test.
        :type vertices: np.ndarray
        :return: Safety boolean state.
        :rtype: bool
        """
        if self.constraint_method != "DISTANCE" or self._base is None:
            return True

        max_deviation = np.max(np.abs(self._base - vertices))
        return max_deviation <= self.threshold

    def __verify_area(self, vertices: np.ndarray) -> bool:
        """
        Validates that the mutated shape doesn't expand or contract beyond our allowable area variance.
        - Generated by Gemini.

        :param vertices: The geometry to test.
        :type vertices: np.ndarray
        :return: Safety boolean state.
        :rtype: bool
        """
        if not self.constraint_method == "SURFACE":
            return True
        
        old_area = self.__calculate_polygon_area(self._base)
        new_area = self.__calculate_polygon_area(vertices)

        if old_area == 0:
            old_area = 1.0

        relative_difference = abs(old_area - new_area) / old_area
        return relative_difference <= self.threshold # Keeps a surface relative to the inital shape

    def _get_aerodynamic_gain(self, coef: float) -> float:
        """
        Calculates the percentage improvement of the new coefficient over the baseline start.

        Helps us visualize if the GA is actually climbing a gradient or stagnating.
        - Generated by Gemini.

        :param coef: The coefficient generated by the current generation.
        :type coef: float
        :return: The mathematical percentage gain or loss.
        :rtype: float
        """
        if abs(self._initial_coef) < 1e-9 or abs(coef) < 1e-9:
            return 0.0

        if self.type == "MAXIMUM":
            gain = (coef - self._initial_coef) / abs(self._initial_coef)
        elif self.type == "MINIMUM":
            gain = (self._initial_coef - coef) / abs(self._initial_coef)
        else:
            raise ValueError(f"Invalid optimization type: {self.type}")

        return gain

