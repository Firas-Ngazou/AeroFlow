    #region Painting Events
    def paintEvent(self, event: QPaintEvent) -> None:
        """
        Handles the paint event for rendering the widget.

        This method is invoked when the widget needs to be repainted. It uses a
        QPainter to render the widget's visual elements, including the cached grid,
        shapes, and selection rectangles. The method ensures efficient drawing
        by leveraging the cached grid if available and performing additional
        rendering as needed. - Generated by Claude Haiku 4.5

        :param event: The paint event passed by the Qt event system.
        :type event: QPaintEvent
        :return: None
        """
        painter = QPainter(self)

        if self._cached_grid is not None:
            painter.drawPixmap(0, 0, self._cached_grid)

        self._draw_shapes(painter)
        self._draw_selection_rects(painter)

        painter.end()

    def resizeEvent(self, event: QResizeEvent) -> None:
        """
        Handles the resize event to adjust the layout and reposition shapes.

        This function responds to the resize event by first redrawing the grid
        and then calculating the horizontal and vertical differences in size.
        These differences are used to reposition each shape on the canvas by
        translating them accordingly.

        Note: The translation logic might introduce slight displacement due
        to integer division of the deltas during resizing. - Generated by Claude Haiku 4.5

        :param event: The resize event containing the new size and the old size.
            It supports accessing width and height through `size()` and
            `oldSize()` methods, respectively.
            (Requires `isValid()` to verify valid old size.)
        :type event: QResizeEvent
        """
        self._draw_grid()

        if not event.oldSize().isValid(): return

        delta_width = event.size().width() - event.oldSize().width()
        delta_height = event.size().height() - event.oldSize().height()

        delta_x = delta_width // 2
        delta_y = delta_height // 2

        # When resizing to many times, since it gets the // of the deltas, the shapes do move a little bit more than
        # they should. Meh... Ig it's fine.
        for shape in self._shapes:
            shape.translate(delta_x, delta_y)
        if len(self._shapes) >= 1: self._on_vertices_changed()

    def _draw_grid(self) -> None:
        """
        Draws a grid on a cached pixmap with specified colors and line styles.

        This method generates a cached grid based on the widget's current
        dimensions. It initializes the background color, sets up the pen styles
        for primary and secondary grid lines, and renders the grid lines using
        the QPainter object. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._cached_grid = QPixmap(self.size())
        background_color = QColor(34, 34, 34)
        self._cached_grid.fill(background_color)
        painter = QPainter(self._cached_grid)

        left = self.rect().left()
        right = self.rect().right()
        top = self.rect().top()
        bottom = self.rect().bottom()
        x = left
        y = top

        primary_pen = QPen(QColor(75, 75, 75, 75))
        primary_pen.setWidth(2)
        secondary_pen = QPen(QColor(75, 75, 75, 25))
        secondary_pen.setWidth(2)

        painter.setPen(primary_pen)
        self._draw_lines(painter, x, y, top, bottom, left, right)

        x = int(left + self._cell_width/2)
        y = int(top + self._cell_width/2)

        painter.setPen(secondary_pen)
        self._draw_lines(painter, x, y, top, bottom, left, right)

        painter.end()

    def _draw_lines(self, painter: QPainter, x: int, y: int,
                    top: int, bottom: int, left: int, right: int) -> None:
        """
        Draws a grid of vertical and horizontal lines within the specified boundaries.

        The method iteratively draws vertical lines within the range defined by `x` and
        `right`, incrementing by `_cell_width`, and horizontal lines within the range
        defined by `y` and `bottom`, incrementing by `_cell_width`. The drawing is
        performed using the provided QPainter instance. - Generated by Claude Haiku 4.5

        :param painter: QPainter instance responsible for rendering the lines.
        :param x: Starting X-coordinate for vertical lines.
        :param y: Starting Y-coordinate for horizontal lines.
        :param top: Y-coordinate of the top boundary for vertical lines.
        :param bottom: Y-coordinate of the bottom boundary for vertical and horizontal lines.
        :param left: X-coordinate of the left boundary for horizontal lines.
        :param right: X-coordinate of the right boundary for vertical and horizontal lines.
        :return: None
        """
        while x < right: # (Vertical lines)
            painter.drawLine(x, top, x, bottom)
            x += self._cell_width
        while y < bottom: # (Horizontal lines)
            painter.drawLine(left, y, right, y)
            y += self._cell_width

    def _draw_shapes(self, painter: QPainter) -> None:
        """
        Draws all the shapes contained within the collection onto the provided
        painter. This method iterates through the internal collection of shapes
        and invokes their respective draw methods. - Generated by Claude Haiku 4.5

        :param painter: The QPainter instance used to render the shapes.
        :type painter: QPainter
        """
        for shape in self._shapes:
            shape.draw(painter)

    def _draw_selection_rects(self, painter: QPainter) -> None:
        """
        Draws selection rectangles with specific visuals depending on user interaction.

        This method handles the rendering of selection rectangles based on different
        states of user interaction. If the user is holding down the control key, the
        selection rectangle will have a red outline, indicating a delete action.
        Otherwise, it will have a blue outline for selecting elements. Additionally,
        it draws white rectangular highlights around selected vertices when no active
        selection is being made. - Generated by Claude Haiku 4.5

        :param painter: The QPainter object used to render the selection rectangles.
        :type painter: QPainter
        """
        if self._selecting_rect is not None:

            # Red rect if the user is holding down the ctrl key
            if self._state_manager.key_state == QStateManager.KeyState.HOLDING_CTRL:
                painter.setPen(self._deleting_rect_pen)
                painter.setBrush(self._deleting_rect_brush)

            # Blue rect if the user is not holding down the ctrl key
            else:
                painter.setPen(self._selecting_rect_pen)
                painter.setBrush(self._selection_rect_brush)
            painter.drawRect(self._selecting_rect)

        # White rect around the selected vertices
        elif self._selected_rect is not None:
            painter.setPen(self._selected_rect_pen)
            painter.setBrush(Qt.BrushStyle.NoBrush)
            painter.drawRect(self._selected_rect)

    #endregion

    #region Input Events
    def mouseMoveEvent(self, event: QMouseEvent, /) -> None:
        """
        Handles a mouse move event and updates the application's state based on the cursor
        location and the current interaction state. This includes detecting the mouse position
        relative to shapes, vertices, and selection rectangles, and performing appropriate
        actions according to the application's state manager. - Generated by Claude Haiku 4.5

        :param event: The mouse move event containing information about the current cursor
            position and movement.
        :type event: QMouseEvent
        :return: None
        """
        match self._state_manager.cursor_state:
            case QStateManager.CursorState.LOCKED:
                return
            case QStateManager.CursorState.DEFAULT:
                position = event.position().toPoint()

                if self._current_shape is None:
                    self._state_manager.mouse_location = QStateManager.MouseLocation.DEFAULT
                    if not self._state_manager.action_state == QStateManager.ActionState.SELECTING_VERTICES:
                        self._nearest_shape = None

                        for shape in self._shapes:

                            # Mouse is hovering over a shape
                            if shape.is_over_shape(position):
                                self._state_manager.mouse_location = QStateManager.MouseLocation.OVER_SHAPE
                                self._nearest_shape = shape

                        # Highlight the last shape that was detected as hovered
                        if self._nearest_shape is not None: self._nearest_shape.highlight()
                    elif self._state_manager.key_state == QStateManager.KeyState.HOLDING_CTRL:
                        # Mouse is selecting shapes to delete
                        self._shapes_to_remove = None
                        if self._selecting_rect is not None:
                            for shape in self._shapes:
                                if shape.is_in_delete_rect(self._selecting_rect):
                                    if self._shapes_to_remove is not None:
                                        self._shapes_to_remove.append(shape)
                                    else:
                                        self._shapes_to_remove = [shape]
                                    shape.highlight(for_deletion=True)

                            self._selecting_rect.setBottomRight(position)

                    self.update()
                    return

                # Mouse buttons are not pressed
                if self._state_manager.mouse_state == QStateManager.MouseState.DEFAULT:
                    near_vertex = self._current_shape.near_vertex(position)

                    # Mouse is hovering over a vertex
                    if near_vertex is not None:
                        self._state_manager.mouse_location = QStateManager.MouseLocation.OVER_VERTEX
                        self._current_shape.hover_vertex(near_vertex)

                    # Mouse is not hovering over a vertex
                    else:
                        self._state_manager.mouse_location = QStateManager.MouseLocation.DEFAULT
                        if self._selected_rect is None: self._current_shape.update_near_median(position)
                        self._current_shape.reset_hovered_vertices()

                # Mouse left button is pressed
                elif self._state_manager.mouse_state == QStateManager.MouseState.HOLDING_MB1:

                    # Mouse is moving a vertex
                    if self._state_manager.action_state == QStateManager.ActionState.MOVING_VERTEX:
                        self._current_shape.move_held_vertices_to_point(position)

                    # Mouse is moving vertices
                    elif self._state_manager.action_state == QStateManager.ActionState.MOVING_VERTICES:
                        self._current_shape.move_held_vertices(position.x() - self._select_start_pos.x(),
                                                               position.y() - self._select_start_pos.y())
                        self._select_start_pos = position
                        self._update_selected_rect()

                    # Mouse is selecting vertices
                    elif self._state_manager.action_state == QStateManager.ActionState.SELECTING_VERTICES:
                        self._selecting_rect.setBottomRight(position)
                        self._current_shape.select_content(self._selecting_rect)

            case QStateManager.CursorState.PEN:
                ...

        self.update()

    def mousePressEvent(self, event: QMouseEvent, /) -> None:
        """
        Handles mouse press events and performs various actions depending on the current state of
        the cursor, key modifier, and mouse location. Based on the state, this method allows interacting
        with geometric shapes (creating, selecting, moving, or modifying shapes and vertices) or
        initiating specific selection modes (e.g., rectangle selection). - Generated by Claude Haiku 4.5

        :param event: The mouse press event that contains information about the mouse button pressed,
                      its position, and other contextual details.
        :type event: QMouseEvent
        :return: None
        """

        match self._state_manager.cursor_state:
            case QStateManager.CursorState.LOCKED:
                return
            case QStateManager.CursorState.DEFAULT:
                if event.button() == Qt.MouseButton.LeftButton:
                    position = event.position().toPoint()

                    if self._current_shape is None:

                        # Mouse is hovering over a shape, we select it
                        if self._state_manager.mouse_location == QStateManager.MouseLocation.OVER_SHAPE:
                            self._state_manager.action_state = QStateManager.ActionState.DEFAULT
                            self._current_shape = self._nearest_shape
                            self._current_shape.select_path()

                        # Mouse is not hovering over a shape, we start the building of the selecting rect
                        elif (self._state_manager.mouse_location == QStateManager.MouseLocation.DEFAULT and
                              self._state_manager.key_state == QStateManager.KeyState.HOLDING_CTRL):
                            self._state_manager.action_state = QStateManager.ActionState.SELECTING_VERTICES
                            self._selecting_rect = QRect(position, position)
                        return

                    # Mouse left button is pressed
                    self._state_manager.mouse_state = QStateManager.MouseState.HOLDING_MB1

                    # Mouse left button was pressed while over a vertex
                    if self._current_shape.near_vertex(position) is not None:
                        self._state_manager.action_state = QStateManager.ActionState.MOVING_VERTEX
                        unselect_others = self._state_manager.key_state != QStateManager.KeyState.HOLDING_SHIFT
                        self._current_shape.hold_vertex(self._current_shape.near_vertex(position),
                                                        unselect_others=unselect_others)

                    # Mouse left button was pressed while over a selection rectangle
                    elif self._selected_rect is not None and self._selected_rect.contains(position):
                        self._state_manager.action_state = QStateManager.ActionState.MOVING_VERTICES
                        self._current_shape.hold_selection()
                        self._select_start_pos = position # Updates the position of the start of the delta (type shi)

                    # Mouse left button was pressed while near a median vertex
                    elif self._current_shape.current_median is not None:
                        self._current_shape.add_median_vertex()
                        self._on_vertices_changed()

                    # Mouse left button was pressed while floating
                    else:
                        self._state_manager.action_state = QStateManager.ActionState.SELECTING_VERTICES
                        if not self._state_manager.key_state == QStateManager.KeyState.HOLDING_SHIFT:
                            self._current_shape.reset_selected_vertices() # Unselect all currently selected vertices
                        self._selecting_rect = QRect(position, position) # The blue rectangle thing (or red for delete)

            case QStateManager.CursorState.PEN:
                if event.button() == Qt.MouseButton.LeftButton:
                    position = event.position().toPoint()
                    if self._current_shape is None:
                        # Making a new shape
                        self._shapes.append(Shape([Vertex(position=position, state=Vertex.VertexState.SELECTED,
                                                          index_position=0)]))
                        self._current_shape = self._shapes[-1]
                    else:
                        # Adding a point to the current shape
                        near_vertex = self._current_shape.near_vertex(position)
                        if near_vertex is not None and near_vertex.index_position == 0:
                            self._exit_current_shape()
                        elif near_vertex is None:
                            self._current_shape.add_point(position)
                            self._on_vertices_changed()

        self.update()

    def mouseReleaseEvent(self, event: QMouseEvent, /) -> None:
        """
        Handles the mouse release event for the current application state.

        This method updates the application's behavior and state based on the mouse
        button released and the current cursor and key states. If the cursor is in
        the LOCKED state, no action is performed. Depending on the cursor's state
        (DEFAULT or other states like PEN), specific logic handles behaviors such as
        selection, deselection, and deletion of shapes or vertices. The method also
        updates the corresponding state within the state manager and the view. - Generated by Claude Haiku 4.5

        :param event: A QMouseEvent instance representing the mouse release event.
        :type event: QMouseEvent
        :return: None
        """
        match self._state_manager.cursor_state:
            case QStateManager.CursorState.LOCKED:
                return
            case QStateManager.CursorState.DEFAULT:
                if event.button() == Qt.MouseButton.LeftButton:

                    # Mouse left button was released
                    self._selecting_rect = None
                    if self._current_shape is not None:
                        self._current_shape.release_all()
                        self._on_vertices_changed()
                    if self._state_manager.key_state != QStateManager.KeyState.HOLDING_CTRL:
                        self._update_selected_rect()
                    elif self._current_shape is not None:
                        # Deleting selection
                        self._selected_rect = None
                        self._current_shape.delete_selected_vertices()
                        self._on_vertices_changed()
                        if not self._current_shape.vertices:
                            self._shapes.remove(self._current_shape)
                            self._current_shape = None
                    else:
                        # Deleting a shape
                        self._selected_rect = None
                        if self._shapes_to_remove is not None:
                            for shape in self._shapes_to_remove:
                                self._shapes.remove(shape)
                                self._on_vertices_changed()

                    self._state_manager.mouse_state = QStateManager.MouseState.DEFAULT
                    self._state_manager.action_state = QStateManager.ActionState.DEFAULT

            case QStateManager.CursorState.PEN:
                ...

        self.update()

    def keyPressEvent(self, event: QKeyEvent, /) -> None:
        """
        Handles key press events and updates the internal state or executes actions
        depending on the current cursor, key, and action states. - Generated by Claude Haiku 4.5

        :param event: The key press event being processed.
        :type event: QKeyEvent
        :return: None
        """
        match self._state_manager.cursor_state:
            case QStateManager.CursorState.LOCKED:
                return
            case QStateManager.CursorState.DEFAULT:
                if event.key() == Qt.Key.Key_Control:
                    self._state_manager.key_state = QStateManager.KeyState.HOLDING_CTRL
                elif event.key() == Qt.Key.Key_Shift:
                    self._state_manager.key_state = QStateManager.KeyState.HOLDING_SHIFT

                if (self._current_shape is not None and
                        self._state_manager.action_state == QStateManager.ActionState.DEFAULT):
                    # Shortcuts
                    if event.key() == Qt.Key.Key_A: self._current_shape.select_all()
                    if event.key() == Qt.Key.Key_Backspace or event.key() == Qt.Key.Key_Delete:
                        self._current_shape.delete_selected_vertices()
                        self._on_vertices_changed()

        if event.key() == Qt.Key.Key_Escape and self._current_shape is not None: self._exit_current_shape()
        if self._current_shape is not None and len(self._current_shape.vertices) < 1: self._exit_current_shape()

        self._update_selected_rect()
        self.update()

    def keyReleaseEvent(self, event: QKeyEvent, /) -> None:
        """
        Handles key release events to adjust the internal state of the cursor and key bindings.

        This method processes key release events and is responsible for updating the
        key and cursor state of the application. Depending on the current cursor state
        managed by the `_state_manager`, appropriate actions are taken. If the cursor
        state is `LOCKED`, the method will terminate early without making any changes.
        For the `DEFAULT` cursor state, the method evaluates the released key and
        updates the key state if the released key matches specific keys (e.g.,
        `CONTROL` or `SHIFT`). - Generated by Claude Haiku 4.5

        :param event: The key release event being processed.
        :type event: QKeyEvent
        :return: None
        """
        match self._state_manager.cursor_state:
            case QStateManager.CursorState.LOCKED:
                return
            case QStateManager.CursorState.DEFAULT:
                if event.key() == Qt.Key.Key_Control or event.key() == Qt.Key.Key_Shift:
                    self._state_manager.key_state = QStateManager.KeyState.DEFAULT

    #endregion

    def switch_cursor(self, cursor_state: QStateManager.CursorState) -> None:
        """
        Switches the cursor to a specified state and resets state manager attributes to their default
        values. It also clears current shapes and triggers an update if necessary. - Generated by Claude Haiku 4.5

        :param cursor_state: The target cursor state to switch to.
        :type cursor_state: QStateManager.CursorState
        :return: None
        """
        self._selecting_rect = None
        self._selected_rect = None

        self._state_manager.action_state = QStateManager.ActionState.DEFAULT
        self._state_manager.mouse_state = QStateManager.MouseState.DEFAULT
        self._state_manager.mouse_location = QStateManager.MouseLocation.DEFAULT
        self._state_manager.key_state = QStateManager.KeyState.DEFAULT

        if self._current_shape is not None and cursor_state == QStateManager.CursorState.PEN:
            self._exit_current_shape()

        match cursor_state:
            case QStateManager.CursorState.LOCKED:
                ...
            case QStateManager.CursorState.DEFAULT:
                self.setCursor(Qt.CursorShape.ArrowCursor)
            case QStateManager.CursorState.PEN:
                self.setCursor(self._pen_cursor)

        self.update()

    def _update_selected_rect(self) -> None:
        """
        Updates the rectangular region enclosing the currently selected vertices of
        a shape. This method calculates the smallest `QRect` that entirely contains
        the selected vertices of the active shape, if any are selected. If fewer
        than two vertices are selected, the enclosing rectangle is set to `None`. - Generated by Claude Haiku 4.5

        :return: None
        """
        if self._current_shape is None: return
        selected = self._current_shape.selected_vertices
        if not len(selected) > 1:
            self._selected_rect = None
            return

        highest = selected[0].position.y()
        lowest = selected[0].position.y()
        farthest_right = selected[0].position.x()
        farthest_left = selected[0].position.x()

        for vertex in selected:
            if vertex.position.y() < highest: highest = vertex.position.y()
            if vertex.position.y() > lowest: lowest = vertex.position.y()
            if vertex.position.x() > farthest_right: farthest_right = vertex.position.x()
            if vertex.position.x() < farthest_left: farthest_left = vertex.position.x()

        self._selected_rect = QRect(farthest_left, highest, farthest_right - farthest_left, lowest - highest)

    def _exit_current_shape(self) -> None:
        """
        Finalizes the current shape editing process, unselecting the current path,
        resetting the current shape to None, and updating the state manager to its
        default action, mouse, and cursor states. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._current_shape.unselect_path()
        self._current_shape = None

        self._state_manager.action_state = QStateManager.ActionState.DEFAULT
        self._state_manager.mouse_state = QStateManager.MouseState.DEFAULT
        self._state_manager.cursor_state = QStateManager.CursorState.DEFAULT

    def _on_vertices_changed(self):
        """
        Handles updates to the vertices of shapes and emits an event with the
        concatenated vertex data. This method collects all vertex data from the
        associated shapes into a single array and triggers the event to notify
        of changes. - Generated by Claude Haiku 4.5

        :return: None
        """
        vertices = np.empty((0, 2), dtype=int)
        for shape in self._shapes:
            vertices = np.concatenate((vertices, shape.get_pixel_data(self.width(), self.height())), axis=0)

        self.vectorDrawingChanged.emit(vertices)


