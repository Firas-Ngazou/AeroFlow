class AeroFlow:
    """
    Manages the core lifecycle, UI routing, and state transitions of the AeroFlow application.

    This class serves as the main application controller. It initializes the primary frameless window,
    handles the routing between the home dashboard and active project views, and manages
    underlying resources such as title bars and layouts. It directly bridges UI interactions
    with the underlying ProjectManager to orchestrate the creation and loading of project files.
    - Generated by Gemini.

    :ivar splash_screen: The initial splash screen to close upon successful application load.
    :type splash_screen: QSplashScreen | None
    """

    def __init__(self, splash_screen: QSplashScreen | None = None) -> None:
        self._window = FramelessWindow()
        self._window.resize(1920, 1080)

        self._home_page_title_bar: TitleBar | None = None
        self._project_page_title_bar: TitleBar | None = None

        self._stack = QStackedWidget(self._window)

        self._home_page = HomePage(self._window)
        self._stack.add_widget(self._home_page)

        self._project_page: ProjectPage | None = None
        self._project_manager = ProjectManager(self._window)
        self._project_manager.home_page = self._home_page

        self._primary_layout = QHBoxLayout(self._window)
        self._primary_layout.spacing = 0
        self._primary_layout.set_contents_margins(0, 32, 0, 0)
        self._primary_layout.add_widget(self._stack)

        self._home_page.newProjectPressed.connect(self.__show_project_page)
        self._home_page.projectSelected.connect(self._on_project_selected)
        self._home_page.changedAllocation.connect(lambda y: self._project_manager.save_ini_number(
            "General", "memory_allocation", y))

        self.__show_home_page()
        self._window.move(800, 200)
        self._window.show()

        if splash_screen:
            splash_screen.finish(self._window)

    def _make_new_home_tbar(self) -> None:
        """
        Instantiates and configures a custom frameless title bar for the home page.

        This sets up the window control buttons (minimize, maximize, close) with specific
        monochrome hover and normal color states to match the home page's minimal aesthetic.
        The title bar is instantiated in a hidden state to prevent flickering during view transitions.
        - Generated by Gemini.
        """
        self._home_page_title_bar = TitleBar(self._window)
        self._home_page_title_bar.hide()
        self._home_page_title_bar.minBtn.set_normal_color(QColor("#F5F5F5"))
        self._home_page_title_bar.maxBtn.set_normal_color(QColor("#F5F5F5"))
        self._home_page_title_bar.closeBtn.set_normal_color(QColor("#F5F5F5"))
        self._home_page_title_bar.minBtn.set_hover_color(QColor("#F5F5F5"))
        self._home_page_title_bar.maxBtn.set_hover_color(QColor("#F5F5F5"))

    def _make_new_project_tbar(self) -> None:
        """
        Builds the custom title bar specific to the active project environment.

        Configures the application logo and connects the title bar's routing signals 
        (like new file requests or returning to the home page) to the main controller's 
        routing methods. It explicitly overrides the default close button behavior.
        - Generated by Gemini.
        """
        self._project_page_title_bar = QCustomTitleBar(self._window)
        self._project_page_title_bar.hide()
        self._project_page_title_bar.icon = QIcon(":/res/app_logo.png")
        self._project_page_title_bar.closeBtn.clicked.disconnect(self._project_page_title_bar.window().close)
        self._project_page_title_bar.newFileRequested.connect(self.__show_project_page)
        self._project_page_title_bar.homePageRequested.connect(self.__show_home_page)

    def __show_home_page(self) -> None:
        """
        Routes the user interface to the home dashboard and cleans up active projects.

        This forcefully deletes any currently loaded project page to free resources and resets
        the current project state. It swaps the title bar to the home configuration and transitions
        the stacked widget to display the home view.
        - Generated by Gemini.
        """
        if self._project_page is not None:
            self._project_page.delete_later()
            self._project_page = None

        self._project_manager.current_project = None

        self._home_page.show()

        self._make_new_home_tbar()
        self._window.set_title_bar(self._home_page_title_bar)
        self._home_page_title_bar.show()
        self._home_page_title_bar.resize(self._window.width, 32)

        self._stack.set_current_widget(self._home_page)

    def __show_project_page(self) -> None:
        """
        Routes the user interface to a fresh project workspace.

        Clears any pre-existing project views from the stack, swaps out the window's title bar 
        for the project-specific configuration, and initializes a new project instance. It defaults 
        the active file name to 'Untitled.json' and binds the project page's home request signal 
        to the routing controller.
        - Generated by Gemini.
        """
        if self._project_page is not None:
            self._stack.remove_widget(self._project_page)
            self._project_page.delete_later()

        if self._window.titleBar is not self._project_page_title_bar:
            self._make_new_project_tbar()
            self._window.set_title_bar(self._project_page_title_bar)

        self._project_page_title_bar.file_name = "Untitled.json"

        self._project_page = self._project_manager.new_project()
        self._project_page.homeRequested.connect(self.__show_home_page)
        self._stack.add_widget(self._project_page)
        self._stack.set_current_widget(self._project_page)

        self._project_page_title_bar.resize(self._window.width, 32)
        self._project_page_title_bar.show()

    @Slot(str)
    def _on_project_selected(self, project_path: str) -> None:
        """
        Loads an existing project from disk and transitions the UI to the project view.

        :param project_path: The absolute or relative file path to the project file.
        :type project_path: str
        - Generated by Gemini.
        """
        self.__show_project_page()
        self._project_manager.open_project(project_path)


class ThemeManager:
    """
    Centralizes the application's visual aesthetics, handling fonts, styles, and color palettes.

    This manager enforces a consistent dark theme across the entire application by programmatically 
    defining QPalette roles, injecting global QSS stylesheets, and registering custom typography 
    from the resource binaries.
    - Generated by Gemini.

    :ivar _palette: The cached dark palette applied to the application.
    :type _palette: QPalette | None
    """

    def __init__(self, q_app: QApplication) -> None:
        """
        Bootstraps the application's global visual configuration.

        Registers the embedded font binaries, parses the external QSS stylesheet, and computes 
        and applies the overarching dark color palette to the core QApplication instance.
        - Generated by Gemini.

        :param q_app: The main application instance to apply the styling against.
        :type q_app: QApplication
        """
        self._q_app = q_app

        self._load_custom_fonts()
        self._load_styles()
        self._palette: QPalette | None = None
        self._apply_dark_palette()

    @staticmethod
    def _load_custom_fonts() -> None:
        """
        Registers embedded font families into the global font database.

        Extracts JetBrains Mono and Author typefaces from the Qt Resource System so they can 
        be referenced natively by QSS stylesheets and QFont objects throughout the application.
        - Generated by Gemini.
        """
        QFontDatabase.add_application_font(":/res/JetBrainsMono-Regular.ttf")
        QFontDatabase.add_application_font(":/res/JetBrainsMono-Bold.ttf")
        QFontDatabase.add_application_font(":/res/Author-Regular.otf")
        QFontDatabase.add_application_font(":/res/Author-Bold.otf")

    def _apply_dark_palette(self) -> None:
        """
        Constructs and enforces the default dark color palette.

        Overrides specific QPalette color roles (Window, WindowText, Highlight) with custom hex values.
        It binds this palette directly to the QApplication instance and cascades the changes down 
        to all instantiated child widgets to ensure strict UI consistency.
        - Generated by Gemini.
        """
        dark_palette = QPalette()

        dark_palette.set_color(QPalette.ColorRole.WindowText, QColor("#F5F5F5"))
        dark_palette.set_color(QPalette.ColorRole.Highlight, QColor("#1D1D1D10"))
        dark_palette.set_color(QPalette.ColorRole.Window, QColor("#1D1D1D"))
        dark_palette.set_color(QPalette.ColorRole.HighlightedText, QColor("#1D1D1D"))

        self._q_app.set_palette(dark_palette)

        self._palette = dark_palette

        self._inherit_palette(self._q_app)

    def _inherit_palette(self, q_widget: QWidget | QApplication) -> None:
        """
        Recursively pushes the cached palette down the widget hierarchy.

        Forces all child components of the provided widget or application to adopt the active 
        theme, overriding any default OS-level styling applied at the widget level.
        - Generated by Gemini.

        :param q_widget: The top-level widget or application to traverse and style.
        :type q_widget: QWidget | QApplication
        """
        for child in q_widget.find_children(QWidget):
            child.set_palette(self._palette)
            self._inherit_palette(child)

    def _load_styles(self) -> None:
        """
        Parses and injects the global QSS stylesheet.

        Resolves the absolute path to the 'styles.qss' file located in the user_interface directory.
        If successfully located, its contents are read and applied globally to the QApplication.
        If missing, it gracefully fails by logging an error to standard output.
        - Generated by Gemini.
        """
        base_path = os.path.dirname(os.path.abspath(__file__))
        styles_path = os.path.join(base_path, "../user_interface/styles.qss")

        if os.path.exists(styles_path):
            with open(styles_path, "r") as file:
                self._q_app.style_sheet = file.read()

        else:
            print("'styles.qss' file was not found.")

