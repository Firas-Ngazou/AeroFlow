class AeroFlow:
    """
    Represents the main application flow management for `AeroFlow`.

    This class initializes and manages the application structure, including the
    home page and project page navigation, handling project selection, and title
    bar interactions. It provides a seamless way to switch between different
    application states (home and project pages) while maintaining the layout. - Generated by OpenAI's GPT 5.5

    :ivar _stack: The stacked widget managing different application pages.
    :type _stack: QStackedWidget
    :ivar _home_page: The home page of the application.
    :type _home_page: HomePage
    :ivar _project_manager: Manages the creation and opening of projects.
    :type _project_manager: ProjectManager
    :ivar _primary_layout: The primary layout that organizes the application UI.
    :type _primary_layout: QHBoxLayout
    """
    def __init__(self):
        self._window = FramelessWindow()
        self._window.resize(1920, 1080)

        self._home_page_title_bar = TitleBar(self._window)
        self._home_page_title_bar.hide()
        self._home_page_title_bar.minBtn.setNormalColor(QColor("#F5F5F5"))
        self._home_page_title_bar.maxBtn.setNormalColor(QColor("#F5F5F5"))
        self._home_page_title_bar.closeBtn.setNormalColor(QColor("#F5F5F5"))
        self._home_page_title_bar.minBtn.setHoverColor(QColor("#F5F5F5"))
        self._home_page_title_bar.maxBtn.setHoverColor(QColor("#F5F5F5"))

        self._project_page_title_bar = QCustomTitleBar(self._window)
        self._project_page_title_bar.icon = QIcon(":/res/app_logo.png")
        self._project_page_title_bar.hide()

        self._stack = QStackedWidget(self._window)

        self._home_page = HomePage(self._window)
        self._stack.addWidget(self._home_page)

        self._project_page: ProjectPage | None = None
        self._project_manager = ProjectManager(self._window)
        self._project_manager.home_page = self._home_page

        self._primary_layout = QHBoxLayout(self._window)
        self._primary_layout.setSpacing(0)
        self._primary_layout.setContentsMargins(0, 32, 0, 0)
        self._primary_layout.addWidget(self._stack)

        self._home_page.newProjectPressed.connect(self.__show_project_page)
        self._home_page.projectSelected.connect(self._on_project_selected)
        self._home_page.changedAllocation.connect(lambda y: self._project_manager.save_ini_number(
            "General", "memory_allocation", y))
        self._project_page_title_bar.closeBtn.clicked.disconnect(self._project_page_title_bar.window().close)
        self._project_page_title_bar.newFileRequested.connect(self.__show_project_page)

        self.__show_home_page()
        self._window.move(800, 200)
        self._window.show()

    def __show_home_page(self):
        """
        Shows the home page of the application by setting the relevant
        visual components and resetting the current project to None. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        self._project_manager.current_project = None

        self._home_page.show()

        self._window.setTitleBar(self._home_page_title_bar)
        self._home_page_title_bar.show()

        self._stack.setCurrentWidget(self._home_page)

    def __show_project_page(self):
        """
        Displays the project page in the application's main window.

        This method ensures that the previous project page, if present,
        is removed and deleted. It sets up the new project page using the
        project manager, connects its `homeRequested` signal to the appropriate
        handler, and updates the stack widget to show the current page. The title
        bar is configured for the project page, including resizing it as needed. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        if self._project_page is not None:
            self._stack.removeWidget(self._project_page)
            self._project_page.deleteLater()

        if self._window.titleBar is not self._project_page_title_bar:
            self._window.setTitleBar(self._project_page_title_bar)

        self._project_page_title_bar.file_name = "Untitled.json"

        self._project_page = self._project_manager.new_project()
        self._project_page.homeRequested.connect(self.__show_home_page)
        self._stack.addWidget(self._project_page)
        self._stack.setCurrentWidget(self._project_page)

        self._project_page_title_bar.resize(self._window.width(), 32)
        self._project_page_title_bar.show()

    @Slot(str)
    def _on_project_selected(self, project_path: str):
        """
        Handles the event when a project is selected by the user.

        This method is triggered when the project selection changes. It updates
        the view to show the project's page and initiates the process to open
        the selected project. - Generated by OpenAI's GPT 5.5

        :param project_path: The file path of the selected project.
        :type project_path: str
        """
        self.__show_project_page()
        self._project_manager.open_project(project_path)

class ThemeManager:
    """
    Manages the application's theme, including loading custom fonts, styling, and applying a dark palette.

    This class is responsible for managing the overall appearance of the application. It applies a consistent
    theme by loading custom fonts, applying stylesheets, and setting up a dark color palette. The dark palette
    is propagated across widgets within the application to ensure visual consistency. - Generated by OpenAI's GPT 5.5

    :ivar _palette: Stores the current color palette of the application.
    :type _palette: QPalette | None
    """
    def __init__(self, q_app: QApplication):
        self._q_app = q_app

        self._load_custom_fonts()
        self._load_styles()
        self._palette: QPalette | None = None
        self._apply_dark_palette()

    @staticmethod
    def _load_custom_fonts():
        """
        Loads custom fonts into the application from provided resources. This method
        adds specified font files to the `QFontDatabase`, making them available for
        use throughout the application. - Generated by OpenAI's GPT 5.5

        This is a helper function that handles the registration of fonts to ensure
        they are accessible for styling purposes, such as in user interface elements.

        :staticmethod:

        :return: None
        """
        QFontDatabase.addApplicationFont(":/res/JetBrainsMono-Regular.ttf")
        QFontDatabase.addApplicationFont(":/res/JetBrainsMono-Bold.ttf")
        QFontDatabase.addApplicationFont(":/res/Author-Regular.otf")
        QFontDatabase.addApplicationFont(":/res/Author-Bold.otf")

    def _apply_dark_palette(self) -> None:
        """
        Applies a dark color theme palette to the current application instance.

        This method configures and applies a predefined dark color scheme palette
        to a given application object. It modifies colors for various roles such as
        WindowText, Highlight, Window, and HighlightedText, creating a consistent
        dark appearance. Additionally, the palette is stored for potential reuse and
        propagation to dependent components. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        dark_palette = QPalette()

        dark_palette.setColor(QPalette.ColorRole.WindowText, QColor("#F5F5F5"))
        dark_palette.setColor(QPalette.ColorRole.Highlight, QColor("#1D1D1D10"))
        dark_palette.setColor(QPalette.ColorRole.Window, QColor("#1D1D1D"))
        dark_palette.setColor(QPalette.ColorRole.HighlightedText, QColor("#1D1D1D"))

        self._q_app.setPalette(dark_palette)

        self._palette = dark_palette

        self._inherit_palette(self._q_app)

    def _inherit_palette(self, q_widget: QWidget | QApplication):
        """
        Recursively inherits a specific palette for all child widgets of the given
        QWidget or QApplication. This ensures that the specified palette is applied
        uniformly across all nested widgets. - Generated by OpenAI's GPT 5.5

        .. note::
            The method performs a depth-first traversal of all child widgets and
            applies the palette to each of them.

        :param q_widget: The parent widget or application whose child widgets
                         should inherit the specified palette.
        :type q_widget: QWidget | QApplication
        """
        for child in q_widget.findChildren(QWidget):
            child.setPalette(self._palette)
            self._inherit_palette(child)

    def _load_styles(self) -> None:
        """
        Loads the application's stylesheet from a predefined directory and applies it to the Qt application.

        This method locates the `styles.qss` file in the `user_interface` directory relative
        to this script's location. If the file exists, its contents are read and applied as
        a stylesheet for the Qt application instance. If the file is not found, an error
        message is printed to the console. - Generated by OpenAI's GPT 5.5

        :raises FileNotFoundError: Logs an error message if the `styles.qss` file does not exist.
        """
        base_path = os.path.dirname(os.path.abspath(__file__))
        styles_path = os.path.join(base_path, "../user_interface/styles.qss")

        if os.path.exists(styles_path):
            with open(styles_path, "r") as file:
                self._q_app.setStyleSheet(file.read())

        else:
            print("'styles.qss' file was not found.")

