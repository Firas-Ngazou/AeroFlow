class ProjectState(Enum):
    """
    Represents the active lifecycle states of an AeroFlow project.

    We use this to strictly control state transitions across the application—from
    initialization, through our shape drawing and simulation tweaking, up to the
    final save state.
    - Generated by Gemini.
    """
    DEFAULT = 0
    NEW = 1
    SAVED = 2
    NONE = 3


class ProjectManager(QObject):
    """
    The core controller handling project creation, configuration loading, and file I/O for AeroFlow.

    This manager ensures that our base INI configurations, JSON templates, and the underlying
    aerodynamic simulation parameters (like LBM constraints) remain perfectly synced across the
    UI. It also strictly maps out the temporary directories needed for our heatmap and streamline
    video generations.
    - Generated by Gemini.

    :ivar _window: The main application window provided during initialization.
    :type _window: FramelessWindow
    """

    def __init__(self, window: FramelessWindow, parent: QObject | None = None) -> None:
        """
        Initializes the project manager, parsing our default paths for the `aeroflow.ini`
        and `template.json` files, and prepares the temporary storage directories required
        for our simulation frame buffering.
        - Generated by Gemini.

        :param window: The main frameless window housing our application views.
        :type window: FramelessWindow
        :param parent: Optional parent QObject for memory management.
        :type parent: QObject | None
        """
        super().__init__(parent)

        # Setup
        self._home_page: HomePage | None = None
        self._current_project: ProjectPage | None = None
        self._project_state = ProjectState.NONE
        self._project_title_bar: QCustomTitleBar | None = None
        self._window = window

        # ini
        self._ini_config = ConfigParser()
        self._ini_path = None

        # json
        self._current_json_path = None
        self._json_template_path = None

        # paths
        base_path = os.path.dirname(os.path.abspath(__file__))
        ini_path = os.path.join(base_path, "../../aeroflow.ini")
        json_template_path = os.path.join(base_path, "../template.json")

        self._tmp_heatmap_path = os.path.join(base_path, "../../tmp_sim_data/tmp_heatmaps/")
        self._tmp_stream_path = os.path.join(base_path, "../../tmp_sim_data/tmp_streams/")

        # load paths
        if os.path.exists(ini_path):
            self._ini_config.read(ini_path)
            self._ini_path = ini_path
        else:
            print(f"No aeroflow.ini file found at {ini_path}. Saves may not work as intended.")
        if os.path.exists(json_template_path):
            self._json_template_path = json_template_path
        else:
            print(f"No template.json file found at {json_template_path}. Saving may not work as intended.")

        # Other
        self._projects_count = 0
        self._was_modified = False

    def __initialize_connections(self) -> None:
        """
        Binds our internal UI signals to the manager's state tracking.

        Ensures that whenever we adjust our vector drawings or toggle JSON settings,
        the active project immediately flags itself as modified and prepares safe-close
        mechanisms.
        - Generated by Gemini.
        """
        self.__load_ini_values()
        self.__ini_connections()

        if self._current_project is None or self._project_title_bar is None:
            return

        self._current_project.vectorDrawingChanged.connect(lambda: self._set_modified(True))
        self._current_project.jsonSettingsChanged.connect(lambda: self._set_modified(True))
        self._current_project.saveWarningYesPressed.connect(self._safe_close)
        self._current_project.saveWarningNoPressed.connect(lambda: self._current_project.set_warning_visible(False))

        self._project_title_bar.openFileRequested.connect(self.open_project)

    def __ini_connections(self) -> None:
        """
        Links our simulation tuning sliders and dials directly to the INI parser.

        Automatically flushes changes in physics constraints—such as wind speed, viscosity,
        and optimization thresholds—straight to disk so the engine operates on live data.
        - Generated by Gemini.
        """
        if self._current_project is None:
            return

        self._current_project.qualityChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Quality", y))
        self._current_project.windSpeedChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Wind_speed", y))
        self._current_project.viscosityChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Viscosity", y)
        )
        self._current_project.constraintChanged.connect(
            lambda y: self._save_ini_string("Optimization", "Constraint_method", y)
        )
        self._current_project.targetChanged.connect(
            lambda y: self._save_ini_string("Optimization", "Target", y)
        )
        self._current_project.typeChanged.connect(
            lambda y: self._save_ini_string("Optimization", "Type", y)
        )

        self._current_project.iterationsChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Iterations", y)
        )
        self._current_project.thresholdChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Constraint_threshold", y)
        )
        self._current_project.mutationRateChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Mutation_rate", y)
        )
        self._current_project.magnitudeChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Magnitude", y)
        )
        self._current_project.populationSizeChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Population_size", y)
        )

    @Slot()
    def _safe_close(self) -> None:
        """
        Gracefully aborts any ongoing physics calculations and closes the active window
        without stranding backend processes.
        - Generated by Gemini.
        """
        self._current_project.on_stop_pressed()
        self._window.close()

    @Slot(bool)
    def _set_modified(self, modified: bool) -> None:
        """
        Toggles the internal modification flag and updates our title bar text to reflect
        the unsaved state (e.g., prepending an asterisk).
        - Generated by Gemini.

        :param modified: The boolean state determining if unsaved changes exist.
        :type modified: bool
        """
        self._was_modified = modified
        self._project_title_bar.is_project_saved = not modified
        if self._project_state is ProjectState.SAVED and modified:
            self._project_state = ProjectState.DEFAULT
            if self._project_title_bar is None:
                return
            self._project_title_bar.file_name = f"* {self._project_title_bar.file_name}"

    def new_project(self) -> ProjectPage:
        """
        Flushes the current view and mounts a fresh, clean project canvas for new
        aerodynamic configurations. Connects the new view to our standard save pipelines.
        - Generated by Gemini.

        :return: The initialized ProjectPage ready for user input.
        :rtype: ProjectPage
        """
        if self._current_project is not None:
            self._current_project.on_page_quit()
            self._current_project.on_stop_pressed()
        self._current_project = ProjectPage(self._window)
        self._project_title_bar = self._current_project.title_bar
        self._current_project.saveProject.connect(self.save_project)
        self._current_project.saveAsProject.connect(self.save_as_project)

        self._project_title_bar.is_project_saved = True
        self._project_title_bar.is_in_edit_mode = False

        self.__initialize_connections()

        self._project_state = ProjectState.NEW
        self._was_modified = False

        self._project_title_bar.closeBtn.clicked.connect(self._on_close_clicked)

        return self._current_project

    @Slot()
    def _on_close_clicked(self) -> None:
        """
        Intercepts the OS close event. If our shapes or engine parameters have been modified
        since the last commit, we throw up a warning dialog before nuking the instance.
        - Generated by Gemini.
        """
        if self._project_state is ProjectState.SAVED:
            self._safe_close()
        elif self._was_modified:
            self._current_project.set_warning_visible(True)
        else:
            self._safe_close()

    def save_project(self, data: dict) -> None:
        """
        Commits the active canvas geometry and engine toggles to the current JSON file path,
        overwriting the previous state and resetting our modification flags.
        - Generated by Gemini.

        :param data: The serialized dictionary of our current vector and UI states.
        :type data: dict
        """
        match self._project_state:
            case ProjectState.NONE:
                return
            case ProjectState.NEW:
                if self._was_modified: self.save_as_project(data)
            case ProjectState.DEFAULT:
                if self._current_json_path is None: return
                save = self._get_json_content(self._current_json_path)
                self._apply_project_data(save, data)
                self._write_json(self._current_json_path, save)

                self._update_previews()
                self._was_modified = False
                self._project_state = ProjectState.SAVED
                self._project_title_bar.is_project_saved = True

    def save_as_project(self, data: dict) -> None:
        """
        Prompts the user for a new file location, copies over our base JSON template, injects
        the active workspace data, and maps the newly created file into our INI registry.
        - Generated by Gemini.

        :param data: The workspace dictionary to inject into the new template copy.
        :type data: dict
        """
        if self._project_title_bar is None:
            return

        current_save_path, _ = QFileDialog.get_save_file_name(self._project_title_bar.window(), "Save as",
                                                              "../../untitled.json",
                                                              "JSON Files (*.json);;All Files (*")
        if not current_save_path: return

        self._current_json_path = current_save_path
        save = self._get_json_content(self._json_template_path)

        save["General"]["Project_name"] = Path(current_save_path).name
        save["Other"]["Project_number"] = self._projects_count

        self._apply_project_data(save, data)
        self._write_json(current_save_path, save)

        self._save_ini_string("Projects", f"project_{self._projects_count}_path",
                              current_save_path)

        self._projects_count += 1
        self._project_state = ProjectState.SAVED
        self._was_modified = False

        self._update_previews()

    def _apply_project_data(self, save: dict, data: dict) -> None:
        """
        Strictly maps our live workspace variables—like the drawn obstacle shapes, streamline
        density preferences, and flow visualization toggles—directly into the target dictionary
        schema expected by the save files.
        - Generated by Gemini.

        :param save: The destination JSON template dictionary.
        :type save: dict
        :param data: The raw data pulled directly from the UI logic.
        :type data: dict
        """
        self._project_title_bar.file_name = Path(self._current_json_path).name
        save["General"]["Project_description"] = data.get("Project_description", "")
        save["Drawing"]["Shapes"] = data.get("Shapes", [])
        save["Drawing"]["Preview"] = data.get("Preview", "")
        save["Other"]["Settings"]["States"]["Live_edit_state"] = data.get("Live_edit_state", False)
        save["Other"]["Settings"]["States"]["Velocity_state"] = data.get("Velocity_state", True)
        save["Other"]["Settings"]["States"]["Density_state"] = data.get("Density_state", False)
        save["Other"]["Settings"]["States"]["Streamlines_state"] = data.get("Streamlines_state", True)
        save["Other"]["Settings"]["States"]["Curl_state"] = data.get("Curl_state", False)
        save["Other"]["Settings"]["States"]["Staircase_state"] = data.get("Staircase_state", False)
        save["Other"]["Settings"]["Streamline_count"] = data.get("Streamline_count", 10)

    @staticmethod
    def _get_json_content(path: str) -> dict:
        """
        Retrieves and parses the raw JSON dictionary from the specified file path.
        - Generated by Gemini.

        :param path: The absolute or relative path to the target .json file.
        :type path: str
        :return: The loaded JSON content.
        :rtype: dict
        """
        with open(path, "r") as file:
            return json.load(file)

    @staticmethod
    def _write_json(path: str, save: dict) -> None:
        """
        Serializes and flushes our data dictionary directly to disk at the specified path
        with a standard 4-space indentation.
        - Generated by Gemini.

        :param path: Target file path.
        :type path: str
        :param save: The dictionary payload to write out.
        :type save: dict
        """
        with open(path, "w") as outfile:
            json.dump(save, outfile, indent = 4)

    @Slot(str)
    def open_project(self, path: str) -> None:
        """
        Loads an existing aerodynamic workspace from disk. Hydrates the vector canvas with saved
        shapes, restores the flow visualization layers (velocity, curl, density), and locks
        the session into the SAVED state.
        - Generated by Gemini.

        :param path: The path to the previously saved .json project file.
        :type path: str
        """
        if self._current_project is not None:
            self._current_project.on_stop_pressed()
        if Path(path).exists():
            data = self._get_json_content(path)

            editor_data = {"Data": data["Drawing"]}
            name = data.get("General", {}).get("Project_name", "")

            self._save_ini_string("Projects", f"project_{self._projects_count}_path", path)

            self._current_project.load_editor_data(editor_data)

            self._current_project.velocity_state = data["Other"]["Settings"]["States"]["Velocity_state"]
            self._current_project.density_state = data["Other"]["Settings"]["States"]["Density_state"]
            self._current_project.streamlines_state = data["Other"]["Settings"]["States"]["Streamlines_state"]
            self._current_project.curl_state = data["Other"]["Settings"]["States"]["Curl_state"]
            self._current_project.streamline_count = data["Other"]["Settings"]["Streamline_count"]

            self._project_title_bar.file_name = name
            self._project_state = ProjectState.SAVED
            self._current_json_path = path

    @Slot(float, int)
    def save_ini_number(self, category: str, parameter: str, value: float | int) -> None:
        """
        Writes a raw numerical setting (int or float) directly into the loaded INI configuration
        matrix and saves the update locally.
        - Generated by Gemini.

        :param category: The top-level bracket section in the INI file.
        :type category: str
        :param parameter: The specific key to update.
        :type parameter: str
        :param value: The number to cast and store.
        :type value: float | int
        """
        self._ini_config[category][parameter] = str(f"{value}")
        with open(self._ini_path, 'w') as configfile:
            self._ini_config.write(configfile)

    @Slot(str)
    def _save_ini_string(self, category: str, parameter: str, value: str) -> None:
        """
        Pushes string-based parameter changes into the active INI config section. Bypasses
        writing if the exact value already exists to save unnecessary disk thrashing.
        - Generated by Gemini.

        :param category: Target section heading.
        :type category: str
        :param parameter: Target key string.
        :type parameter: str
        :param value: The literal string value to save.
        :type value: str
        """
        paths = self._ini_config[category].values()
        if value in paths: return
        self._ini_config[category][parameter] = value
        with open(self._ini_path, 'w') as configfile:
            self._ini_config.write(configfile)

    def __load_ini_values(self) -> None:
        """
        Pulls our core physics engine parameters (lattice viscosity, wind vectors) and genetic
        optimization thresholds out of the `.ini` cache and loads them directly into the current
        project's properties to prep the simulation backend.
        - Generated by Gemini.
        """
        self._ini_config.read(self._ini_path)

        allocation = self._ini_config.getint("General", "Memory_allocation")
        quality = self._ini_config.getfloat("Simulation", "Quality")
        wind_speed = self._ini_config.getfloat("Simulation", "Wind_speed")
        viscosity = self._ini_config.getfloat("Simulation", "Viscosity")

        constraint_method = self._ini_config.get("Optimization", "Constraint_method", fallback = "SURFACE")
        target = self._ini_config.get("Optimization", "Target", fallback = "PORTANCE")
        type_name = self._ini_config.get("Optimization", "Type", fallback = "MINIMUM")
        iterations = self._ini_config.getint("Optimization", "Iterations")
        threshold = self._ini_config.getfloat("Optimization", "Constraint_threshold")
        mutation_rate = self._ini_config.getfloat("Optimization", "Mutation_rate")
        magnitude = self._ini_config.getfloat("Optimization", "Magnitude", fallback = 1.0)
        population_size = self._ini_config.getint("Optimization", "Population_size")

        self._current_project.allocation = allocation
        self._current_project.quality = quality
        self._current_project.wind_speed = wind_speed
        self._current_project.constraint_method = constraint_method
        self._current_project.target = target
        self._current_project.type = type_name
        self._current_project.iterations = iterations
        self._current_project.threshold = threshold
        self._current_project.mutation_rate = mutation_rate
        self._current_project.magnitude = magnitude
        self._current_project.population_size = population_size
        self._current_project.viscosity = viscosity

    def _update_previews(self) -> None:
        """
        Iterates over our registry of known project paths, verifies the files still exist
        on disk, and pushes valid entries to the home page's recent projects board.
        - Generated by Gemini.
        """
        self._ini_config.read(self._ini_path)
        paths = [value for key, value in self._ini_config.items("Projects")]

        for path in paths:
            if not Path(path).exists():
                print(f"Project path {path} does not exist.")
                continue
            self._home_page.add_project(path)

    @Slot(list)
    def _on_heatmap_frame_finished(self, data: list) -> None:
        """
        Intercepts individual rendered QPixmap frames passing back from our simulation thread
        and kicks them over to the PNG compiler to be cached for the final video output.
        - Generated by Gemini.

        :param data: A list containing [0]: the generated QPixmap, and [1]: the frame index.
        :type data: list
        """
        frame = data[0]
        current_frame = data[1]
        self._save_png("heatmap", frame, current_frame)

    def _save_png(self, type: str, frame: QPixmap, current_frame: int) -> None:
        """
        Dumps a given visual frame directly into our temporary storage folders as a cleanly
        indexed PNG, allowing us to build the visual sequence for flow lines or heatmaps.
        - Generated by Gemini.

        :param type: Either "heatmap" or "stream" to designate the correct temporary buffer.
        :type type: str
        :param frame: The QPixmap buffer.
        :type frame: QPixmap
        :param current_frame: The sequential integer for chronological sorting later.
        :type current_frame: int
        :raises ValueError: Hard crashes if attempting to save an unsupported visualization type.
        """
        formatted_name = self._project_title_bar.file_name().split(".")[0]

        if type == "heatmap":
            save_path = os.path.join(self._tmp_heatmap_path, f"tmp_heatmap_{current_frame}_{formatted_name}.png")

        elif type == "stream":
            save_path = os.path.join(self._tmp_stream_path, f"tmp_stream_{current_frame}_{formatted_name}.png")

        else:
            raise ValueError(f"Invalid type: {type}")

        frame.save(save_path, "PNG")

    @Slot()
    def _on_heatmap_finished(self) -> None:
        """
        Fires exactly when our lattice physics solver has finished iterating the final frame.
        Triggers the OpenCV compiler to wrap up the loose PNGs into our finalized MP4.
        - Generated by Gemini.
        """
        name = "tmp_heatmap.mp4"
        fps = 30

        self._mp4_from_png_dir("heatmap", name, fps)

    def _mp4_from_png_dir(self, type: str, name: str, fps: int) -> None:
        """
        Uses OpenCV to stitch together the sequentially cached PNG renders into a standard
        framerate MP4. Once encoded, it aggressively deletes the source PNGs to keep our temp
        directories from ballooning during heavy simulations.
        - Generated by Gemini.

        :param type: The sequence directory target ("heatmap" or "stream").
        :type type: str
        :param name: Output file destination string.
        :type name: str
        :param fps: The frames-per-second lock for the resulting video matrix.
        :type fps: int
        """
        if type == "heatmap":
            dir_path = self._tmp_heatmap_path
            images = [file for file in os.listdir(dir_path) if file.endswith(".png")]
            images.sort(key = lambda x: int(x.split("_")[2]))

            frame = cv2.imread(os.path.join(dir_path, images[0]))
            height = frame.shape[0]
            width = frame.shape[1]

            writer = cv2.VideoWriter.fourcc(*"mp4v")
            output_path = os.path.join(dir_path, name)
            video = cv2.VideoWriter(output_path, writer, fps, (width, height))

            for image in images:
                path = os.path.join(dir_path, image)
                data = cv2.imread(path)

                if data is not None:
                    video.write(data)

            video.release()

            for image in images:
                file_path = os.path.join(dir_path, image)
                os.remove(file_path)

    @property
    def home_page(self) -> HomePage | None:
        """
        Exposes the active home page controller, typically the project dashboard.
        - Generated by Gemini.

        :return: Current home view, if active.
        :rtype: HomePage | None
        """
        return self._home_page

    @home_page.setter
    def home_page(self, page: HomePage | None) -> None:
        """
        Replaces the active home view and strictly forces a refresh of our project count
        and INI-backed UI state to match the fresh context.
        - Generated by Gemini.

        :param page: The new instance.
        :type page: HomePage | None
        """
        self._home_page = page
        self._update_previews()
        self._projects_count = self._home_page.project_count
        self._update_home_ini()

    def _update_home_ini(self) -> None:
        """
        Hops into the global configuration file to pull out our defined memory constraints
        and safely pushes that limit into the home page for display or resource gating.
        - Generated by Gemini.
        """
        self._ini_config.read(self._ini_path)

        allocation = self._ini_config.getint("General", "memory_allocation")

        self._home_page.allocation_value = allocation

    @property
    def current_project(self) -> ProjectPage | None:
        """
        Retrieves the actively running simulation or drawing workspace.
        - Generated by Gemini.

        :return: Active canvas and physics manager.
        :rtype: ProjectPage | None
        """
        return self._current_project

    @current_project.setter
    def current_project(self, project: ProjectPage | None) -> None:
        """
        Swaps out the current view safely by flagging the old instance for immediate C++ deletion
        before assigning the incoming project space. Prevents heavy memory leaks between tests.
        - Generated by Gemini.

        :param project: The new view context to embed.
        :type project: ProjectPage | None
        """
        if self._current_project:
            self._current_project.delete_later()

        self._current_project = project