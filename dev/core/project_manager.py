import json
import cv2
import os
from enum import Enum
from pathlib import Path

from PySide6.QtCore import Slot, QObject, Signal
from PySide6.QtGui import QPixmap
from PySide6.QtWidgets import QFileDialog, QLabel

from dev.user_interface.management.home_page import HomePage
from dev.user_interface.management.project_page import ProjectPage
from dev.user_interface.management.q_custom_window_frame import QCustomTitleBar, FramelessWindow
from configparser import ConfigParser

class ProjectState(Enum):
    """
    Represents the state of a project.

    This enumeration defines the various states a project can be in, such as
    default, new, saved, or none. It is used to track the current status of a
    project within an application. - Generated by OpenAI's GPT 5.5

    :ivar DEFAULT: Represents the default state of a project.
    :type DEFAULT: int
    :ivar NEW: Represents a newly created project.
    :type NEW: int
    :ivar SAVED: Represents a project that has been saved.
    :type SAVED: int
    :ivar NONE: Represents the absence of a project state.
    :type NONE: int
    """
    DEFAULT = 0
    NEW = 1
    SAVED = 2
    NONE = 3

class ProjectManager(QObject):
    """
    Manages project operations such as creating, saving, and loading projects.

    This class acts as a controller for handling project-related operations such as project creation, saving
    projects to JSON files, loading projects, and synchronizing configurations with .ini files. It serves as
    an intermediary between the user interface and the underlying project data. Additionally, the class
    maintains state information about the current project and manages communication between components.
    - Generated by OpenAI's GPT 5.5

    :ivar _window: The main application window that contains the project.
    :type _window: FramelessWindow
    """

    def __init__(self, window: FramelessWindow, parent: QObject | None = None) -> None:
        super().__init__(parent)

        # Setup
        self._home_page: HomePage | None = None
        self._current_project: ProjectPage | None = None
        self._project_state = ProjectState.NONE
        self._project_title_bar: QCustomTitleBar | None = None
        self._window = window

        # ini
        self._ini_config = ConfigParser()
        self._ini_path = None

        # json
        self._current_json_path = None
        self._json_template_path = None

        # paths
        base_path = os.path.dirname(os.path.abspath(__file__))
        ini_path = os.path.join(base_path, "../../aeroflow.ini")
        json_template_path = os.path.join(base_path, "../template.json")

        self._tmp_heatmap_path = os.path.join(base_path, "../../tmp_sim_data/tmp_heatmaps/")
        self._tmp_stream_path = os.path.join(base_path, "../../tmp_sim_data/tmp_streams/")

        # load paths
        if os.path.exists(ini_path):
            self._ini_config.read(ini_path)
            self._ini_path = ini_path
        else: print(f"No aeroflow.ini file found at {ini_path}. Saves may not work as intended.")
        if os.path.exists(json_template_path):
            self._json_template_path = json_template_path
        else: print(f"No template.json file found at {json_template_path}. Saving may not work as intended.")

        # Other
        self._projects_count = 0
        self._was_modified = False

    def __initialize_connections(self) -> None:
        """
        Initializes connections for various project signals and UI actions.

        This method sets up connections between the project's signals and their
        corresponding slots or handlers. It ensures that the application reacts
        appropriately to project-related events such as modifications to the vector
        drawing, save warnings, or interactions with the project title bar. - Generated by OpenAI's GPT 5.5

        :raises: Does not raise any exceptions.
        :return: None
        """
        self.__load_ini_values()
        self.__ini_connections()

        self._current_project.vectorDrawingChanged.connect(lambda: self._set_modified(True))
        self._current_project.jsonSettingsChanged.connect(lambda: self._set_modified(True))
        self._current_project.saveWarningYesPressed.connect(self._safe_close)
        self._current_project.saveWarningNoPressed.connect(lambda: self._current_project.set_warning_visible(False))

        self._project_title_bar.openFileRequested.connect(self.open_project)

    def __ini_connections(self) -> None:
        """
        Establishes connections between project attributes and corresponding methods for
        saving configuration values in an INI file.

        This method sets up signal-slot connections to save respective simulation and
        optimization parameters whenever changes are made to these attributes in the
        current project. The connections ensure that changes to quality, wind speed,
        optimization constraints, iterations, and constraint thresholds are
        automatically saved in the relevant sections of the INI file. - Generated by OpenAI's GPT 5.5

        :raises: This method does not explicitly raise any exceptions.
        :return: None
        """
        self._current_project.qualityChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Quality", y))
        self._current_project.windSpeedChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Wind_speed", y))
        self._current_project.viscosityChanged.connect(
            lambda y: self.save_ini_number("Simulation", "Viscosity", y)
        )
        self._current_project.constraintChanged.connect(
            lambda y: self._save_ini_string("Optimization", "Constraint_method", y)
        )
        self._current_project.iterationsChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Iterations", y)
        )
        self._current_project.thresholdChanged.connect(
            lambda y: self.save_ini_number("Optimization", "Constraint_threshold", y)
        )

    @Slot()
    def _safe_close(self) -> None:
        """
        Safely closes the current project and window. - Generated by OpenAI's GPT 5.5
        """
        self._current_project.on_stop_pressed()
        self._window.close()

    @Slot(bool)
    def _set_modified(self, modified: bool) -> None:
        """
        Sets the modified state of the object.

        Updates the internal state of the object to indicate whether it has
        been modified. This method is designed to handle boolean input. - Generated by OpenAI's GPT 5.5

        :param modified: A boolean value indicating the modified state to be set.
        :type modified: bool
        """
        self._was_modified = modified
        self._project_title_bar.is_project_saved = not modified
        if self._project_state is ProjectState.SAVED and modified:
            self._project_state = ProjectState.DEFAULT
            self._project_title_bar.file_name = f"* {self._project_title_bar.file_name()}"

    def new_project(self) -> ProjectPage:
        """
        Initializes a new project and sets up its properties and connections.

        This method creates a new project by initializing a `ProjectPage` instance. It sets up
        the project's title bar, state, and connects related signals to ensure proper operation.
        Additionally, it handles the project's close button functionality. - Generated by OpenAI's GPT 5.5

        :returns: A reference to the newly initialized project.
        :rtype: ProjectPage
        """
        if self._current_project is not None:
            self._current_project.on_page_quit()
            self._current_project.on_stop_pressed()
        self._current_project = ProjectPage(self._window)
        self._project_title_bar = self._current_project.title_bar
        self._current_project.saveProject.connect(self.save_project)
        self._current_project.saveAsProject.connect(self.save_as_project)

        self._project_title_bar.is_project_saved = True
        self._project_title_bar.is_in_edit_mode = False

        self.__initialize_connections()

        self._project_state = ProjectState.NEW
        self._was_modified = False

        self._project_title_bar.closeBtn.clicked.connect(self._on_close_clicked)

        return self._current_project

    @Slot()
    def _on_close_clicked(self) -> None:
        """
        Handles the close button click event by determining the current project state
        and managing closing behavior or warnings appropriately. - Generated by OpenAI's GPT 5.5

        :raises None: This method does not raise any exceptions.
        """
        if self._project_state is ProjectState.SAVED:
            self._safe_close()
        elif self._was_modified: self._current_project.set_warning_visible(True)
        else:
            self._safe_close()

    def save_project(self, data: dict) -> None:
        """
        Saves the current project based on its state, handles updates, and applies
        modifications to existing project data. - Generated by OpenAI's GPT 5.5

        :param data: The data to be saved into the current project. Should be provided
            as a dictionary.
        :type data: dict
        :return: None
        """
        match self._project_state:
            case ProjectState.NONE:
                return
            case ProjectState.NEW:
                if self._was_modified: self.save_as_project(data)
            case ProjectState.DEFAULT:
                if self._current_json_path is None: return
                save = self._get_json_content(self._current_json_path)
                self._apply_project_data(save, data)
                self._write_json(self._current_json_path, save)

                self._update_previews()
                self._was_modified = False
                self._project_state = ProjectState.SAVED
                self._project_title_bar.is_project_saved = True

    def save_as_project(self, data: dict) -> None:
        """
        Saves the project data to a user-specified JSON file and updates related project attributes
        and settings. This function manages the save location, updates internal project state,
        and increments the project count. - Generated by OpenAI's GPT 5.5

        :param data: Dictionary containing project-related data that needs to be stored.
        :type data: dict
        :return: None
        """
        current_save_path, _ = QFileDialog.getSaveFileName(self._project_title_bar.window(), "Save as",
                                                "../../untitled.json", "JSON Files (*.json);;All Files (*")
        if not current_save_path: return

        self._current_json_path = current_save_path
        save = self._get_json_content(self._json_template_path)

        save["General"]["Project_name"] = Path(current_save_path).name
        save["Other"]["Project_number"] = self._projects_count

        self._apply_project_data(save, data)
        self._write_json(current_save_path, save)

        self._save_ini_string("Projects", f"project_{self._projects_count}_path",
                              current_save_path)

        self._projects_count += 1
        self._project_state = ProjectState.SAVED
        self._was_modified = False

        self._update_previews()

    def _apply_project_data(self, save: dict, data: dict) -> None:
        """
        Applies the project data to the current save object by extracting and mapping relevant
        fields from the provided data dictionary. Updates the project's title bar and various
        sections of the `save` dictionary with the input data. - Generated by OpenAI's GPT 5.5

        :param save: The dictionary that represents the current state of the project save file.
           It is updated with the provided data.
        :type save: dict
        :param data: The dictionary containing new project data. Expected keys include
           "Project_description", "Shapes", and "Preview".
        :type data: dict
        :return: None
        """
        self._project_title_bar.file_name = Path(self._current_json_path).name
        save["General"]["Project_description"] = data.get("Project_description", "")
        save["Drawing"]["Shapes"] = data.get("Shapes", [])
        save["Drawing"]["Preview"] = data.get("Preview", "")
        save["Other"]["Settings"]["States"]["Live_edit_state"] = data.get("Live_edit_state", False)
        save["Other"]["Settings"]["States"]["Velocity_state"] = data.get("Velocity_state", True)
        save["Other"]["Settings"]["States"]["Density_state"] = data.get("Density_state", False)
        save["Other"]["Settings"]["States"]["Streamlines_state"] = data.get("Streamlines_state", True)
        save["Other"]["Settings"]["States"]["Curl_state"] = data.get("Curl_state", False)
        save["Other"]["Settings"]["States"]["Staircase_state"] = data.get("Staircase_state", False)
        save["Other"]["Settings"]["Streamline_count"] = data.get("Streamline_count", 10)

    @staticmethod
    def _get_json_content(path: str) -> dict:
        """
        Reads and parses a JSON file from the specified path. - Generated by OpenAI's GPT 5.5

        :param path: The file system path to the JSON file.
        :type path: str
        :return: Dictionary containing data parsed from the JSON file.
        :rtype: dict
        :raises FileNotFoundError: If the file does not exist at the given path.
        :raises json.JSONDecodeError: If the file content is not properly formatted JSON.
        """
        with open(path, "r") as file:
            return json.load(file)

    @staticmethod
    def _write_json(path: str, save: dict) -> None:
        """
        Writes a dictionary as a JSON file to the specified path.

        This method serializes the given dictionary and writes it to a file at the
        specified location. The output file will be formatted with an indentation of 4
        spaces for better readability. - Generated by OpenAI's GPT 5.5

        :param path: The file path where the JSON file will be stored.
        :type path: str
        :param save: The dictionary to be saved as a JSON file.
        :type save: dict
        """
        with open(path, "w") as outfile:
            json.dump(save, outfile, indent=4)

    @Slot(str)
    def open_project(self, path: str) -> None:
        """
        Opens a project file by reading its contents and loading the associated data into the application.
         - Generated by OpenAI's GPT 5.5

        :param path: The file system path to the project file to be opened. Must be a valid path to an existing file.
        :type path: str
        :return: None
        """
        if self._current_project is not None:
            self._current_project.on_stop_pressed()
        if Path(path).exists():
            data = self._get_json_content(path)

            editor_data = {"Data": data["Drawing"]}
            name = data.get("General", {}).get("Project_name", "")

            self._save_ini_string("Projects", f"project_{self._projects_count}_path", path)

            self._current_project.load_editor_data(editor_data)

            self._current_project.velocity_state = data["Other"]["Settings"]["States"]["Velocity_state"]
            self._current_project.density_state = data["Other"]["Settings"]["States"]["Density_state"]
            self._current_project.streamlines_state = data["Other"]["Settings"]["States"]["Streamlines_state"]
            self._current_project.curl_state = data["Other"]["Settings"]["States"]["Curl_state"]
            self._current_project.streamline_count = data["Other"]["Settings"]["Streamline_count"]

            self._project_title_bar.file_name = name
            self._project_state = ProjectState.SAVED
            self._current_json_path = path

    @Slot(float, int)
    def save_ini_number(self, category: str, parameter: str, value: float | int) -> None:
        """
        Saves a numerical value (float or integer) to an `.ini` configuration file under the
        specified category and parameter keys. The value is stored as a string and written to
        the file. - Generated by OpenAI's GPT 5.5

        :param category: The section/category name in the `.ini` configuration file
            where the parameter is to be stored. Must be a string.
        :param parameter: The key/parameter name under the specified category where
            the value should be saved. Must be a string.
        :param value: The numerical value to be saved under the specified parameter and
            category. The value can be of type float or int.
        :return: None
        """
        self._ini_config[category][parameter] = str(f"{value}")
        with open(self._ini_path, 'w') as configfile:
            self._ini_config.write(configfile)

    @Slot(str)
    def _save_ini_string(self, category: str, parameter: str, value: str) -> None:
        """
        Saves a specified parameter and its associated value under a specific category
        in the INI configuration. If the value already exists in the given category,
        no changes are made. Otherwise, the value is added, and the updated configuration
        is written to the INI file located at the configured path. - Generated by OpenAI's GPT 5.5

        :param category: The category under which the parameter-value pair will be saved.
        :type category: str
        :param parameter: The name of the parameter to save.
        :type parameter: str
        :param value: The value to associate with the specified parameter in the given category.
        :type value: str
        :return: None
        """
        paths = self._ini_config[category].values()
        if value in paths: return
        self._ini_config[category][parameter] = value
        with open(self._ini_path, 'w') as configfile:
            self._ini_config.write(configfile)

    def __load_ini_values(self) -> None:
        """
        Loads and applies configuration values from an INI file to the current project.

        The method reads simulation and optimization parameters from the INI file path
        provided and updates the corresponding attributes in the current project object.
        The method is used to ensure that project configurations align with the values
        defined in the INI file. - Generated by OpenAI's GPT 5.5

        Raises:
            No specific exceptions are raised directly in this method, but errors might
            propagate from configparser or type conversions if the INI file content is
            invalid or missing required sections/keys.

        :return: None
        """
        self._ini_config.read(self._ini_path)

        allocation = self._ini_config.getint("General", "Memory_allocation")
        quality = self._ini_config.getfloat("Simulation", "Quality")
        wind_speed = self._ini_config.getfloat("Simulation", "Wind_speed")
        viscosity = self._ini_config.getfloat("Simulation", "Viscosity")

        constraint_method = self._ini_config.get("Optimization", "Constraint_method")
        iterations = self._ini_config.getint("Optimization", "Iterations")
        threshold = self._ini_config.getint("Optimization", "Constraint_threshold")

        self._current_project.allocation = allocation
        self._current_project.quality = quality
        self._current_project.wind_speed = wind_speed
        self._current_project.constraint_method = constraint_method
        self._current_project.iterations = iterations
        self._current_project.threshold = threshold
        self._current_project.viscosity = viscosity

    def _update_previews(self) -> None:
        """
        Updates the previews of the projects listed in the configuration file. This
        method checks the existence of paths specified under the "Projects" section
        of the configuration file. If a path exists, it adds the project to the home
        page. If not, it prints an error message indicating the non-existent path. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        self._ini_config.read(self._ini_path)
        paths = [value for key, value in self._ini_config.items("Projects")]

        for path in paths:
            if not Path(path).exists():
                print(f"Project path {path} does not exist.")
                continue
            self._home_page.add_project(path)

    @Slot(list)
    def _on_heatmap_frame_finished(self, data: list) -> None:
        """
        Handles the event when a heatmap frame is finished. - Generated by OpenAI's GPT 5.5

        :param data: A list containing the frame (QPixmap) and current frame index (int).
        """
        frame = data[0]
        current_frame = data[1]
        self._save_png("heatmap", frame, current_frame)

    def _save_png(self, type: str, frame: QPixmap, current_frame: int) -> None:
        """
        Saves a QPixmap frame as a PNG file. - Generated by OpenAI's GPT 5.5

        :param type: The type of frame ("heatmap" or "stream").
        :param frame: The QPixmap to save.
        :param current_frame: The index of the current frame.
        """
        formatted_name = self._project_title_bar.file_name().split(".")[0]

        if type == "heatmap":
            save_path = os.path.join(self._tmp_heatmap_path, f"tmp_heatmap_{current_frame}_{formatted_name}.png")

        elif type == "stream":
            save_path = os.path.join(self._tmp_stream_path, f"tmp_stream_{current_frame}_{formatted_name}.png")

        else:
            raise ValueError(f"Invalid type: {type}")

        frame.save(save_path, "PNG")

    @Slot()
    def _on_heatmap_finished(self) -> None:
        """
        Handles the event when heatmap generation is finished by creating an MP4. - Generated by OpenAI's GPT 5.5
        """
        name = "tmp_heatmap.mp4"
        path = os.path.join(self._tmp_heatmap_path, name)
        fps = 30

        self._mp4_from_png_dir("heatmap", name, fps)

    def _mp4_from_png_dir(self, type: str, name: str, fps: int) -> None:
        """
        Creates an MP4 video from a directory of PNG images. - Generated by OpenAI's GPT 5.5

        :param type: The type of images ("heatmap" or "stream").
        :param name: The output file name.
        :param fps: Frames per second for the output video.
        """
        if type == "heatmap":
            dir_path = self._tmp_heatmap_path
            images = [file for file in os.listdir(dir_path) if file.endswith(".png")]
            images.sort(key=lambda x: int(x.split("_")[2]))

            frame = cv2.imread(os.path.join(dir_path, images[0]))
            height = frame.shape[0]
            width = frame.shape[1]

            writer = cv2.VideoWriter.fourcc(*"mp4v")
            output_path = os.path.join(dir_path, name)
            video = cv2.VideoWriter(output_path, writer, fps, (width, height))

            for image in images:
                path = os.path.join(dir_path, image)
                data = cv2.imread(path)

                if data is not None:
                    video.write(data)

            video.release()

            for image in images:
                file_path = os.path.join(dir_path, image)
                os.remove(file_path)

    @property
    def home_page(self) -> HomePage | None:
        """
        Retrieves the home page object associated with this instance. The home page
        object could be None if no home page is set. - Generated by OpenAI's GPT 5.5

        :return: The home page object if present; otherwise, None
        :rtype: HomePage | None
        """
        return self._home_page
    @home_page.setter
    def home_page(self, page: HomePage | None) -> None:
        """
        Sets the home page attribute and updates associated values.

        This method sets the home page of the application and triggers updates
        to internal preview settings and project count based on the provided
        HomePage instance. - Generated by OpenAI's GPT 5.5

        :param page: The HomePage instance to associate as the current
                     home page. Can be set to None to clear the home page.
        :type page: HomePage | None
        """
        self._home_page = page
        self._update_previews()
        self._projects_count = self._home_page.project_count
        self._update_home_ini()

    def _update_home_ini(self) -> None:
        """
        Updates the home page with values from the INI configuration. - Generated by OpenAI's GPT 5.5
        """
        self._ini_config.read(self._ini_path)

        allocation = self._ini_config.getint("General", "memory_allocation")

        self._home_page.allocation_value = allocation

    @property
    def current_project( self ) -> ProjectPage | None:
        return self._current_project
    @current_project.setter
    def current_project( self , project: ProjectPage | None):
        if self._current_project:
            self._current_project.deleteLater()

        self._current_project = project
