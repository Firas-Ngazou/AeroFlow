from PySide6.QtWidgets import QWidget, QFrame

class QVSeperator(QFrame):
    """
    A vertical line separator for UI layouts.

    I use this frame when I need a clean visual break between adjacent toolbar items
    or buttons without adding unnecessary complexity to the layout.

    - Generated by Gemini
    """
    def __init__(self, parent: QWidget | None = None) -> None:
        """
        Initializes a vertical separator with a fixed height and sunken relief.

        :param parent: The parent widget container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)
        self.frame_shape = QFrame.Shape.VLine
        self.frame_shadow = QFrame.Shadow.Sunken
        self.set_fixed_height(16)


