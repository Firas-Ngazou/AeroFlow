class BarStatus(Enum):
    """
    Enumeration representing the discrete execution states of a background process.

    I use this to keep the UI and the underlying threads perfectly synchronized without relying
    on raw strings or arbitrary integers. IDLE means ready, RUNNING means active execution,
    and FINISHED triggers the final UI updates.

    "State management is the backbone of any responsive user interface." - Gemini
    """
    IDLE = 0
    RUNNING = 1
    FINISHED = 2

class QProgressPoint(QWidget):
    """
    A minimalist visual indicator for tracking the current operational state.

    I designed this to provide immediate visual feedback via a color-coded LED-style point.
    It maps directly to the BarStatus enum, swapping CSS background colors dynamically
    to indicate idle (red), running (yellow), or finished (green) states.

    :ivar _point_frame: The inner colored frame acting as the visual indicator.
    :type _point_frame: QFrame
    :ivar _status: The current status of the tracked task.
    :type _status: BarStatus

    "Clarity in UI design means the user never has to guess what the system is doing." - Gemini
    """
    def __init__(self, parent: QWidget | None = None) -> None:
        """
        Initializes the point indicator and establishes its default idle styling.

        :param parent: The parent widget layout. Defaults to None.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._idle_qss: str = """background-color: #BC6E6E; border-radius: 10px;""" # Red
        self._running_qss: str = """background-color: #E4B653; border-radius: 10px;""" # Yellow
        self._finished_qss: str = """background-color: #8DB182; border-radius: 10px;""" # Green

        background_frame = QFrame()
        background_frame.set_property("class", "progress_point_background")
        background_frame.set_fixed_height(30)
        background_frame.set_fixed_width(30)

        self._point_frame = QFrame()
        self._point_frame.style_sheet = self._idle_qss
        self._point_frame.set_fixed_height(20)
        self._point_frame.set_fixed_width(20)

        self._status: BarStatus = BarStatus.IDLE

        self._primary_layout = QHBoxLayout(background_frame)
        self._primary_layout.add_widget(self._point_frame)
        self._primary_layout.set_contents_margins(0, 0, 0, 0)

        root_layout = QVBoxLayout(self)
        root_layout.add_widget(background_frame)
        root_layout.set_contents_margins(0, 0, 0, 0)

    @property
    def status(self) -> BarStatus:
        """
        Retrieves the current execution status tied to this visual point.

        :return: The active BarStatus enum value.
        :rtype: BarStatus

        - Generated by Gemini
        """
        return self._status

    @status.setter
    def status(self, value: BarStatus) -> None:
        """
        Updates the status and immediately triggers a CSS color swap on the point frame.

        :param value: The new state to transition into.
        :type value: BarStatus
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._status = value
        if self._status == BarStatus.IDLE:
            self._point_frame.style_sheet = self._idle_qss
        elif self._status == BarStatus.RUNNING:
            self._point_frame.style_sheet = self._running_qss
        elif self._status == BarStatus.FINISHED:
            self._point_frame.style_sheet = self._finished_qss

class QProgressBar(QWidget):
    """
    A custom progress tracking component tailored to the application's aesthetic.

    Instead of relying on default OS progress bars, I built this to match the specific
    visual language of the analysis window. It dynamically calculates its fill width based on
    a percentage and enforces a minimum pixel width so the border-radius styling doesn't break
    at low values.

    :ivar _bar_length: The absolute pixel width of the progress track.
    :type _bar_length: int
    :ivar _fill_percentage: The current completion percentage (0-100).
    :type _fill_percentage: int
    :ivar _min_filling: The minimum pixel width required to preserve rounded corners.
    :type _min_filling: int

    "A good progress bar builds trust by making backend work transparent to the user." - Gemini
    """
    def __init__(self, parent: QWidget | None = None) -> None:
        """
        Constructs the progress bar layout, connecting the status label, point indicator,
        and the dynamically resizing fill frame.

        :param parent: Optional QWidget that acts as the parent container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._bar_length: int = 440
        self._fill_percentage: int = 0
        self._min_filling: int = 6 # Under that, filling's edges will be squared

        # Colors
        self._idle_qss: str = """background-color: #BC6E6E; border-radius: 10px;"""  # Red
        self._running_qss: str = """background-color: #E4B653; border-radius: 10px;"""  # Yellow
        self._finished_qss: str = """background-color: #8DB182; border-radius: 10px;"""  # Green

        self._status: BarStatus = BarStatus.IDLE

        # Backgrounds
        background_frame = QFrame()
        background_frame.set_fixed_height(30)
        background_frame.set_property("class", "light_analysis_frame")

        self._bar_frame = QFrame()
        self._bar_frame.set_fixed_width(self._bar_length)
        self._bar_frame.set_fixed_height(30)
        self._bar_frame.set_property("class", "dark_analysis_frame")

        # The filling
        self._fill_frame = QFrame()
        self._fill_frame.set_fixed_width(int(self._fill_percentage*((self._bar_length-6)/100)))
        self._fill_frame.set_fixed_height(24)
        self._fill_frame.style_sheet = self._idle_qss

        bar_layout = QHBoxLayout(self._bar_frame)
        bar_layout.add_widget(self._fill_frame, alignment=Qt.AlignmentFlag.AlignLeft)
        bar_layout.set_contents_margins(2, 2, 2, 2)

        status_label = QLabel("Statut")
        status_label.set_property("class", "dark_text")
        status_label.font = QFont("JetBrains Mono", 12)

        self._progress_point = QProgressPoint()

        self._primary_layout = QHBoxLayout(background_frame)
        self._primary_layout.add_spacing(15)
        self._primary_layout.add_widget(status_label)
        self._primary_layout.add_spacing(10)
        self._primary_layout.add_widget(self._progress_point)
        self._primary_layout.add_widget(self._bar_frame)
        self._primary_layout.set_contents_margins(0, 0, 0, 0)

        root_layout = QVBoxLayout(self)
        root_layout.add_widget(background_frame)
        root_layout.set_contents_margins(0, 0, 0, 0)

    @property
    def fill_percentage(self) -> int:
        """
        Retrieves the current fill completion out of 100.

        :return: Current percentage as an integer.
        :rtype: int

        - Generated by Gemini
        """
        return self._fill_percentage

    @fill_percentage.setter
    def fill_percentage(self, value: int) -> None:
        """
        Updates the visual fill of the progress bar based on the incoming percentage.

        It automatically bounds the width using the `_min_filling` threshold to maintain
        UI integrity, and delegates the color state updates (idle, running, finished) based
        on the new value.

        :param value: The new progress completion percentage.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if 0 < value < self._min_filling:
            value = self._min_filling

        self._fill_percentage = value
        self._fill_frame.set_fixed_width(int(self._fill_percentage*((self._bar_length-6)/100)))

        if self._fill_percentage >= 100:
            self.status = BarStatus.FINISHED
        elif self._fill_percentage > 0:
            self.status = BarStatus.RUNNING
        else:
            self.status = BarStatus.IDLE

    @property
    def status(self) -> BarStatus:
        """
        Retrieves the active state enum governing the bar's styling.

        :return: The current BarStatus enum.
        :rtype: BarStatus

        - Generated by Gemini
        """
        return self._status

    @status.setter
    def status(self, value: BarStatus) -> None:
        """
        Forces a state transition on both the horizontal bar fill and the nested progress point.

        :param value: The new BarStatus state to adopt.
        :type value: BarStatus
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._status = value
        if self._status == BarStatus.IDLE:
            self._fill_frame.style_sheet = self._idle_qss
        elif self._status == BarStatus.RUNNING:
            self._fill_frame.style_sheet = self._running_qss
        elif self._status == BarStatus.FINISHED:
            self._fill_frame.style_sheet = self._finished_qss
        self._progress_point.status = value