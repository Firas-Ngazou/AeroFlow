from enum import Enum

from PySide6.QtCore import Qt
from PySide6.QtGui import QFont
from PySide6.QtWidgets import QWidget, QFrame, QHBoxLayout, QVBoxLayout, QLabel

class BarStatus(Enum):
    """
    Enumeration representing the status of a process or operation.

    This class defines a set of constants that represent different
    states for a process. It can be used to track or manage the
    state of an operation, providing an easy way to compare and
    transition between states. - Generated by OpenAI's GPT-5.4

    :cvar IDLE: The process is idle or not in progress.
    :cvar RUNNING: The process is actively running.
    :cvar FINISHED: The process has completed execution.
    """
    IDLE = 0
    RUNNING = 1
    FINISHED = 2

class QProgressPoint(QWidget):
    """
    Represents a customizable progress point widget.

    The QProgressPoint widget is designed to visually represent the progress
    of a task using different states such as idle, running, and finished. The
    appearance of the widget changes based on the current state, which is reflected
    by updating its background color and related styles. - Generated by OpenAI's GPT-5.4

    :ivar _point_frame: The inner frame that visually represents the progress point.
    :type _point_frame: QFrame
    :ivar _status: Current status of the progress point, indicating the state
        of the task (e.g., idle, running, or finished).
    :type _status: BarStatus
    """
    def __init__(self, parent: QWidget | None = None):
        """
        Represents a custom widget showing a progress point visual element. This widget
        consists of an outer frame and an inner point that indicates different statuses
        (e.g., idle, running, finished) through color-coded visual cues. - Generated by OpenAI's GPT-5.4

        Attributes:
            _status (BarStatus): The current status of the progress point.

        :param parent: The parent widget for this progress point. Defaults to None.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        self._idle_qss = """background-color: #BC6E6E; border-radius: 10px;""" # Red
        self._running_qss = """background-color: #E4B653; border-radius: 10px;""" # Yellow
        self._finished_qss = """background-color: #8DB182; border-radius: 10px;""" # Green

        background_frame = QFrame()
        background_frame.setProperty("class", "progress_point_background")
        background_frame.setFixedSize(30, 30)

        self._point_frame = QFrame()
        self._point_frame.setStyleSheet(self._idle_qss)
        self._point_frame.setFixedSize(20, 20)

        self._status: BarStatus = BarStatus.IDLE

        self._primary_layout = QHBoxLayout(background_frame)
        self._primary_layout.addWidget(self._point_frame)
        self._primary_layout.setContentsMargins(0, 0, 0, 0)

        root_layout = QVBoxLayout(self)
        root_layout.addWidget(background_frame)
        root_layout.setContentsMargins(0, 0, 0, 0)

    @property
    def status(self) -> BarStatus:
        return self._status

    @status.setter
    def status(self, value: BarStatus):
        self._status = value
        if self._status == BarStatus.IDLE:
            self._point_frame.setStyleSheet(self._idle_qss)
        elif self._status == BarStatus.RUNNING:
            self._point_frame.setStyleSheet(self._running_qss)
        elif self._status == BarStatus.FINISHED:
            self._point_frame.setStyleSheet(self._finished_qss)

class QProgressBar(QWidget):
    """
    Represents a custom progress bar widget.

    This class defines a customizable progress bar suitable for visualizing different
    statuses and filling progress. The widget is designed with distinctive colors for
    idle, running, and finished states and allows straightforward integration into a
    PyQt or PySide application. The progress bar's appearance and behavior can be
    further customized as needed for specific purposes. - Generated by OpenAI's GPT-5.4

    :ivar _bar_length: Specifies the total length of the progress bar.
    :type _bar_length: int

    :ivar _fill_percentage: Represents the current fill percentage of the progress bar.
    :type _fill_percentage: int

    :ivar _min_filling: Defines the minimum width for the filled portion of the progress
        bar, below which the filling's edges remain squared.
    :type _min_filling: int
    """
    def __init__(self, parent: QWidget | None = None):
        """
        Initializes a custom UI component designed for visualizing progress with a bar-style
        representation. This component sets up the layout of a background frame, status label,
        progress bar, and status point indicator. The progress bar includes a filling element
        that dynamically adjusts its width according to the fill percentage. The component
        also manages three visual states: idle, running, and finished, each represented by
        specific colors. - Generated by OpenAI's GPT-5.4

        :param parent: Optional QWidget that acts as the parent for this component.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        self._bar_length = 440
        self._fill_percentage = 0
        self._min_filling = 6 # Under that, filling's edges will be squared

        # Colors
        self._idle_qss = """background-color: #BC6E6E; border-radius: 10px;"""  # Red
        self._running_qss = """background-color: #E4B653; border-radius: 10px;"""  # Yellow
        self._finished_qss = """background-color: #8DB182; border-radius: 10px;"""  # Green

        self._status: BarStatus = BarStatus.IDLE

        # Backgrounds
        background_frame = QFrame()
        background_frame.setFixedHeight(30)
        background_frame.setProperty("class", "light_analysis_frame")

        self._bar_frame = QFrame()
        self._bar_frame.setFixedWidth(self._bar_length)
        self._bar_frame.setFixedHeight(30)
        self._bar_frame.setProperty("class", "dark_analysis_frame")

        # The filling
        self._fill_frame = QFrame()
        self._fill_frame.setFixedWidth(int(self._fill_percentage*((self._bar_length-6)/100)))
        self._fill_frame.setFixedHeight(24)
        self._fill_frame.setStyleSheet(self._idle_qss)

        bar_layout = QHBoxLayout(self._bar_frame)
        bar_layout.addWidget(self._fill_frame, alignment=Qt.AlignmentFlag.AlignLeft)
        bar_layout.setContentsMargins(2, 2, 2, 2)

        status_label = QLabel("Statut")
        status_label.setProperty("class", "dark_text")
        status_label.setFont(QFont("JetBrains Mono", 12))

        self._progress_point = QProgressPoint()

        self._primary_layout = QHBoxLayout(background_frame)
        self._primary_layout.addSpacing(15)
        self._primary_layout.addWidget(status_label)
        self._primary_layout.addSpacing(10)
        self._primary_layout.addWidget(self._progress_point)
        self._primary_layout.addWidget(self._bar_frame)
        self._primary_layout.setContentsMargins(0, 0, 0, 0)

        root_layout = QVBoxLayout(self)
        root_layout.addWidget(background_frame)
        root_layout.setContentsMargins(0, 0, 0, 0)

    @property
    def fill_percentage(self) -> int:
        return self._fill_percentage

    @fill_percentage.setter
    def fill_percentage(self, value: int):
        if 0 < value < self._min_filling:
            value = self._min_filling

        self._fill_percentage = value
        self._fill_frame.setFixedWidth(int(self._fill_percentage*((self._bar_length-6)/100)))

        if self._fill_percentage >= 100:
            self.status = BarStatus.FINISHED
        elif self._fill_percentage > 0:
            self.status = BarStatus.RUNNING
        else:
            self.status = BarStatus.IDLE

    @property
    def status(self) -> BarStatus:
        return self._status

    @status.setter
    def status(self, value: BarStatus):
        self._status = value
        if self._status == BarStatus.IDLE:
            self._fill_frame.setStyleSheet(self._idle_qss)
        elif self._status == BarStatus.RUNNING:
            self._fill_frame.setStyleSheet(self._running_qss)
        elif self._status == BarStatus.FINISHED:
            self._fill_frame.setStyleSheet(self._finished_qss)
        self._progress_point.status = value
