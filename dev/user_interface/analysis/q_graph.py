from PySide6.QtCore import QPoint, Qt, QPointF, QMargins
from PySide6.QtGui import QPen, QColor, QBrush, QFont, QPainter
from PySide6.QtWidgets import QWidget, QLabel, QApplication, QVBoxLayout
from PySide6.QtCharts import QChart, QChartView, QLineSeries, QValueAxis


class QCustomGraph(QChartView):
    """
    A custom Qt charting widget designed to dynamically plot 2D coordinate data.

    It handles its own internal point sorting, axis scaling, and layout configuration,
    providing a clean, dark-themed line graph tailored for real-time telemetry updates.

    - Generated by Gemini
    """

    def __init__(self, parent: QWidget | None = None) -> None:
        """
        Initializes the graph widget, configuring the axes, line series, and aesthetics.

        Strips away default margins, grid lines, and legends to maximize the usable plotting
        area, and enforces a custom JetBrains Mono font for consistency.

        :param parent: The parent widget container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        self._chart = QChart()
        super().__init__(self._chart, parent)

        # Setup
        self._chart.background_visible = False
        self._chart.margins = QMargins(0, 0, 0, 0)
        self._chart.layout.set_contents_margins(0, 0, 0, 0)
        self._chart.legend().hide()
        self.set_render_hint(QPainter.RenderHint.Antialiasing)
        self._title: str = " - "

        # Series
        self._series = QLineSeries()
        self._chart.add_series(self._series)
        self._chart.title = self._title

        # Axis
        self._axis_x = QValueAxis()
        self._axis_y = QValueAxis()
        self._axis_x.set_grid_line_visible(False)
        self._axis_y.set_grid_line_visible(False)

        # Font
        font = QFont("JetBrains Mono", 7)
        font.bold = True
        self._axis_x.labels_font = font
        self._axis_y.labels_font = font

        # Colors
        axis_pen = QPen(QColor(245, 245, 245, 255))
        axis_pen.set_width(2)
        self._axis_x.line_pen = axis_pen
        self._axis_y.line_pen = axis_pen
        self._axis_x.labels_color = QColor(245, 245, 245, 255)
        self._axis_y.labels_color = QColor(245, 245, 245, 255)

        # Grid pen
        grad_pen = QPen(QColor(245, 245, 245, 255))
        self._axis_x.grid_line_pen = grad_pen
        self._axis_y.grid_line_pen = grad_pen

        self._chart.add_axis(self._axis_x, Qt.AlignmentFlag.AlignBottom)
        self._chart.add_axis(self._axis_y, Qt.AlignmentFlag.AlignLeft)

        self._series.attach_axis(self._axis_x)
        self._series.attach_axis(self._axis_y)

        # Line pen
        self._line_pen = QPen(QColor(255, 142, 142, 255))
        self._line_pen.set_width(2)
        self._series.set_pen(self._line_pen)

        self._points: list[QPointF] = []
        self._g_height: int = 300
        self._g_width: int = 600
        self._offset: int = 50

    def add_point(self, point: QPointF) -> None:
        """
        Injects a new coordinate point into the internal dataset.

        Automatically sorts the series by the X-axis, rebuilds the line, and dynamically
        scales the physical bounds of both axes to keep the data centered and visible.

        :param point: The 2D coordinate to plot.
        :type point: QPointF
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._points.append(point)
        self._points.sort(key = lambda p: p.x())

        self._series.clear()
        for p in self._points:
            self._series.append(QPointF(p.x(), p.y()))

        if self._points:
            x_min = min(p.x() for p in self._points)
            x_max = max(p.x() for p in self._points)
            y_min = min(p.y() for p in self._points)
            y_max = max(p.y() for p in self._points)

            if x_min == x_max:
                self._axis_x.set_range(x_min - 1, x_max + 1)
            else:
                self._axis_x.set_range(x_min, x_max)

            if y_min == y_max:
                self._axis_y.set_range(y_min - 1, y_max + 1)
            else:
                self._axis_y.set_range(y_min, y_max)

    def reset(self) -> None:
        """
        Purges all internal coordinate data and resets the axis ranges back to their idle bounds.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._points.clear()
        self._series.clear()
        self._axis_x.set_range(0, 10)
        self._axis_y.set_range(0, 10)

    @property
    def g_height(self) -> int:
        """
        Retrieves the configured absolute height of the graph widget.

        :return: The height in pixels.
        :rtype: int

        - Generated by Gemini
        """
        return self._g_height

    @g_height.setter
    def g_height(self, value: int) -> None:
        """
        Sets the fixed height of the widget and forces the internal chart to resize.

        :param value: The target height in pixels.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._g_height = value
        self.set_fixed_height(value)
        self._chart.resize(self.width, value)

    @property
    def g_width(self) -> int:
        """
        Retrieves the configured absolute width of the graph widget.

        :return: The width in pixels.
        :rtype: int

        - Generated by Gemini
        """
        return self._g_width

    @g_width.setter
    def g_width(self, value: int) -> None:
        """
        Sets the fixed width of the widget and forces the internal chart to resize.

        :param value: The target width in pixels.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._g_width = value
        self.set_fixed_width(value)
        self._chart.resize(value, self.height)

    @property
    def offset(self) -> int:
        """
        Retrieves the axis length offset factor.

        :return: The padding offset in pixels.
        :rtype: int

        - Generated by Gemini
        """
        return self._offset

    @offset.setter
    def offset(self, value: int) -> None:
        """
        Sets the axis length offset factor used in dynamic length calculations.

        :param value: The padding offset in pixels.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._offset = value

    @property
    def x_axis_len(self) -> int:
        """
        Computes the effective physical length of the X-axis by subtracting the offset.

        :return: The adjusted axis length in pixels.
        :rtype: int

        - Generated by Gemini
        """
        return self._g_width - self._offset

    @x_axis_len.setter
    def x_axis_len(self, value: int) -> None:
        """
        Recomputes and sets the total graph width based on the desired X-axis length and offset.

        :param value: The target X-axis length.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._g_width = value + self._offset
        self.set_fixed_width(self._g_width)
        self._chart.resize(self._g_width, self.height)

    @property
    def y_axis_len(self) -> int:
        """
        Computes the effective physical length of the Y-axis by adding the offset.

        :return: The adjusted axis length in pixels.
        :rtype: int

        - Generated by Gemini
        """
        return self._g_height + self._offset

    @y_axis_len.setter
    def y_axis_len(self, value: int) -> None:
        """
        Recomputes and sets the total graph height based on the desired Y-axis length and offset.

        :param value: The target Y-axis length.
        :type value: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._g_height = value + self._offset
        self.set_fixed_height(self._g_height)
        self._chart.resize(self.width, self._g_height)

    @property
    def title(self) -> str:
        """
        Retrieves the active title of the chart.

        :return: The chart title.
        :rtype: str

        - Generated by Gemini
        """
        return self._title

    @title.setter
    def title(self, value: str) -> None:
        """
        Sets the text displayed as the main title of the chart.

        :param value: The text to set as the title.
        :type value: str
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._title = value
        self._chart.title = value


