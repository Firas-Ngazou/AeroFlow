class QResultField(QWidget):
    """
    A custom UI component for AeroFlow to cleanly display key-value physics metrics.

    I got tired of messy standard layouts, so I built this two-tone frame system. The primary frame holds the
    metric label, and the secondary nested frame holds the live simulation value. It keeps the telemetry
    looking crisp and highly readable over the canvas.

    :ivar _result_name: QLabel for the metric name.
    :type _result_name: QLabel
    :ivar _result_value: QLabel for the live metric data.
    :type _result_value: QLabel

    - Generated by Gemini
    """

    def __init__(self, text: str, parent: QWidget | None = None):
        """
        Initializes the dual-frame key-value layout.

        I locked the heights at 30px so the grid doesn't wobble when values change rapidly during
        the Lattice-Boltzmann execution. We use JetBrains Mono for a proper monospaced developer feel.

        :param text: The text to display as the metric label.
        :type text: str
        :param parent: The parent widget container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        primary_field_frame = QFrame()
        primary_field_frame.set_fixed_height(30)
        primary_field_frame.set_property("class", "light_analysis_frame")

        secondary_field_frame = QFrame()
        secondary_field_frame.set_fixed_height(30)
        secondary_field_frame.set_property("class", "dark_analysis_frame")

        self._result_name = QLabel(text)
        self._result_name.set_property("class", "dark_text")
        self._result_name.font = QFont("JetBrains Mono", 8)

        self._result_value = QLabel(" - ")
        self._result_value.font = QFont("JetBrains Mono", 8)

        self._primary_layout = QHBoxLayout(primary_field_frame)
        self._primary_layout.set_contents_margins(0, 0, 0, 0)

        self._secondary_field_layout = QHBoxLayout(secondary_field_frame)
        self._secondary_field_layout.add_widget(self._result_value)
        self._secondary_field_layout.set_contents_margins(10, 2, 10, 2)

        self._primary_layout.add_spacing(10)
        self._primary_layout.add_widget(self._result_name)
        self._primary_layout.add_spacing(10)
        self._primary_layout.add_widget(secondary_field_frame)

        root_layout = QVBoxLayout(self)
        root_layout.add_widget(primary_field_frame)
        root_layout.set_contents_margins(0, 0, 0, 0)

    @property
    def result_value(self) -> str:
        """
        Retrieves the text currently displayed in the secondary dark frame.

        :return: The string value of the metric.
        :rtype: str

        - Generated by Gemini
        """
        return self._result_value.text

    @result_value.setter
    def result_value(self, value: str) -> None:
        """
        Injects a new value string into the widget's display label.

        :param value: The new text to display.
        :type value: str

        - Generated by Gemini
        """
        self._result_value.text = value


class QOptimizationAnalysis(QWidget):
    """
    The dedicated tab for tracking shape optimization progress in AeroFlow.

    I built this to monitor the fitness loop. It tracks how much better our generated shapes are getting
    over time by plotting fitness per iteration and monitoring the projected drag and lift improvements.

    - Generated by Gemini
    """

    def __init__(self, parent: QWidget | None = None):
        """
        Sets up the optimization grid and binds the live-updating QCustomGraph.

        :param parent: The parent tab widget.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._primary_layout = QVBoxLayout(self)

        self._performance_gain_field = QResultField("Gain de performance [%]")
        self._initial_projected_drag = QResultField("Traînée projetée [-]")
        self._initial_projected_lift = QResultField("Portance projetée [-]")

        self._gain_value = 0
        self._projected_drag = 0.0
        self._projected_lift = 0.0

        self._graph = QCustomGraph()
        self._graph.g_height = 150
        self._graph.title = "Fitness en fonction de l'itération"

        self._secondary_layout = QGridLayout()
        self._secondary_layout.add_widget(self._performance_gain_field, 0, 0)
        self._secondary_layout.add_widget(self._initial_projected_drag, 1, 0)
        self._secondary_layout.add_widget(self._initial_projected_lift, 0, 1)

        self._primary_layout.add_layout(self._secondary_layout)
        self._primary_layout.add_widget(self._graph)
        self._primary_layout.add_stretch()

    @property
    def gain_value(self) -> float | str:
        """
        Retrieves the current performance gain multiplier.

        :return: The stored gain value.
        :rtype: float | str

        - Generated by Gemini
        """
        return self._gain_value

    @gain_value.setter
    def gain_value(self, value: float | str) -> None:
        """
        Updates the performance gain and handles the float-to-string formatting for the UI.

        :param value: The percentage gain, or a reset string like ' - '.
        :type value: float | str

        - Generated by Gemini
        """
        self._gain_value = value
        if isinstance(value, str):
            self._performance_gain_field.result_value = value
            return
        self._performance_gain_field.result_value = f"{value:.2f}"

    @property
    def projected_drag(self) -> float | str:
        """
        Retrieves the internally tracked projected drag.

        :return: The stored projected drag.
        :rtype: float | str

        - Generated by Gemini
        """
        return self._projected_drag

    @projected_drag.setter
    def projected_drag(self, value: float | str) -> None:
        """
        Updates the projected drag value and formats it to two decimal places.

        :param value: The drag coefficient prediction.
        :type value: float | str

        - Generated by Gemini
        """
        self._projected_drag = value
        if isinstance(value, str):
            self._initial_projected_drag.result_value = value
            return
        self._initial_projected_drag.result_value = f"{value:.2f}"

    @property
    def projected_lift(self) -> float | str:
        """
        Retrieves the internally tracked projected lift.

        :return: The stored projected lift.
        :rtype: float | str

        - Generated by Gemini
        """
        return self._projected_lift

    @projected_lift.setter
    def projected_lift(self, value: float | str) -> None:
        """
        Updates the projected lift value and formats the display.

        :param value: The lift coefficient prediction.
        :type value: float | str

        - Generated by Gemini
        """
        self._projected_lift = value
        if isinstance(value, str):
            self._initial_projected_lift.result_value = value
            return
        self._initial_projected_lift.result_value = f"{value:.2f}"

    def add_graph_point(self, point: QPointF) -> None:
        """
        Passes a new 2D coordinate directly into our custom fitness graph.

        :param point: The X (iteration) and Y (fitness) coordinate.
        :type point: QPointF

        - Generated by Gemini
        """
        self._graph.add_point(point)

    def reset_graph(self) -> None:
        """
        Purges the graph data and resets the optimization text fields back to their idle states.

        - Generated by Gemini
        """
        self._graph.reset()
        self.gain_value = " - "
        self.projected_drag = " - "
        self.projected_lift = " - "


