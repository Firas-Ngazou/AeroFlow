class QResultField(QWidget):
    """
    Represents a custom QWidget combining text labels and layouts for displaying
    results in a formatted and styled manner.

    QResultField provides a graphical layout with two main frames: a primary
    frame containing the result name and a secondary frame containing the result
    value. This widget is intended to be used for structured display of results
    in complex UI designs. - Generated by OpenAI's GPT-5.4

    :ivar text: The text to be displayed as the name of the result.
    :type text: str
    """
    def __init__(self, text: str, parent: QWidget | None = None):
        """
        A custom widget that displays a labeled result with primary and secondary field
        layouts. The primary layout contains a result name, while the secondary field
        layout contains a result value. - Generated by OpenAI's GPT-5.4

        :ivar _result_name: QLabel widget displaying the name of the result. It uses
            the "dark_text" property and a "JetBrains Mono" font with size 8.
        :ivar _result_value: QLabel widget displaying the value of the result. It uses
            a "JetBrains Mono" font with size 8.
        :ivar _primary_layout: QHBoxLayout used for the primary field frame, containing
            the result name and secondary field frame.
        :ivar _secondary_field_layout: QHBoxLayout used for the secondary field frame,
            containing the result value.

        :param text: The text to display as the result name in the widget.
        :type text: str
        :param parent: The parent widget, which can be set to None for no parent.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        primary_field_frame = QFrame()
        primary_field_frame.setFixedHeight(30)
        primary_field_frame.setProperty("class", "light_analysis_frame")

        secondary_field_frame = QFrame()
        secondary_field_frame.setFixedHeight(30)
        secondary_field_frame.setProperty("class", "dark_analysis_frame")

        self._result_name = QLabel(text)
        self._result_name.setProperty("class", "dark_text")
        self._result_name.setFont(QFont("JetBrains Mono", 8))

        self._result_value = QLabel("Place Holder")
        self._result_value.setFont(QFont("JetBrains Mono", 8))

        self._primary_layout = QHBoxLayout(primary_field_frame)
        self._primary_layout.setContentsMargins(0, 0, 0, 0)

        self._secondary_field_layout = QHBoxLayout(secondary_field_frame)
        self._secondary_field_layout.addWidget(self._result_value)
        self._secondary_field_layout.setContentsMargins(10, 2, 10, 2)

        self._primary_layout.addSpacing(10)
        self._primary_layout.addWidget(self._result_name)
        self._primary_layout.addSpacing(10)
        self._primary_layout.addWidget(secondary_field_frame)

        root_layout = QVBoxLayout(self)
        root_layout.addWidget(primary_field_frame)
        root_layout.setContentsMargins(0, 0, 0, 0)

