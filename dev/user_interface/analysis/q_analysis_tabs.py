class QAnalysisWidget(QFloatingWidget):
    """
    Provides a specialized widget for analysis purposes, particularly optimization and results analysis.

    This widget is a subclass of QFloatingWidget and embeds multiple tabs for different analysis functionalities.
    It includes optimization and result analysis tabs and applies custom styling and layout configurations.
     - Generated by OpenAI's GPT-5.4

    :ivar saved_position: Stores the initial position of the widget.
    :type saved_position: QPoint
    """
    def __init__(self, initial_position: QPoint, parent: QWidget | None = None):
        """
        Initializes the class with the specified initial position and parent widget. - Generated by OpenAI's GPT-5.4

        :param initial_position: The initial position for the widget.
        :type initial_position: QPoint
        :param parent: The parent widget for this instance. Optional.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        self.setMinimumWidth(600)
        self.setMinimumHeight(200)

        # Progress bar
        self._progress_bar = QProgressBar()
        self._info_label = QLabel("  Durée estimée : 00:00:00")
        self._info_label.setFont(QFont("JetBrains Mono", 9))

        self.saved_position = initial_position

        self._tabs = QTabWidget()
        self._tabs.setProperty("class", "analysis_tabs")
        self._tabs.tabBar().setProperty("class", "analysis_tabs")

        self._optimization_tab = QOptimizationAnalysis()
        self._tabs.addTab(self._optimization_tab, "Optimisation")

        self._results_tab = QResultAnalysis()
        self._tabs.addTab(self._results_tab, "Résultats")

        self._tabs.setFont(QFont("JetBrains Mono", 12))

        self._v_box_layout.addWidget(self._progress_bar, alignment=Qt.AlignmentFlag.AlignTop)
        self._v_box_layout.addWidget(self._info_label, alignment=Qt.AlignmentFlag.AlignTop)
        self._v_box_layout.addWidget(self._tabs)

    @property
    def simulation_progress(self):
        return self._progress_bar.fill_percentage

    @simulation_progress.setter
    def simulation_progress(self, value: int):
        self._progress_bar.fill_percentage = value

    @property
    def simulation_info_label(self):
        return self._info_label.text()

    @simulation_info_label.setter
    def simulation_info_label(self, value: str):
        self._info_label.setText(value)

    @Slot(str)
    def set_sim_info_label(self, value: str):
        self.simulation_info_label = value