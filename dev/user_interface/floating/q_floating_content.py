class QFloatingContent(QFloatingWidget):
    """
    A base container for floating UI components, providing a title and standard action buttons.

    This class provides a consistent look and feel for modal-like floating widgets in AeroFlow,
    handling the title label styling and the standard "Apply/Cancel" button row at the bottom.

    :ivar _title_label: Display label for the widget title.
    :ivar _left_pb: The primary action button (e.g., Apply).
    :ivar _right_pb: The secondary action button (e.g., Cancel).

    - Generated by Gemini
    """

    def __init__(self, title: str, parent: QWidget | None = None) -> None:
        """
        Constructs the floating content layout with a title and action button row.

        :param title: The title string to display in the header.
        :type title: str
        :param parent: The parent widget container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._title_label = QLabel(title)

        self.minimum_width = 300
        self.minimum_height = 150

        font = QFont("JetBrains Mono", 12)
        font.bold = True
        self._title_label.font = font

        self._title_label.alignment = Qt.AlignmentFlag.AlignCenter

        self._left_pb = QFloatingSettingPB("Appliquer")
        self._right_pb = QFloatingSettingPB("Annuler", fill = False)

        self._lower_h_layout = QHBoxLayout()
        self._lower_h_layout.add_stretch()
        self._lower_h_layout.add_widget(self._left_pb, alignment = Qt.AlignmentFlag.AlignRight)
        self._lower_h_layout.add_widget(self._right_pb, alignment = Qt.AlignmentFlag.AlignRight)

        self._v_box_layout.add_widget(self._title_label, alignment = Qt.AlignmentFlag.AlignTop)
        self._v_box_layout.add_stretch()
        self._v_box_layout.add_layout(self._lower_h_layout)


class QFloatingWarning(QFloatingContent):
    """
    A specialized confirmation dialog used for critical user alerts or destructive actions.

    Extends QFloatingContent to include a multi-line warning message, emitting signals
    for user confirmation (Yes) or rejection (No).

    :ivar yesPressed: Emitted when the user confirms the action.
    :ivar noPressed: Emitted when the user rejects the action.

    - Generated by Gemini
    """
    yesPressed = Signal()
    noPressed = Signal()

    def __init__(self, initial_position: QPoint, title: str, warning_text: str, parent: QWidget | None = None) -> None:
        """
        Initializes the warning dialog, calculating the screen-space offset for modal centering.

        :param initial_position: The reference coordinate for centering the dialog.
        :param title: The warning title.
        :param warning_text: The body text describing the warning.
        :param parent: The parent widget.

        - Generated by Gemini
        """
        super().__init__(title, parent)

        center_point = QPoint(int(initial_position.x() - self.width / 2 - 40),
                              int(initial_position.y() - self.height / 2))
        self.saved_position = center_point

        self._left_pb.text = "Oui"
        self._right_pb.text = "Non"

        self._warning_text: str = warning_text
        self._warning_label: QLabel = QLabel(self._warning_text)
        self._warning_label.font = QFont("JetBrains Mono", 9)
        self._v_box_layout.insert_widget(2, self._warning_label, alignment = Qt.AlignmentFlag.AlignCenter)

        self._left_pb.clicked.connect(self.yesPressed)
        self._right_pb.clicked.connect(self.noPressed)

    @property
    def warning_text(self) -> str:
        """
        Retrieves the current warning message text.

        :return: The warning description.
        :rtype: str

        - Generated by Gemini
        """
        return self._warning_text

    @warning_text.setter
    def warning_text(self, text: str) -> None:
        """
        Updates the warning message label dynamically.

        :param text: The new warning message.
        :type text: str

        - Generated by Gemini
        """
        self._warning_text = text
        self._warning_label.text = self._warning_text


class QFloatingSlider(QFloatingContent):
    """
    A dedicated floating widget wrapper for a slider component.

    Provides a clean UI container for slider-based inputs, handling the commit (Apply)
    and rollback (Cancel) logic automatically.

    :ivar applyPressed: Emits the chosen slider integer value.
    :ivar cancelPressed: Emitted when the user discards changes.

    - Generated by Gemini
    """
    applyPressed = Signal(int)
    cancelPressed = Signal()

    def __init__(self, title: str, parent: QWidget | None = None) -> None:
        """
        Initializes the slider container and links the control buttons to the slider's value range.

        :param title: Header text for the slider.
        :param parent: Parent widget container.

        - Generated by Gemini
        """
        super().__init__(title, parent)

        self._left_pb.text = "Appliquer"
        self._right_pb.text = "Annuler"

        self._slider_group = QSliderGroup("")

        self._v_box_layout.insert_widget(2, self._slider_group, alignment = Qt.AlignmentFlag.AlignCenter)

        self._left_pb.clicked.connect(lambda: self.applyPressed.emit(self._slider_group.value))
        self._right_pb.clicked.connect(self.cancelPressed)

        # Revert to default on cancel
        self.cancelPressed.connect(lambda: self._slider_group.set_value(self._slider_group.default_value))

    @property
    def maximum(self) -> int:
        """
        Retrieves the current maximum value bound of the slider.

        :return: Maximum slider value.
        :rtype: int

        - Generated by Gemini
        """
        return self._slider_group.maximum

    @maximum.setter
    def maximum(self, value: int) -> None:
        """
        Sets the maximum value bound of the slider.

        :param value: The new maximum.
        :type value: int

        - Generated by Gemini
        """
        self._slider_group.maximum = value

    @property
    def minimum(self) -> int:
        """
        Retrieves the current minimum value bound of the slider.

        :return: Minimum slider value.
        :rtype: int

        - Generated by Gemini
        """
        return self._slider_group.minimum

    @minimum.setter
    def minimum(self, value: int) -> None:
        """
        Sets the minimum value bound of the slider.

        :param value: The new minimum.
        :type value: int

        - Generated by Gemini
        """
        self._slider_group.minimum = value

    @property
    def value(self) -> int:
        """
        Retrieves the current slider value.

        :return: Current slider value.
        :rtype: int

        - Generated by Gemini
        """
        return self._slider_group.value

    @value.setter
    def value(self, value: int) -> None:
        """
        Sets the current slider value.

        :param value: The new slider value.
        :type value: int

        - Generated by Gemini
        """
        self._slider_group.value = value

    @property
    def single_step(self) -> int:
        """
        Retrieves the single step increment value for the slider.

        :return: Slider step count.
        :rtype: int

        - Generated by Gemini
        """
        return self._slider_group.single_step

    @single_step.setter
    def single_step(self, step: int) -> None:
        """
        Sets the single step increment value for the slider.

        :param step: The new step value.
        :type step: int

        - Generated by Gemini
        """
        self._slider_group.single_step = step

    @property
    def default_value(self) -> int:
        """
        Retrieves the configured default reset value of the slider.

        :return: Default value.
        :rtype: int

        - Generated by Gemini
        """
        return self._slider_group.default_value

    @default_value.setter
    def default_value(self, value: int) -> None:
        """
        Sets the default reset value of the slider.

        :param value: The default value.
        :type value: int

        - Generated by Gemini
        """
        self._slider_group.default_value = value