class QFloatingContent(QFloatingWidget):
    """
    A custom floating widget class for creating a user interface component with a
    title and associated buttons for "Apply" and "Cancel" actions.

    This class is used to display content in a structured layout with a title label
    and interactive buttons. It provides a customizable design, uses pre-defined
    fonts and alignments for the title, and maintains a clean layout. - Generated by OpenAI's GPT 5.5

    :ivar _title_label: Internal QLabel instance that displays the title of the widget.
    :ivar _left_pb: Internal QFloatingSettingPB button instance for the "Apply" action.
    :ivar _right_pb: Internal QFloatingSettingPB button instance for the "Cancel" action.
    :ivar _lower_h_layout: Internal QHBoxLayout instance managing the layout of the buttons.
    :ivar _v_box_layout: Internal QVBoxLayout instance managing the overall layout structure.
    """
    def __init__(self, title: str, parent: QWidget | None = None):
        super().__init__(parent)

        self._title_label = QLabel(title)

        font = QFont("JetBrains Mono", 12)
        font.setBold(True)
        self._title_label.setFont(font)

        self._title_label.setAlignment(Qt.AlignmentFlag.AlignCenter)

        self._left_pb = QFloatingSettingPB("Appliquer")
        self._right_pb = QFloatingSettingPB("Annuler", fill=False)

        self._lower_h_layout = QHBoxLayout()
        self._lower_h_layout.addStretch()
        self._lower_h_layout.addWidget(self._left_pb, alignment=Qt.AlignmentFlag.AlignRight)
        self._lower_h_layout.addWidget(self._right_pb, alignment=Qt.AlignmentFlag.AlignRight)

        self._v_box_layout.addWidget(self._title_label, alignment=Qt.AlignmentFlag.AlignTop)
        self._v_box_layout.addStretch()
        self._v_box_layout.addLayout(self._lower_h_layout)

