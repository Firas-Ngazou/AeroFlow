from PySide6.QtCore import Qt, Signal, QPoint
from PySide6.QtGui import QFont, QShowEvent, QHideEvent
from PySide6.QtWidgets import QWidget, QHBoxLayout, QLabel

from dev.user_interface.floating.q_floating_widget import QFloatingWidget
from dev.user_interface.components.q_buttons import QFloatingSettingPB

class QFloatingContent(QFloatingWidget):
    """
    Represents a floating content widget with a title and action buttons.

    The QFloatingContent class extends QFloatingWidget to provide a customizable
    floating user interface element with a title label and two buttons for actions.
    It is designed for scenarios where specific options need to be presented
    in a concise and easily accessible floating widget. - Generated by OpenAI's GPT-5.4

    :ivar _title_label: Label displaying the title of the floating content.
    :type _title_label: QLabel
    :ivar _apply_pb: Push button to confirm or apply an action.
    :type _apply_pb: QFloatingSettingPB
    :ivar _cancel_pb: Push button to cancel or discard an action.
    :type _cancel_pb: QFloatingSettingPB
    :ivar _lower_h_layout: Horizontal layout containing the action buttons.
    :type _lower_h_layout: QHBoxLayout
    """
    def __init__(self, title: str, parent: QWidget | None = None):
        """
        Constructor for the custom widget, initializing the title label, fonts, and layout elements.
         - Generated by OpenAI's GPT-5.4

        :param title: The text used to set as the title of the widget.
        :type title: str
        :param parent: The parent QWidget of this widget. If None, the widget will
            be created without a parent.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        self._title_label = QLabel(title)

        font = QFont("JetBrains Mono", 12)
        font.setBold(True)
        self._title_label.setFont(font)

        self._title_label.setAlignment(Qt.AlignmentFlag.AlignCenter)

        self._apply_pb = QFloatingSettingPB("Appliquer")
        self._cancel_pb = QFloatingSettingPB("Annuler", fill=False)

        self._lower_h_layout = QHBoxLayout()
        self._lower_h_layout.addStretch()
        self._lower_h_layout.addWidget(self._apply_pb, alignment=Qt.AlignmentFlag.AlignRight)
        self._lower_h_layout.addWidget(self._cancel_pb, alignment=Qt.AlignmentFlag.AlignRight)

        self._v_box_layout.addWidget(self._title_label, alignment=Qt.AlignmentFlag.AlignTop)
        self._v_box_layout.addStretch()
        self._v_box_layout.addLayout(self._lower_h_layout)

class QFloatingWarning(QFloatingContent):
    """
    Represents a floating warning element in the user interface.

    The QFloatingWarning class is a specialized widget intended for displaying
    warning messages to users. It inherits from QFloatingContent and supplements
    it with additional functionality tailored for warnings, such as customizable
    warning text and signal emission upon visibility changes. - Generated by OpenAI's GPT-5.4

    :ivar saved_position: The calculated position of the widget based on the
        initial position and its size.
    :type saved_position: QPoint
    :ivar warning_text: The text content displayed in the warning label. This
        attribute supports both getting and setting.
    :type warning_text: str
    """
    showing = Signal(bool)

    def __init__(self, initial_position: QPoint, title: str, warning_text: str, parent: QWidget | None = None):
        """
        Initializes an instance of a custom dialog with a warning message and specified positioning.

        This constructor sets up the minimum size of the dialog and calculates its centered
        position based on the given `initial_position`. A warning label displaying the
        `warning_text` is added to the layout of the dialog. - Generated by OpenAI's GPT-5.4

        :param initial_position: The initial position for centering the dialog, represented as
            a QPoint.
        :param title: The title of the dialog window.
        :param warning_text: The warning message to be shown in the dialog.
        :param parent: The parent widget for this dialog or None if no parent.
        """
        super().__init__(title, parent)
        self.setMinimumSize(300, 150)

        center_point = QPoint(int(initial_position.x() - self.width()/2 - 40), int(initial_position.y() - self.height()/2))
        self.saved_position = center_point

        self._warning_text = warning_text
        self._warning_label: QLabel = QLabel(self._warning_text)
        self._warning_label.setFont(QFont("JetBrains Mono", 9))
        self._v_box_layout.insertWidget(2, self._warning_label, alignment=Qt.AlignmentFlag.AlignCenter)

    @property
    def warning_text(self) -> str:
        """
        Provides access to a warning message in text format.

        This property returns the warning message stored in the object. It allows
        read-only access to the private attribute that contains the message. The
        message should provide all necessary information about the warning, ensuring
        clarity and ease of understanding. - Generated by OpenAI's GPT-5.4

        :rtype: str
        :return: The warning message as a string.
        """
        return self._warning_text
    @warning_text.setter
    def warning_text(self, text: str):
        """
        Sets the warning text of the warning label with the given text value. Updates the
        UI component associated with the warning label. - Generated by OpenAI's GPT-5.4

        :param text: The new warning text to display in the warning label.
        :type text: str
        """
        self._warning_text = text
        self._warning_label.setText(self._warning_text)

    def showEvent(self, event: QShowEvent) -> None:
        """
        Handles the event triggered when the widget is shown.

        This method is typically used to respond to the widget being displayed
        by emitting a signal with the relevant state. It ensures appropriate
        behavior and state synchronization when a show event occurs. - Generated by OpenAI's GPT-5.4

        :param event: The event object of type QShowEvent that contains
                      information related to the show event.
        :return: None
        """
        self.showing.emit(True)

    def hideEvent(self, event: QHideEvent) -> None:
        """
        Handles the hide event of the widget, emitting a signal to indicate the visibility
        state of the widget has changed. - Generated by OpenAI's GPT-5.4

        :param event: The QHideEvent triggered when the widget is hidden
        :type event: QHideEvent
        :return: None
        """
        self.showing.emit(False)