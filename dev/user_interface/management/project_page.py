from datetime import date

import numpy as np
from PySide6.QtCore import Qt, Signal, QPoint, Slot
from PySide6.QtGui import QShortcut, QKeySequence
from PySide6.QtWidgets import QVBoxLayout, QWidget, QHBoxLayout, QFrame

from dev.user_interface.analysis.q_analysis_tabs import QAnalysisWidget
from dev.user_interface.floating.q_floating_content import QFloatingWarning
from dev.physics_engine.vector_obstacle import VectorObstacle
from dev.user_interface.canvas.q_state_manager import QStateManager
from dev.user_interface.canvas.q_editor import QEditor
from dev.user_interface.canvas.q_tool_bar import QToolBar
from dev.user_interface.management.q_custom_window_frame import FramelessWindow, QCustomTitleBar

class ProjectPage(QWidget):
    """
    Represents the main project page in the application, providing the user interface for project
    editing and management.

    This class acts as the primary UI component where users interact with tools, edit vector drawings,
    handle projects, and manage settings. It communicates with various components such as the title bar,
    editor, toolbar, and other widgets to provide a seamless user experience. - Generated by OpenAI's GPT 5.5

    Signals:
        :ivar saveProject: Emitted when the project is saved. Provides the saved data as a dictionary.
        :ivar homeRequested: Emitted when navigation to the home screen is requested.
        :ivar constraintChanged: Emitted when the constraint method changes.
        :ivar iterationsChanged: Emitted when the number of iterations changes.
        :ivar thresholdChanged: Emitted when the threshold value changes.
        :ivar qualityChanged: Emitted when the quality factor changes.
        :ivar windSpeedChanged: Emitted when the wind speed value changes.
        :ivar vectorDrawingChanged: Emitted when the vector drawing changes, providing an ndarray.
        :ivar saveWarningYesPressed: Emitted when the user confirms saving in the warning dialog.
        :ivar saveWarningNoPressed: Emitted when the user dismisses the warning dialog without saving.

    Methods:
        :method set_warning_visible: Toggles the visibility of the unsaved changes warning.
        :method load_editor_data: Loads data into the editor for project editing.
        :method title_bar: Provides access to the custom title bar.
        :method constraint_method, threshold, iterations, quality, wind_speed:
            Getter and setter properties for toolbar options.

    :ivar title_bar: Provides the custom title bar instance for management.
    :type title_bar: QCustomTitleBar
    :ivar constraint_method: Returns or sets the selected constraint method as a string.
    :type constraint_method: str
    :ivar threshold: Returns or sets the numerical threshold used in the editor.
    :type threshold: int
    :ivar iterations: Returns or sets the number of iterations for computation or analysis.
    :type iterations: int
    :ivar quality: Returns or sets the quality factor.
    :type quality: float
    :ivar wind_speed: Returns or sets the wind speed value managed by the editor.
    :type wind_speed: float
    """
    saveProject = Signal(dict)
    homeRequested = Signal()
    constraintChanged = Signal(str)
    iterationsChanged = Signal(int)
    thresholdChanged = Signal(int)
    qualityChanged = Signal(float)
    windSpeedChanged = Signal(float)
    vectorDrawingChanged = Signal(np.ndarray)
    saveWarningYesPressed = Signal()
    saveWarningNoPressed = Signal()

    def __init__(self, parent: FramelessWindow):
        super().__init__(parent)

        self._initial_res = 1080
        self.resize(int((16/9)*self._initial_res), self._initial_res)
        self.setMinimumWidth(450)

        self._editor: QEditor
        self._state_manager = QStateManager(self)
        self._window = parent

        self._title_bar: QCustomTitleBar = self._window.titleBar

        self.__initialize_canvas()
        self.__initialize_title_bar()
        self.__initialize_connections()

        self._primary_layout = QVBoxLayout(self)
        self._primary_layout.setContentsMargins(0, 0, 0, 0)
        self._primary_layout.addWidget(self._editor)

    def __initialize_canvas(self):
        """
        Initializes the canvas by setting up the editor, tool bar, vector obstacle, and layout configurations.

        This method creates the primary editor and tool bar specific to the state manager. It also sets
        up the layouts to ensure proper alignment and configuration for the editor and additional tools.
         - Generated by OpenAI's GPT 5.5

        :rtype: None
        :return: This method does not return any value.
        """
        self._editor = QEditor(self._state_manager)
        self._editor.switch_cursor(QStateManager.CursorState.DEFAULT)

        self._tool_bar = QToolBar(self._state_manager)

        self._vector_obstacle = VectorObstacle(self._initial_res)

        self._lower_layout = QHBoxLayout()
        self._lower_layout.addWidget(self._tool_bar, alignment=Qt.AlignmentFlag.AlignHCenter)
        self._secondary_layout = QVBoxLayout(self._editor)
        self._secondary_layout.setContentsMargins(0, 0, 0, 0)
        self._secondary_layout.addStretch()
        self._secondary_layout.addLayout(self._lower_layout)

    def __initialize_title_bar(self):
        """
        Initializes the title bar and associated widgets.

        This method sets up the components required for the title bar, including
        an analysis tab widget and a save warning dialog. These components are
        hidden initially and styled appropriately. The method also handles
        inserting these widgets into the secondary layout with specified
        alignment. - Generated by OpenAI's GPT 5.5

        :raises RuntimeError: If the widgets cannot be inserted into the layout.

        :return: None
        """
        self._analysis_tab = QAnalysisWidget(QPoint(0, 0), self)
        self._analysis_tab.hide()

        self._save_warning = QFrame(self)
        self._save_warning.setObjectName("save_warning")
        self._save_warning.setStyleSheet("#save_warning { background-color: rgba(245, 245, 245, 70);}")
        self._save_warning_window = QFloatingWarning(QPoint(int(self.width()/2), int(self.height()/2)),
                                                     "Attention",
                                                     "Quitter sans sauvegarder vos modifications "
                                                     "risque de\n"
                                                     "résulter en une perte totale de votre travail.\n\n"
                                                     "Êtes-vous sûr de vouloir continuer ?",
                                                     self._save_warning)
        self._save_warning.hide()

        self._secondary_layout.insertWidget(0, self._analysis_tab, 0,
                                            alignment=Qt.AlignmentFlag.AlignTop | Qt.AlignmentFlag.AlignLeft)

    def __initialize_connections(self):
        """
        Sets up all necessary signal-slot connections for the class and initializes
        shortcuts. This method links UI components and internal logic to ensure
        smooth communication between different parts of the system. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        self._tool_bar.constraintChanged.connect(self.constraintChanged.emit)
        self._tool_bar.iterationsChanged.connect(self.iterationsChanged.emit)
        self._tool_bar.thresholdChanged.connect(self.thresholdChanged.emit)
        self._tool_bar.qualityChanged.connect(self.qualityChanged.emit)
        self._tool_bar.windSpeedChanged.connect(self.windSpeedChanged.emit)
        self._editor.vectorDrawingChanged.connect(self.vectorDrawingChanged.emit)

        self._state_manager.cursorStateChanged.connect(self._editor.switch_cursor)
        self._state_manager.cursorStateChanged.connect(self._tool_bar.update_cursor_state)

        self._save_warning_window.yesPressed.connect(self.saveWarningYesPressed.emit)
        self._save_warning_window.noPressed.connect(self.saveWarningNoPressed.emit)

        self._title_bar.analysisPressed.connect(lambda y: self._on_analysis_pressed(y))

        self.vectorDrawingChanged.connect(self._vector_obstacle.set_vertices)
        self.qualityChanged.connect(self._vector_obstacle.set_reduction_factor)

        # Project saving
        self._save_shortcut = QShortcut(QKeySequence("Ctrl+S"), self)
        self._save_shortcut.setContext(Qt.ShortcutContext.WindowShortcut)

        self._save_shortcut.activated.connect(self._on_save_project)

    def resizeEvent(self, event, /):
        """
        Handles the resize event to adjust the size of certain UI elements dynamically. - Generated by OpenAI's GPT 5.5

        :param event: The resize event instance containing information about the
            resizing operation.
        :return: None
        """
        self._save_warning.setGeometry(0, 0, self.width(), self.height())

    @Slot()
    def _on_save_project(self):
        """
        Handles the process of saving a project and emits the saved data.

        This method collects and modifies the current project data by assigning
        a description containing the current date. The updated data is then
        emitted via a signal for further processing. - Generated by OpenAI's GPT 5.5

        :return: None
        """
        saved_data = self._editor.save_data()

        today_date = date.today()
        project_description = str(today_date)

        saved_data["Project_description"] = project_description

        self.saveProject.emit(saved_data)

    def set_warning_visible(self, visible: bool):
        """
        Sets the visibility of the warning message and manages the state of the associated UI
        components, including enabling or disabling the title bar, showing or hiding the
        analysis tab, and clearing the "analysis checked" state if applicable. - Generated by OpenAI's GPT 5.5

        :param visible: Boolean indicating whether the warning should be visible.
        :type visible: bool
        :return: None
        """
        if visible:
            self._save_warning.show()
            self._save_warning.raise_()
            if self._title_bar.is_analysis_checked:
                self._title_bar.is_analysis_checked = False
                self._analysis_tab.hide()

            self._title_bar.setDisabled(True)
        else:
            self._save_warning.hide()
            self._title_bar.setDisabled(False)

    def load_editor_data(self, data: dict):
        """
        Loads data into the editor instance.

        This function is responsible for loading the provided data into the editor. It
        delegates the operation to the internal editor object, ensuring the data is
        parsed and handled as required. - Generated by OpenAI's GPT 5.5

        :param data: The data to be loaded into the editor.
        :type data: dict
        :return: None
        """
        self._editor.load_data(data)

    @Slot(bool)
    def _on_analysis_pressed(self, pressed: bool):
        """
        Handles the toggling of the analysis tab's visibility based on the `pressed` state.
        - Generated by OpenAI's GPT 5.5

        :param pressed: A boolean indicating whether the analysis tab should be shown
            or hidden. If True, the analysis tab will be shown, otherwise it will be hidden.
        :type pressed: bool
        """
        self._analysis_tab.show() if pressed else self._analysis_tab.hide()

    @property
    def title_bar(self) -> QCustomTitleBar:
        """
        Gets the custom title bar instance associated with the current context. - Generated by OpenAI's GPT 5.5

        :return: The custom title bar associated with this instance.
        :rtype: QCustomTitleBar
        """
        return self._title_bar

    @property
    def constraint_method(self) -> str:
        """
        Gets the constraint method associated with the tool bar.

        This property retrieves the current constraint method value from the
        tool bar. The constraint method can be used to understand or modify
        how constraints are applied in a specific context. - Generated by OpenAI's GPT 5.5

        :return: The constraint method as a string.
        :rtype: str
        """
        return self._tool_bar.constraint_method
    @constraint_method.setter
    def constraint_method(self, constraint: str):
        """
        Sets the constraint method for the tool bar. - Generated by OpenAI's GPT 5.5

        :param constraint: The constraint method to be set.
        :type constraint: str
        """
        self._tool_bar.constraint_method = constraint

    @property
    def threshold(self) -> int:
        """
        Gets the current threshold value for the toolbar configuration.

        The threshold value determines the limit or boundary at which a specific
        action, calculation, or configuration applies within the toolbar logic. It
        is an important property meant for controlling user interface behavior
        or internal processes bound to the toolbar. - Generated by OpenAI's GPT 5.5

        :return: The integer value of the threshold.
        :rtype: int
        """
        return self._tool_bar.threshold
    @threshold.setter
    def threshold(self, threshold: int):
        """
        Sets the threshold for the tool bar. - Generated by OpenAI's GPT 5.5

        :param threshold: The new threshold value to be set for the tool bar.
        :type threshold: int
        """
        self._tool_bar.threshold = threshold

    @property
    def iterations(self) -> int:
        """
        Provides access to the number of iterations stored in the toolbar. - Generated by OpenAI's GPT 5.5

        :return: The number of iterations.
        :rtype: int
        """
        return self._tool_bar.iterations
    @iterations.setter
    def iterations(self, iterations: int):
        """
        Sets the number of iterations for the tool bar.

        This property setter adjusts the iteration count used by the tool bar for its
        internal operations. It ensures that the provided value is assigned properly
        to the underlying tool bar instance. - Generated by OpenAI's GPT 5.5

        :param iterations: The number of iterations to set.
        :type iterations: int
        """
        self._tool_bar.iterations = iterations

    @property
    def quality(self) -> float:
        """
        Gets the quality value of the tool bar. - Generated by OpenAI's GPT 5.5

        :return: The quality value of type float.
        :rtype: float
        """
        return self._tool_bar.quality
    @quality.setter
    def quality(self, quality: float):
        """
        Sets the quality property of the toolbar. - Generated by OpenAI's GPT 5.5

        :param quality: The value to set as the quality. Must be a float.
        :type quality: float
        """
        self._tool_bar.quality = quality

    @property
    def wind_speed(self) -> float:
        """
        Retrieves the wind speed value from the tool bar. - Generated by OpenAI's GPT 5.5

        :return: Wind speed value as a floating-point number.
        :rtype: float
        """
        return self._tool_bar.wind_speed
    @wind_speed.setter
    def wind_speed(self, wind_speed: float):
        """
        Sets the wind speed for the tool bar. - Generated by OpenAI's GPT 5.5

        :param wind_speed: Wind speed value to be set.
        :type wind_speed: float
        """
        self._tool_bar.wind_speed = wind_speed