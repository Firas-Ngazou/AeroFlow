    def _update_image_type(self) -> None:
        """Calculates and updates the rendering pipeline mode. - Generated by Gemini"""
        velocity = self._settings_side_bar.velocity_state == 1
        density = self._settings_side_bar.density_state == 1
        stream = self._settings_side_bar.streamlines_state == 1
        curl = self._settings_side_bar.curl_state == 1

        if velocity:
            if stream:
                self._sim_controller.image_type = SimImageType.VELOCITY_HEAT_STREAM
            elif curl:
                self._sim_controller.image_type = SimImageType.VELOCITY_HEAT_CURL
            else:
                self._sim_controller.image_type = SimImageType.VELOCITY_HEAT
            return
        elif density:
            if stream:
                self._sim_controller.image_type = SimImageType.DENSITY_HEAT_STREAM
            elif curl:
                self._sim_controller.image_type = SimImageType.DENSITY_HEAT_CURL
            else:
                self._sim_controller.image_type = SimImageType.DENSITY_HEAT
        elif stream:
            self._sim_controller.image_type = SimImageType.STREAM
        elif curl:
            self._sim_controller.image_type = SimImageType.CURL
        else:
            self._sim_controller.image_type = SimImageType.NONE

    @Slot()
    def _on_play_pressed(self) -> None:
        """Commences the simulation sequence. - Generated by Gemini"""
        self._editor.disable_settings = True
        self._sim_controller.reset()
        self._settings_side_bar.sim_playing = True

        if not self._sim_thread.is_running():
            self._sim_thread.start()

        if not self._title_bar.is_analysis_checked:
            self._title_bar.click_analysis()
        self._analysis_tab.set_results_tab_active()

        vertices = self._editor.get_vertices()
        self._simulation_engine.vertices = vertices

        data = [self.wind_speed, [self._editor.width, self._editor.height]]

        self._sim_controller.show()
        self.runSimulation.emit(data)

        width = self.window().width
        height = self.window().height
        self.window().set_fixed_size(width, height)

    @Slot()
    def on_stop_pressed(self) -> None:
        """Stops the simulation and restores the UI state. - Generated by Gemini"""
        self._settings_side_bar.sim_playing = False
        if not self._is_optimizing: self._editor.disable_settings = False
        self._sim_controller.hide()
        self._state_manager.set_cursor_state(QStateManager.CursorState.DEFAULT)

        if self._sim_thread.is_running():
            self._sim_thread.request_interruption()
            self._sim_thread.quit()
            self._sim_thread.wait()

        self._sim_controller.reset()
        self._editor.display_pixmap()

        self.window().minimum_width = self._minimum_window_width
        self.window().minimum_height = self._minimum_window_height
        self.window().maximum_width = self._maximum_window_width
        self.window().maximum_height = self._maximum_window_height

        self._analysis_tab.simulation_progress = 0
        self._analysis_tab.set_sim_info_label(" - ")
        self._analysis_tab.set_drag_coef_value(" - ")
        self._analysis_tab.set_lift_coef_value(" - ")
        self._analysis_tab.set_reynolds_number_value(" - ")
        self._analysis_tab.set_mach_number_value(" - ")
        self._analysis_tab.set_kinetic_energy_value(" - ")
        self._analysis_tab.set_pressure_drop_value(" - ")
        self._analysis_tab.set_total_mass_value(" - ")
        self._analysis_tab.set_total_enstrophy_value(" - ")
