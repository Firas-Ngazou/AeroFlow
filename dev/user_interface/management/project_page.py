    @Slot(dict)
    def _on_save_shape_requested(self, data: dict) -> None:
        """
        Registers a saved shape as a prefab in the toolbar. - Generated by Gemini
        """
        if "Name" in data and "Vertices" in data and "Preview" in data:
            prefab_data = {"Name": data.get("Name"), "Vertices": data.get("Vertices"), "Preview": data.get("Preview")}
            self._tool_bar.add_prefab_to_scroll(prefab_data)

    @Slot()
    def _on_vector_drawing_changed(self) -> None:
        """
        Commits drawing changes to the simulation context. - Generated by Gemini
        """
        self.vectorDrawingChanged.emit()
        self._analysis_tab.reset_opt_graph()
        self._tool_bar.has_drawing = self._editor.has_drawing
        if self._simulation_engine.live_edit:
            updated_vertices = self._editor.get_vertices()
            self.liveEditVerticesChanged.emit(updated_vertices.copy())

    @Slot(np.ndarray)
    def _on_optimize_start(self, vertices: np.ndarray) -> None:
        """
        Launches the genetic algorithm optimization thread. - Generated by Gemini
        """
        if self._settings_side_bar.sim_playing or self._is_optimizing:
            return
        self._is_optimizing = True
        self._editor.disable_settings = True
        self._state_manager.set_cursor_state(QStateManager.CursorState.LOCKED)
        if not self._title_bar.is_analysis_checked:
            self._title_bar.click_analysis()
        self._analysis_tab.set_optimization_tab_active()
        self._settings_side_bar.set_optimization_tab_active()
        self._analysis_tab.reset_opt_graph()
        self.optimize.emit(vertices)
        self._title_bar.is_optimizing = True
        self._tool_bar.is_optimizing = True
        self._settings_side_bar.is_optimizing = True

    @Slot(np.ndarray, int, float)
    def _on_ga_iteration_completed(self, new_vertices: np.ndarray, current_iteration: int, coef: float) -> None:
        """
        Updates the graph and canvas after a GA iteration. - Generated by Gemini
        """
        point = QPointF(current_iteration, coef)
        self._analysis_tab.add_opt_graph_point(point)
        self._analysis_tab.simulation_progress = int(((current_iteration + 1) / max(1, self.iterations)) * 100)
        self._editor.change_current_shape(new_vertices)

    @Slot()
    def _on_ga_optimization_completed(self) -> None:
        """
        Cleans up after GA completion. - Generated by Gemini
        """
        self._finish_optimization()

    @Slot()
    def _on_force_stop_optimization(self) -> None:
        """
        Forcibly interrupts the GA thread.

        - Generated by Gemini
        """
        if not self._is_optimizing:
            return
        if self._ga_thread is not None and self._ga_thread.is_running():
            self._ga_thread.request_interruption()
            self._ga_thread.terminate()
            self._ga_thread.wait()
        self._start_ga_thread()
        self._finish_optimization()

    def _finish_optimization(self) -> None:
        """
        Resets UI states after optimization ends.

        - Generated by Gemini
        """
        self._state_manager.set_cursor_state(QStateManager.CursorState.DEFAULT)
        self._title_bar.is_optimizing = False
        self._tool_bar.is_optimizing = False
        self._settings_side_bar.is_optimizing = False
        self._is_optimizing = False

        self._tool_bar.has_drawing = self._editor.has_drawing
        if not self._settings_side_bar.sim_playing: self._editor.disable_settings = False

    def _start_ga_thread(self) -> None:
        """
        Spawns the genetic algorithm thread.

        - Generated by Gemini
        """
        self._ga_thread = QThread()
        self._ga = GeneticAlgorithm()
        self._ga.constraint_method = self.constraint_method
        self._ga.target = self.target
        self._ga.type = self.type
        self._ga.threshold = self.threshold
        self._ga.iterations = self.iterations
        self._ga.population = self.population_size
        self._ga.mutation_rate = self.mutation_rate
        self._ga.magnitude = self.magnitude
        self._ga.move_to_thread(self._ga_thread)
        self._ga.iterationCompleted.connect(self._on_ga_iteration_completed)
        self._ga.optimizationCompleted.connect(self._on_ga_optimization_completed)
        self._ga.aeroGainUpdated.connect(self._analysis_tab.set_opt_gain)
        self._ga.projectedDragUpdated.connect(self._analysis_tab.set_opt_projected_drag)
        self._ga.projectedLiftUpdated.connect(self._analysis_tab.set_opt_projected_lift)
        self.optimize.connect(self._ga.optimize)
        self._ga_thread.start()

