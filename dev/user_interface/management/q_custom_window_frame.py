class QFileMenu(QMenu):
    """
    A context menu providing file management operations like saving, opening, and creating projects.

    - Generated by Gemini
    """
    newFileRequested = Signal()
    openFileRequested = Signal(str)
    saveFileRequested = Signal()
    saveAsFileRequested = Signal()

    def __init__(self, parent: QWidget | None = None) -> None:
        """
        Initializes the file menu with standard actions.

        :param parent: The parent widget.

        - Generated by Gemini
        """
        super().__init__(parent)

        self._new_action = QAction("Nouveau", self)
        self._open_action = QAction("Ouvrir", self)
        self._save_action = QAction("Enregistrer (CTRL + S)", self)
        self._save_as_action = QAction("Enregistrer sous (CTRL + SHIFT + S)", self)

        self.add_action(self._new_action)
        self.add_action(self._open_action)
        self.add_separator()
        self.add_action(self._save_action)
        self.add_action(self._save_as_action)

        self._new_action.triggered.connect(self.newFileRequested.emit)
        self._open_action.triggered.connect(self._on_open_file_requested)
        self._save_action.triggered.connect(self.saveFileRequested.emit)
        self._save_as_action.triggered.connect(self.saveAsFileRequested.emit)

    @Slot()
    def _on_open_file_requested(self) -> None:
        """Opens a file dialog to select an existing project JSON. - Generated by Gemini"""
        path, _ = QFileDialog.get_open_file_name(self, "Ouvrir un fichier", "../../",
                                                 "JSON Files (*.json);;All Files (*")
        if path: self.openFileRequested.emit(path)

    @Slot()
    def set_save_action_enabled(self, enabled: bool) -> None:
        """Updates the enabled state of the Save action. - Generated by Gemini"""
        self._save_action.set_disabled(not enabled)

    @Slot()
    def set_new_action_enabled(self, enabled: bool) -> None:
        """Updates the enabled state of the New action. - Generated by Gemini"""
        self._new_action.set_disabled(not enabled)

    def set_save_disabled(self, disabled: bool) -> None:
        """Disables or enables the Save action. - Generated by Gemini"""
        self._save_action.set_disabled(disabled)

    def set_save_as_disabled(self, disabled: bool) -> None:
        """Disables or enables the Save As action. - Generated by Gemini"""
        self._save_as_action.set_disabled(disabled)


