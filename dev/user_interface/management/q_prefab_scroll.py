class QShapePrefab(QFrame):
    """
    Represents a UI frame component for managing shape prefabs.

    This class is a custom implementation based on QFrame and provides functionalities
    for displaying a shape prefab image, its name, and interactive buttons for deletion
    and cancellation. It supports event-driven interaction with signals and integrates easily
    as part of a PyQt or PySide application. - Generated by OpenAI's GPT-5.5

    :ivar deleteRequested: Signal emitted when a delete operation is requested.
        Carries the name of the shape to be deleted as a string.
    :type deleteRequested: Signal

    :ivar instanceRequested: Signal emitted when a left mouse button click requests
        an instance of the shape. Carries the name of the requested shape as a string.
    :type instanceRequested: Signal
    """
    deleteRequested = Signal(str)
    instanceRequested = Signal(str)

    def __init__(self, data: dict, parent: QWidget | None = None):
        """
        Represents a custom UI frame component to display shape prefabs. This includes an image
        preview, object name, and optional buttons for deletion and cancellation. The widget
        leverages a given data dictionary for initialization and integrates with a parent widget.
         - Generated by OpenAI's GPT-5.5

        :param data: A dictionary containing attributes for initializing the UI component.
            Expected keys:
            - "Name" (str): The name of the shape object, used for the tooltip and identification.
            - "Preview" (str, optional): Base64-encoded string of the preview image. If provided,
              an image will be displayed; otherwise, the widget remains empty.
        :param parent: Parent widget (optional). Defaults to None, allowing the widget to exist
            independently or under a specified parent in the UI hierarchy.
        """
        super().__init__(parent)

        # Setup
        font = QFont("JetBrains Mono", 9)
        self.mouse_tracking = True
        self.object_name = "shape_prefab_frame"

        self.set_fixed_size(100, 100)
        self.set_property("class", "primary_frame")
        self.tool_tip = data.get("Name", " - ")

        # Pixmap setup
        self._image_label = QLabel()
        self._image_label.alignment = Qt.AlignmentFlag.AlignCenter

        # Buttons
        self._delete_button = QPushButton(self)
        self._delete_button.text = "Supprimer"
        self._delete_button.font = font
        self._delete_button.set_property("class", "delete_pb")
        self._delete_button.hide()

        self._cancel_button = QPushButton(self)
        self._cancel_button.text = "Annuler"
        self._cancel_button.font = font
        self._cancel_button.set_property("class", "shape_settings_pb")
        self._cancel_button.hide()

        self._settings_visible = False

        # Layout
        layout = QVBoxLayout(self)
        layout.set_contents_margins(5, 5, 5, 5)
        layout.add_widget(self._image_label)
        layout.add_widget(self._delete_button)
        layout.add_widget(self._cancel_button)

        # Make pixmap
        self._name = data.get("Name", "")

        # Connections
        self._delete_button.clicked.connect(self._on_delete_pressed)
        self._cancel_button.clicked.connect(self._on_cancel_pressed)

        preview_base64 = data.get("Preview", "")
        if preview_base64:
            byte_array = QByteArray.from_base64(preview_base64.encode("utf-8"))
            pixmap = QPixmap()
            pixmap.load_from_data(byte_array)

            scaled_pixmap = pixmap.scaled(80, 80, Qt.AspectRatioMode.KeepAspectRatio,
                                          Qt.TransformationMode.SmoothTransformation)
            self._image_label.pixmap = scaled_pixmap

    def enter_event(self, event):
        """
        Handles the event when the user interacts with the widget.

        This method is triggered when an event enters the widget area. If the
        settings are not currently visible, it applies a specific stylesheet to
        update the appearance of the widget. - Generated by OpenAI's GPT-5.5

        :param event: The event object that triggers the method.
        :type event: QEvent
        :return: None
        """
        if not self._settings_visible:
            self.style_sheet = "#shape_prefab_frame {background-color: rgba(245, 245, 245, 10);}"

    def leave_event(self, event):
        """
        Handles the leave event triggered when the mouse cursor leaves the widget.

        Adjusts the style of the widget to make the background transparent and hides
        specific settings associated with the widget. - Generated by OpenAI's GPT-5.5

        :param event: The `QEvent` instance corresponding to the leave event.
        :return: None
        """
        self.style_sheet = "#shape_prefab_frame {background-color: transparent;}"
        self._set_settings_visible(False)

    def mouse_press_event(self, event):
        """
        Handles mouse press events and performs specific actions based on the mouse button pressed.

        This method overrides the superclass implementation to handle right and left mouse button
        clicks. It ensures that certain UI settings are displayed or events are emitted based on
        the state of internal attributes and the interaction type. - Generated by OpenAI's GPT-5.5

        :param event: The mouse event containing information about the button pressed.
        :type event: QMouseEvent
        :return: None
        """
        if event.button() == Qt.MouseButton.RightButton:
            self._set_settings_visible(True)
        if not self._settings_visible and event.button() == Qt.MouseButton.LeftButton:
            self.instanceRequested.emit(self._name)

        super().mouse_press_event(event)

    def _set_settings_visible(self, visible: bool):
        """
        Sets the visibility of certain UI components and updates the internal settings state.
         - Generated by OpenAI's GPT-5.5

        :param visible: A boolean indicating whether the settings components should be
            visible or not.
        :return: None
        """
        self._delete_button.visible = visible
        self._cancel_button.visible = visible
        self._settings_visible = visible

    @Slot()
    def _on_cancel_pressed(self):
        """
        Handles the cancellation event for a specific action.

        This method is triggered when a cancel button is pressed. It updates
        the internal state to hide certain settings. This function is intended
        for internal use. - Generated by OpenAI's GPT-5.5

        :param: None

        :return: None
        """
        self._set_settings_visible(False)

    @Slot()
    def _on_delete_pressed(self):
        """
        This method is a Qt slot that handles the signal for the delete operation.
        When triggered, it emits the `deleteRequested` signal with the name of the
        item to be deleted. - Generated by OpenAI's GPT-5.5

        :raises: No specific exceptions are raised.
        :return: None
        """
        self.deleteRequested.emit(self._name)

class QPrefabScroll(QWidget):
    instanceRequested = Signal(dict)

    def __init__(self, parent: QWidget | None = None):
        """
        Represents a UI component that initializes and manages a primary frame with a scrollable content area.
        This component dynamically loads and displays prefabs from a predefined save path if available.
         - Generated by OpenAI's GPT-5.5

        :param parent: The parent widget for this component, or None if no parent.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        # Setup
        self._save_path: str | None = None

        base_path = os.path.dirname(os.path.abspath(__file__))
        save_path = os.path.join(base_path, "../../../tmp_files/shape_prefabs.json")

        if os.path.exists(save_path):
            self._save_path = save_path

        # Main layout
        main_layout = QVBoxLayout(self)
        main_layout.set_contents_margins(0, 0, 0, 0)

        # Frame
        self._frame = QFrame(self)
        self._frame.set_fixed_width(600)
        self._frame.minimum_height = 150
        self._frame.set_property("class", "primary_frame")
        main_layout.add_widget(self._frame)

        frame_layout = QVBoxLayout(self._frame)
        frame_layout.set_contents_margins(15, 15, 15, 15)

        # Scroll area
        self._scroll_area = QScrollArea(self._frame)
        self._scroll_area.widget_resizable = True
        self._scroll_area.vertical_scroll_bar_policy = Qt.ScrollBarPolicy.ScrollBarAlwaysOff
        self._scroll_area.horizontal_scroll_bar_policy = Qt.ScrollBarPolicy.ScrollBarAlwaysOn

        self._scroll_area.frame_shape = QFrame.Shape.NoFrame

        self._scroll_content = QWidget()
        self._scroll_layout = QHBoxLayout(self._scroll_content)
        self._scroll_layout.set_contents_margins(0, 0, 0, 0)
        self._scroll_layout.spacing = 15
        self._scroll_layout.alignment = Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter

        self._scroll_layout.add_stretch()

        self._scroll_area.set_widget(self._scroll_content)
        frame_layout.add_widget(self._scroll_area)

        self._load_prefabs()

    def _load_prefabs(self):
        """
        Loads prefabs from a save file if the save path is specified. The method reads a
        JSON file located at the specified save path, processes and validates its
        contents, and adds prefabs to the current data structure using the `add_prefab`
        method. Prefabs are added without triggering save updates. - Generated by OpenAI's GPT-5.5

        Raises:
            Does not raise any exceptions directly in this method.

        :return: None
        """
        if not self._save_path:
            return

        with open(self._save_path, 'r') as file:
            loaded = json.load(file)

            if isinstance(loaded, dict):
                existing = loaded
            else:
                existing = {"Shapes": loaded}

            for prefab_data in existing["Shapes"]:
                self.add_prefab(prefab_data, update_save=False)

    @Slot(str)
    def _on_instance_requested(self, name: str):
        """
        Handles the instance request for a specified shape name. If a save path is defined,
        the method loads the saved data from the provided path, searches for the shape with
        the specified name, and if found, emits an event with the shape's vertices data. - Generated by OpenAI's GPT-5.5
        :param name: The name of the shape to be searched for in the saved data.
        :type name: str
        """
        if self._save_path is None:
            return

        with open(self._save_path, 'r') as file:
            loaded = json.load(file)

            for shape in loaded["Shapes"]:
                if shape.get("Name") == name:
                    data = {"Vertices": shape.get("Vertices")}
                    self.instanceRequested.emit(data)
                    break


    def add_prefab(self, data: dict, update_save: bool = True):
        """
        Adds a prefab to the scroll layout and connects its signals for further actions like delete
        or instance creation. The method simplifies the input data to only include specific keys,
        instantiates a `QShapePrefab` object, and inserts it into the layout. It optionally updates
        the save path based on the provided data. - Generated by OpenAI's GPT-5.5

        :param data: A dictionary containing information about the prefab. It must include
            at least a "Name" key. Additional keys such as "Preview" will be conditionally used.
        :param update_save: Determines if the save path should be updated. Defaults to True.
        :type update_save: bool
        :return: None
        """
        if "Name" not in data:
            return
        simplified_data = {"Name": data.get("Name"), "Preview": data.get("Preview")}
        prefab = QShapePrefab(simplified_data)
        prefab.deleteRequested.connect(self._delete_prefab)
        prefab.instanceRequested.connect(self._on_instance_requested)
        count = self._scroll_layout.count()
        self._scroll_layout.insert_widget(count - 1, prefab)

        if update_save:
            self._update_save_path(data)

    def _update_save_path(self, data: dict):
        """
        Updates the save path file with new shape data, ensuring no duplicates by name.
        If `_save_path` is not defined or the given `data` name already exists, the
        operation is skipped. - Generated by OpenAI's GPT-5.5

        :param data: Dictionary containing the shape data to be added. The `data` must
            include a "Name" key for proper identification and comparison.
        :type data: dict
        """
        if not self._save_path:
            return

        existing = {"Shapes": []}
        with open(self._save_path, 'r') as file:
            loaded = json.load(file)

            if isinstance(loaded, dict):
                existing = loaded

                if "Shapes" not in existing:
                    existing["Shapes"] = []

        new_name = data.get("Name")
        for existing_prefab in existing["Shapes"]:
            if existing_prefab.get("Name") == new_name:
                return

        existing["Shapes"].append(data)

        with open(self._save_path, 'w') as file:
            json.dump(existing, file, indent=4)

    @Slot(str)
    def _delete_prefab(self, name: str):
        """
        Deletes a prefab by its name and updates the UI and saved states accordingly. - Generated by OpenAI's GPT-5.5

        :param name: Name of the prefab to delete
        :type name: str
        :return: None
        """
        sender = self.sender()
        if sender:
            self._scroll_layout.remove_widget(sender)
            sender.delete_later()
            self._delete_from_save(name)

    def _delete_from_save(self, name: str):
        """
        Deletes an entry corresponding to the given name from the saved file if it exists.

        This method checks if a save path is specified and reads the JSON content of the
        file located at the save path. If the content contains a "Shapes" key, it filters
        the list of shapes to exclude the shape with the specified name. The updated content
        is then written back to the file.

        :param name: The name of the shape to delete from the saved file.
        :type name: str
        """
        if not self._save_path:
            return

        with open(self._save_path, 'r') as file:
            existing = json.load(file)

        if isinstance(existing, dict) and "Shapes" in existing:
            existing["Shapes"] = [shape for shape in existing["Shapes"] if shape.get("Name") != name]

            with open(self._save_path, 'w') as file:
                json.dump(existing, file, indent=4)