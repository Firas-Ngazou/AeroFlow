import dev.user_interface.tools.q_wrapper as q_wrapper
q_wrapper.apply_all_wrappers()

from PySide6.QtCore import Qt, Slot, Signal, QSize
from PySide6.QtGui import QFont
from PySide6.QtWidgets import QWidget, QFrame, QHBoxLayout, QVBoxLayout, QLabel, QComboBox

class QCustomCombo(QWidget):
    """
    A custom-styled dropdown component for settings panels.

    This widget groups a descriptive label and a QComboBox into a themed frame,
    designed to maintain visual consistency across the application's configuration sidebars.

    :ivar currentTextChanged: Emitted when the user selects a new item in the dropdown.

    - Generated by Gemini
    """
    currentTextChanged = Signal(str)

    def __init__(self, title: str, parent: QWidget | None = None) -> None:
        """
        Initializes the labeled combobox container.

        :param title: The text label displayed to the left of the dropdown.
        :type title: str
        :param parent: Optional parent widget.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._combo_box = QComboBox()
        self._combo_box.placeholder_text = "MÉTHODE"
        self._combo_box.set_property("class", "settings_combo_box")
        self._combo_box.set_fixed_width(150)
        self._combo_box.set_fixed_height(30)
        self._combo_box.font = QFont("JetBrains Mono", 9)

        self._title = QLabel(title)
        self._title.font = QFont("JetBrains Mono", 11)

        self._combo_box.current_index = 1

        # Constraint frame & layout
        self._frame = QFrame(self)
        self._frame.set_property("class", "constraint_frame")
        self._constraint_layout = QHBoxLayout(self._frame)

        self._constraint_layout.add_widget(self._title, alignment = Qt.AlignmentFlag.AlignLeft)
        self._constraint_layout.add_widget(self._combo_box, alignment = Qt.AlignmentFlag.AlignRight)
        self._constraint_layout.set_contents_margins(15, 0, 0, 0)

        root_layout = QVBoxLayout(self)
        root_layout.add_widget(self._frame)
        root_layout.set_contents_margins(0, 0, 0, 0)

        self._combo_box.currentTextChanged.connect(self.currentTextChanged)

    def add_combo_item(self, text: str) -> None:
        """
        Appends a new selectable item to the dropdown menu.

        :param text: The text label for the new menu item.
        :type text: str
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._combo_box.add_item(text)

    @property
    def current_text(self) -> str:
        """
        Retrieves the currently selected text from the dropdown.

        :return: Currently selected item string.
        :rtype: str

        - Generated by Gemini
        """
        return self._combo_box.current_text

    @current_text.setter
    def current_text(self, text: str) -> None:
        """
        Sets the active selection in the dropdown by string match.

        :param text: The string to set as active.
        :type text: str
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._combo_box.current_text = text