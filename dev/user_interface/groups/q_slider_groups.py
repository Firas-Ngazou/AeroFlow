from PySide6.QtCore import Qt, Slot, Signal
from PySide6.QtGui import QFont
from PySide6.QtWidgets import QWidget, QFrame, QHBoxLayout, QVBoxLayout, QLabel, \
    QDoubleSpinBox, QSlider, QSpinBox

from dev.user_interface.components.q_real_slider import QRealSlider
from dev.user_interface.components.q_buttons import QResetPB

class QAbstractSliderGroup(QWidget):
    """
    A widget group that combines a slider, a spin box, and a reset button with a customizable title.

    This class creates a widget group that consists of a slider, a spin box, and a reset button
    arranged with a primary layout. The title of the group can be specified. The slider and spin box
    are interconnected, and the reset button allows resetting their values to their default state.
    This widget group is suitable for settings that require numeric input within a certain range.
    - Generated by OpenAI's GPT-5.4

    :ivar _title: The QLabel used for displaying the title of the group.
    :type _title: QLabel
    :ivar _slider: The slider for adjusting values, which can be either QSlider or QRealSlider.
    :type _slider: QSlider | QRealSlider
    :ivar _spin_box: The spin box for adjusting values, which can be either QSpinBox or QDoubleSpinBox.
    :type _spin_box: QSpinBox | QDoubleSpinBox
    :ivar _primary_layout: A vertical layout containing all sub-layouts and widgets of the widget group.
    :type _primary_layout: QVBoxLayout
    :ivar _top_layout: The horizontal layout containing the title, the spin box, and the reset button.
    :type _top_layout: QHBoxLayout
    :ivar _bottom_layout: The horizontal layout containing the slider.
    :type _bottom_layout: QHBoxLayout
    """
    def __init__(self, text: str, slider: QSlider | QRealSlider, spin_box: QSpinBox | QDoubleSpinBox,
                 parent: QWidget | None = None):
        """
        Initializes an object that integrates a labeled slider and spinbox widget with reset functionality.

        This class represents a composite widget consisting of a title label, a reset button,
        a slider, and a spinbox. The slider and spinbox are linked and synchronized to
        share a common value. The reset button resets the slider and spinbox values to a default
        pre-configured value. - Generated by OpenAI's GPT-5.4

        :param text: The title text displayed by the label above the slider-spinbox combination.
        :type text: str
        :param slider: The slider widget, which can be a QSlider or custom QRealSlider.
        :type slider: QSlider | QRealSlider
        :param spin_box: The spinbox widget, which can be either a QSpinBox or QDoubleSpinBox.
        :type spin_box: QSpinBox | QDoubleSpinBox
        :param parent: The parent widget that contains this composite widget. Can be None.
        :type parent: QWidget | None
        """
        super().__init__(parent)

        self._default_value = 0
        self._default_range = (0, 10)

        # Primary frame & layout
        primary_frame = QFrame()
        primary_frame.setProperty("class", "primary_frame")
        self._primary_layout = QVBoxLayout(primary_frame)

        # Title
        self._title = QLabel(text)
        self._title.setFont(QFont("JetBrains Mono", 10))

        # Reset button
        self._reset_button = QResetPB()
        self._reset_button.setFont(QFont("JetBrains Mono", 9))
        self._reset_button.clicked.connect(self._on_reset_pressed)

        # Slider & spinbox
        self._slider = slider
        self._spin_box = spin_box

        self._slider.setOrientation(Qt.Orientation.Horizontal)
        self._slider.setFixedHeight(24)
        self._slider.setProperty("class", "settings_slider")
        self._slider.setValue(self._default_value)
        self._slider.setRange(*self._default_range)

        # self._spin_box.setFixedWidth(100)
        self._spin_box.setFixedHeight(24)
        self._spin_box.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self._spin_box.setProperty("class", "settings_spin_box")
        self._spin_box.setFont(QFont("JetBrains Mono", 7))
        self._spin_box.setValue(self._default_value)
        self._spin_box.setRange(*self._default_range)

        # Secondary layouts
        self._top_layout = QHBoxLayout()
        self._top_layout.addWidget(self._title, alignment=Qt.AlignmentFlag.AlignLeft)
        self._top_layout.addWidget(self._spin_box)
        self._top_layout.addWidget(self._reset_button, alignment=Qt.AlignmentFlag.AlignRight)
        self._top_layout.setContentsMargins(10, 2, 10, 2)

        self._bottom_layout = QHBoxLayout()
        self._bottom_layout.addWidget(self._slider)
        self._bottom_layout.setContentsMargins(15, 2, 15, 2)

        self._primary_layout.addLayout(self._top_layout)
        self._primary_layout.addLayout(self._bottom_layout)

        root_layout = QVBoxLayout(self)
        root_layout.setContentsMargins(0, 0, 0, 0)
        root_layout.addWidget(primary_frame)

    @Slot()
    def _on_reset_pressed(self):
        """
        Slot function that resets the slider and spin box values to their default values.
        - Generated by OpenAI's GPT-5.4

        :return: None
        """
        self._slider.setValue(self._default_value)
        self._spin_box.setValue(self._default_value)

class QRealSliderGroup(QAbstractSliderGroup):
    """
    Represents a slider group that includes both a slider and a corresponding spin box
    for handling and displaying real number values.

    This class combines a slider and a double spin box into a cohesive unit, allowing for
    synchronized adjustments of values. The purpose is to provide a user interface element
    that allows users to modify numeric values using either a slider or a spin box. Both
    the slider and spin box are synchronized to reflect the same value at all times. - Generated by OpenAI's GPT-5.4

    :ivar realValueChanged: Signal emitted when the real value of the slider changes,
        passing the updated value as a float.
    :type realValueChanged: Signal
    """
    realValueChanged = Signal(float)

    def __init__(self, text: str, parent: QWidget | None = None):
        """
        Initializes a custom widget that integrates a real-valued slider and a double spin box
        to allow synchronized control and display of a numerical value. - Generated by OpenAI's GPT-5.4

        This widget combines the functionalities of QRealSlider and QDoubleSpinBox.
        The slider's real value changes will update the spin box, and vice versa,
        ensuring they remain synchronized. The widget emits the `realValueChanged`
        signal whenever the slider's value changes.

        :param text: The display text for the widget.
        :type text: str
        :param parent: The optional parent widget. Defaults to None.
        :type parent: QWidget | None
        """
        super().__init__(text, QRealSlider(), QDoubleSpinBox(), parent)

        # Connections
        self._slider.realValueChanged.connect(self._spin_box.setValue)
        self._slider.realValueChanged.connect(self.realValueChanged)
        self._spin_box.valueChanged.connect(self._slider.setValue)

