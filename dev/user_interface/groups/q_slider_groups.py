class QAbstractSliderGroup(QWidget):
    """
    A unified abstract container for synchronized slider and spinbox UI elements.

    I built this base class to handle the boilerplate of binding a slider to a spinbox.
    It maintains the title label, the reset button logic, and the structural layout
    shared by both integer and float-based input groups.

    :ivar _title: Label widget for the group header.
    :ivar _slider: The primary drag-based input widget.
    :ivar _spin_box: The secondary text-input based widget.
    :ivar _default_value: The value returned to when the user clicks reset.

    - Generated by Gemini
    """

    def __init__(self, text: str, slider: QSlider | QRealSlider, spin_box: QSpinBox | QDoubleSpinBox,
                 parent: QWidget | None = None) -> None:
        """
        Initializes the abstract slider group with shared layout components.

        :param text: The header text for the slider group.
        :param slider: The slider implementation (QSlider or QRealSlider).
        :param spin_box: The spinbox implementation (QSpinBox or QDoubleSpinBox).
        :param parent: Optional parent widget.

        - Generated by Gemini
        """
        super().__init__(parent)

        self._default_value: float | int = 0
        self._default_range: tuple[int, int] = (0, 10)

        # Primary frame & layout
        primary_frame = QFrame()
        primary_frame.set_property("class", "primary_frame")
        self._primary_layout = QVBoxLayout(primary_frame)

        # Title
        self._title = QLabel(text)
        self._title.font = QFont("JetBrains Mono", 10)

        # Reset button
        self._reset_button = QResetPB()
        self._reset_button.font = QFont("JetBrains Mono", 9)
        self._reset_button.clicked.connect(self._on_reset_pressed)

        # Slider & spinbox
        self._slider = slider
        self._spin_box = spin_box

        self._slider.orientation = Qt.Orientation.Horizontal
        self._slider.set_fixed_height(24)
        self._slider.set_property("class", "settings_slider")
        self._slider.value = self._default_value
        self._slider.set_range(*self._default_range)

        # self._spin_box.setFixedWidth(100)
        self._spin_box.set_fixed_height(24)
        self._spin_box.alignment = Qt.AlignmentFlag.AlignCenter
        self._spin_box.set_property("class", "settings_spin_box")
        self._spin_box.font = QFont("JetBrains Mono", 7)
        self._spin_box.value = self._default_value
        self._spin_box.set_range(*self._default_range)

        # Secondary layouts
        self._top_layout = QHBoxLayout()
        self._top_layout.add_widget(self._title, alignment = Qt.AlignmentFlag.AlignLeft)
        self._top_layout.add_widget(self._spin_box)
        self._top_layout.add_widget(self._reset_button, alignment = Qt.AlignmentFlag.AlignRight)
        self._top_layout.set_contents_margins(10, 2, 10, 2)

        self._bottom_layout = QHBoxLayout()
        self._bottom_layout.add_widget(self._slider)
        self._bottom_layout.set_contents_margins(15, 2, 15, 2)

        self._primary_layout.add_layout(self._top_layout)
        self._primary_layout.add_layout(self._bottom_layout)

        root_layout = QVBoxLayout(self)
        root_layout.set_contents_margins(0, 0, 0, 0)
        root_layout.add_widget(primary_frame)

    @Slot()
    def _on_reset_pressed(self) -> None:
        """
        Slot function that resets the slider and spin box values to their default states.

        - Generated by Gemini
        """
        self._slider.value = self._default_value
        self._spin_box.value = self._default_value


class QRealSliderGroup(QAbstractSliderGroup):
    """
    A concrete implementation of QAbstractSliderGroup for floating-point values.

    Connects the QRealSlider to a QDoubleSpinBox, providing high-precision inputs
    for physics parameters like viscosity or wind speed.

    :ivar realValueChanged: Signal emitted when the floating-point value is updated.

    - Generated by Gemini
    """
    realValueChanged = Signal(float)

    def __init__(self, text: str, parent: QWidget | None = None) -> None:
        """
        Initializes the group with a real-valued slider and double spinbox.

        :param text: Header text.
        :param parent: Optional parent widget.

        - Generated by Gemini
        """
        super().__init__(text, QRealSlider(), QDoubleSpinBox(), parent)

        # Connections
        self._slider.realValueChanged.connect(self._on_slider_value_changed)
        self._spin_box.valueChanged.connect(self._on_spin_box_value_changed)

    @Slot(float)
    def _on_slider_value_changed(self, value: float) -> None:
        self._spin_box.value = value
        self.realValueChanged.emit(value)

    @Slot(float)
    def _on_spin_box_value_changed(self, value: float | int) -> None:
        self._slider.value = value

    @property
    def value(self) -> float | int:
        """
        Retrieves the current real value.
        :rtype: float | int
        - Generated by Gemini
        """
        return self._slider.value

    @value.setter
    def value(self, value: float | int) -> None:
        """
        Sets the value, synchronizing both input elements.
        - Generated by Gemini
        """
        self._slider.value = value
        self._spin_box.value = value

    @property
    def maximum(self) -> float | int:
        """
        Retrieves the upper bound.
        :rtype: float | int
        - Generated by Gemini
        """
        return self._slider.maximum

    @maximum.setter
    def maximum(self, value: float | int) -> None:
        """
        Sets the upper bound for both inputs.
        - Generated by Gemini
        """
        self._slider.maximum = value
        self._spin_box.maximum = value

    @property
    def minimum(self) -> float | int:
        """
        Retrieves the lower bound.
        :rtype: float | int
        - Generated by Gemini
        """
        return self._slider.minimum

    @minimum.setter
    def minimum(self, value: float | int) -> None:
        """
        Sets the lower bound for both inputs.
        - Generated by Gemini
        """
        self._slider.minimum = value
        self._spin_box.minimum = value

    @property
    def single_step(self) -> float | int:
        """
        Retrieves the float increment step size.
        :rtype: float | int
        - Generated by Gemini
        """
        return self._spin_box.single_step

    @single_step.setter
    def single_step(self, step: float | int) -> None:
        """
        Sets the float increment step size.
        - Generated by Gemini
        """
        self._spin_box.single_step = step
        self._slider.single_step = step

    def set_value(self, value: float | int) -> None:
        """
        Forces a value update on the slider and spinbox.
        - Generated by Gemini
        """
        self._slider.value = value
        self._spin_box.value = value

    def set_range(self, min_range: float | int, max_range: float | int) -> None:
        """
        Sets the range constraints for both input elements.
        - Generated by Gemini
        """
        self._slider.set_range(min_range, max_range)
        self._spin_box.set_range(min_range, max_range)

    @property
    def default_value(self) -> float | int:
        """
        Retrieves the default reset value.
        :rtype: float | int
        - Generated by Gemini
        """
        return self._default_value

    @default_value.setter
    def default_value(self, value: float | int) -> None:
        """
        Sets the default reset value.
        - Generated by Gemini
        """
        self._default_value = value
        self._slider.value = value
        self._spin_box.value = value

    @property
    def decimals(self) -> int:
        """
        Retrieves the decimal precision for the spinbox.
        :rtype: int
        - Generated by Gemini
        """
        return self._slider.decimals

    @decimals.setter
    def decimals(self, value: int) -> None:
        """
        Sets the decimal precision for the spinbox.
        - Generated by Gemini
        """
        self._slider.decimals = value
        self._spin_box.decimals = value


