    def _scale_current(self, cursor_position: QPoint):
        """
        Scales the current shape being processed based on the movement of the cursor. The scaling is
        centered around a predefined point and applied proportionally according to the distance between
        the cursor and the center. - Generated by OpenAI's GPT-5.5

        :param cursor_position: The current position of the cursor used to calculate the scaling factor.
        :type cursor_position: QPoint
        :return: None
        """
        if (not self._current_shape or not self.is_scaling or
                not self._scale_start_verts or not self._scale_center):
            return

        self._update_cursor_shape_line(cursor_position)

        center = self._scale_center

        start_dist = (self._scale_start_qp - center).manhattan_length()
        current_dist = (cursor_position - center).manhattan_length()

        if start_dist == 0:
            return

        scale_factor = current_dist / start_dist
        self._current_shape.scale_selected(scale_factor, self._scale_start_verts, center)

        self._update_selected_rect()

    def _rotate_current(self, cursor_position: QPoint):
        """
        Rotates the currently selected shape based on cursor movement. This function calculates
        the angular difference between the initial rotation angle and the current angle,
        then applies the resulting rotation to the selected vertices of the shape. Additionally,
        it updates the cursor shape line and the bounding rectangle for the selected shape.
        - Generated by OpenAI's GPT-5.5

        :param cursor_position: Current position of the cursor used for rotation calculation.
        :type cursor_position: QPoint
        """
        if (not self._current_shape or not self.is_rotating or
                not self._rotate_start_verts or not self._rotate_center):
            return

        self._update_cursor_shape_line(cursor_position)

        center = self._rotate_center

        start_delta_y = self._rotate_start_qp.y() - center.y()
        start_delta_x = self._rotate_start_qp.x() - center.x()
        start_angle = math.atan2(start_delta_y, start_delta_x)

        current_delta_y = cursor_position.y() - center.y()
        current_delta_x = cursor_position.x() - center.x()
        current_angle = math.atan2(current_delta_y, current_delta_x)

        delta_angle = current_angle - start_angle
        self._current_shape.rotate_selected(delta_angle, self._rotate_start_verts, center)

        self._update_selected_rect()

    def _update_cursor_shape_line( self, cursor_position: QPoint ):
        """
        Updates the cursor shape line based on the cursor position and the current state of the object
        (rotation or scaling). Determines the new line connecting the rotation or scaling center
        to the current cursor position if the corresponding operation is active. - Generated by OpenAI's GPT-5.5

        :param cursor_position: Current position of the cursor.
        :type cursor_position: QPoint
        :return: None
        """
        if not self._current_shape:
            self._cursor_shape_line = None
            return

        if not self.is_scaling and not self.is_rotating:
            self._cursor_shape_line = None
            return

        if self.is_rotating and self._rotate_center is not None:
            center = self._rotate_center
            self._cursor_shape_line = QLine(center, cursor_position)
        elif self.is_scaling and self._scale_center is not None:
            center = self._scale_center
            self._cursor_shape_line = QLine(center, cursor_position)

    def _move_current( self, cursor_position: QPoint ) -> None:
        """
        Adjusts the current shape's position based on the given cursor position. The method calculates
        the delta movement from the initial starting point and moves the shape accordingly. If the Shift
        key is being held, the delta is snapped to a grid based on the cell width. - Generated by OpenAI's GPT-5.5

        :param cursor_position: The current position of the cursor.
        :type cursor_position: QPoint
        :return: None
        """
        if not self._current_shape or not self.is_moving or not self._move_start_qp or not self._move_start_verts:
            return

        delta = cursor_position - self._move_start_qp

        if self._state_manager.key_state == QStateManager.KeyState.HOLDING_SHIFT:
            delta = QPoint(round(delta.x() / self._cell_width)*self._cell_width,
                           round(delta.y() / self._cell_width)*self._cell_width)

        self._current_shape.move_selected_to_delta(delta, self._move_start_verts)
        self._update_selected_rect()

