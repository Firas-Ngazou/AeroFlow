@dataclass
class Vertex:
    """
    My fundamental data structure for representing a single point in the vector graphics system.

    It tracks its own 2D position, its current interaction state, and its index within the parent shape
    to make array operations easier.

    :ivar position: The raw (X, Y) canvas coordinates.
    :type position: QPoint
    :ivar state: The current visual and interactive state of the vertex.
    :type state: Vertex.VertexState
    :ivar index_position: The numerical order of this vertex within the parent shape's list.
    :type index_position: int

    - Generated by Gemini
    """

    class VertexState(Enum):
        """
        The internal interaction states I use to dictate how a vertex should be rendered and handled.

        :ivar DEFAULT: Resting state, no interaction.
        :type DEFAULT: int
        :ivar SELECTED: Part of the active selection group.
        :type SELECTED: int
        :ivar HOVERED: The mouse is currently over this specific vertex.
        :type HOVERED: int
        :ivar HELD: The user is actively clicking and dragging this vertex.
        :type HELD: int
        :ivar HOVERED_SELECTED: The mouse is over a vertex that is already selected.
        :type HOVERED_SELECTED: int
        :ivar MEDIAN: A dynamically generated midpoint used for adding new vertices.
        :type MEDIAN: int

        - Generated by Gemini
        """
        DEFAULT = 0
        SELECTED = 1
        HOVERED = 2
        HELD = 3
        HOVERED_SELECTED = 4
        MEDIAN = 5

    position: QPoint
    state: VertexState = VertexState.DEFAULT
    index_position: int = -1

    def move(self, delta_x: int, delta_y: int) -> None:
        """
        Shifts the vertex position by a discrete pixel offset.

        :param delta_x: The translation offset along the X-axis.
        :type delta_x: int
        :param delta_y: The translation offset along the Y-axis.
        :type delta_y: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self.position.set_x(self.position.x() + delta_x)
        self.position.set_y(self.position.y() + delta_y)


class Shape:
    """
    The core geometric container managing a sequence of Vertices.

    I built this to abstract away the complex rendering logic. It handles its own QPainterPath generation,
    median point calculations, and categorizes its vertices based on their interaction states so the main
    editor just has to call `draw()`.

    :ivar _state: The interaction state of the polygon itself.
    :type _state: Shape.ShapeState
    :ivar _status: Determines if the shape is actively being drawn (DEFAULT) or sealed (CLOSED).
    :type _status: Shape.ShapeStatus
    :ivar _vertices: The ordered list of Vertex objects defining the polygon boundary.
    :type _vertices: list[Vertex]
    :ivar _path: The cached PySide6 rendering path to avoid recreating QPolygonF every frame.
    :type _path: QPainterPath | None
    :ivar _categories: Groups vertices by state to optimize the rendering passes.
    :type _categories: dict
    :ivar _hide_vertices: Toggles the rendering of the vertex points themselves.
    :type _hide_vertices: bool
    :ivar _median_vertices: The dynamically generated midpoints between our main vertices.
    :type _median_vertices: list[Vertex] | None

    - Generated by Gemini
    """

    class ShapeState(Enum):
        """
        Tracks the overall interaction state of the polygon boundary.

        :ivar DEFAULT: Standard resting state.
        :type DEFAULT: int
        :ivar SELECTED: The shape is active for manipulation.
        :type SELECTED: int
        :ivar HOVERED: The mouse is within the shape's boundary.
        :type HOVERED: int
        :ivar HOVERED_DELETE: The mouse is over the shape while the user is holding the delete modifier.
        :type HOVERED_DELETE: int

        - Generated by Gemini
        """
        DEFAULT = 0
        SELECTED = 1
        HOVERED = 2
        HOVERED_DELETE = 3

    class ShapeStatus(Enum):
        """
        Tracks the structural status of the shape.

        :cvar DEFAULT: The shape is currently being drawn/extended.
        :cvar CLOSED: The loop is sealed and the shape is finalized.

        - Generated by Gemini
        """
        DEFAULT = 0
        CLOSED = 1

    def __init__(self, vertices: list[Vertex]) -> None:
        """
        Initializes the shape with a starting set of vertices and pre-allocates my styling brushes/pens.

        :param vertices: The initial sequence of points defining the shape.
        :type vertices: list[Vertex]

        - Generated by Gemini
        """
        self._vertex_min_radius = 5
        self._vertex_max_radius = 7

        # States
        self._state = Shape.ShapeState.SELECTED
        self._status = Shape.ShapeStatus.DEFAULT

        # Vertices
        self._vertices = vertices
        self._vertices_nd = np.empty((0, 2), dtype = int)
        self._update_vertices_nd()

        # Path & image data
        self._path: QPainterPath | None = None # QPainterPath for not having to re-make a QPolygonF every time

        # Categories
        self._categories = {state: [] for state in Vertex.VertexState}
        self._update_categories()

        # Settings
        self._hide_vertices = False

        # Median positions
        self._median_vertices: list[Vertex] | None = None  # The positions in between the vertices
        self._median_vertices_nd: np.ndarray | None = None
        self._current_median: Vertex | None = None
        self._current_median_path: QPainterPath | None = None

        # region Pens and brushes
        self._default_vertex_pen = QPen(QColor(179, 208, 255))  # light blue
        self._default_vertex_pen.set_width(2)
        self._selected_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._selected_vertex_pen.set_width(4)
        self._hovered_vertex_pen = QPen(QColor(179, 208, 255))  # light blue
        self._hovered_vertex_pen.set_width(2)
        self._held_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._held_vertex_pen.set_width(4)
        self._hovered_selected_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._hovered_selected_vertex_pen.set_width(4)

        self._default_vertex_brush = QBrush(QColor(245, 245, 245))  # white
        self._selected_vertex_brush = QBrush(QColor(245, 245, 245))  # white
        self._hovered_vertex_brush = QBrush(QColor(204, 204, 204))  # light gray
        self._held_vertex_brush = QBrush(QColor(171, 171, 171))  # dark gray
        self._hovered_selected_vertex_brush = QBrush(QColor(204, 204, 204))  # light gray

        self._shape_pen = QPen(QColor(245, 245, 245))
        self._shape_pen.set_width(2)
        self._shape_brush = QBrush(QColor(220, 220, 220, 100))
        self._shape_hover_pen = QPen(QColor(0, 124, 217))
        self._shape_hover_pen.set_width(4)
        self._shape_hover_brush = QBrush(QColor(119, 197, 255, 100))
        self._shape_hover_delete_pen = QPen(QColor(225, 0, 0))
        self._shape_hover_delete_pen.set_width(4)
        self._shape_hover_delete_brush = QBrush(QColor(225, 0, 0, 100))

        self._median_vertex_pen = QPen(QColor(179, 208, 255))
        self._median_vertex_pen.set_width(4)
        self._median_vertex_brush = QBrush(QColor(179, 208, 255))

        self._painter_configs = {
            Vertex.VertexState.DEFAULT: (self._default_vertex_pen, self._default_vertex_brush, self._vertex_min_radius),
            Vertex.VertexState.SELECTED: (self._selected_vertex_pen, self._selected_vertex_brush,
                                          self._vertex_max_radius),
            Vertex.VertexState.HOVERED: (self._hovered_vertex_pen, self._hovered_vertex_brush, self._vertex_min_radius),
            Vertex.VertexState.HELD: (self._held_vertex_pen, self._held_vertex_brush, self._vertex_max_radius),
            Vertex.VertexState.HOVERED_SELECTED: (self._hovered_selected_vertex_pen,
                                                  self._hovered_selected_vertex_brush, self._vertex_max_radius),
        }
        # endregion

    # region Painting Logic
    def draw(self, painter: QPainter) -> None:
        """
        My main render dispatch for the shape.

        Applies the correct styling based on the polygon's hover/delete state, forces the path to close
        if the status demands it, and then cascades down to draw the individual vertices.

        :param painter: The active QPainter context provided by the canvas.
        :type painter: QPainter
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._path is None: self._update_path()
        if self._state == Shape.ShapeState.HOVERED:
            painter.set_pen(self._shape_hover_pen)
            painter.set_brush(self._shape_hover_brush)
        elif self._state == Shape.ShapeState.HOVERED_DELETE:
            painter.set_pen(self._shape_hover_delete_pen)
            painter.set_brush(self._shape_hover_delete_brush)
        else:
            painter.set_pen(self._shape_pen)
            painter.set_brush(self._shape_brush)

        if self._status == Shape.ShapeStatus.CLOSED:
            self._path.close_subpath()
        painter.draw_path(self._path)

        if not self._hide_vertices: self._draw_vertices(painter)

    def _draw_vertices(self, painter: QPainter) -> None:
        """
        Iterates through my state-categorized vertices and applies their specific styling before drawing.
        Also handles rendering the interactive 'add median' crosshair if the user is hovering a midpoint.

        :param painter: The active QPainter context.
        :type painter: QPainter
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._vertices:
            for state, (pen, brush, radius) in self._painter_configs.items():
                painter.set_pen(pen)
                painter.set_brush(brush)

                for vertex in self._categories[state]:
                    painter.draw_ellipse(vertex.position, radius, radius)

            painter.set_pen(self._median_vertex_pen)
            painter.set_brush(self._median_vertex_brush)
            if self._current_median is not None:
                painter.draw_path(self._current_median_path)

    # endregion

    # region Vertex Addition
    def add_point(self, position: QPoint) -> None:
        """
        Appends a new vertex to the active shape path.

        Only works if the shape is still in drawing mode (not CLOSED). I automatically unselect
        everything else so the new point becomes the sole active selection.

        :param position: The canvas coordinates for the new point.
        :type position: QPoint
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._status == Shape.ShapeStatus.CLOSED: return
        # Unselecting all vertices
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)

        # Adding the vertex to the shape at the end of the lists
        self._vertices.append(Vertex(position = position, state = Vertex.VertexState.SELECTED,
                                     index_position = len(self._vertices)))
        self._vertices_nd = np.append(self._vertices_nd, [[position.x(), position.y()]], axis = 0)

        self._update_categories()
        self._update_path()

    def add_median_vertex(self) -> None:
        """
        Converts the actively hovered median point into a permanent, structural vertex.

        I use this so the user can easily subdivide segments of a closed shape. It automatically
        re-indexes the entire vertex array to keep the boundary sequence valid.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if not self._current_median or self._status != Shape.ShapeStatus.CLOSED: return
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        self._current_median.state = Vertex.VertexState.SELECTED

        self._vertices.insert(self._current_median.index_position + 1, self._current_median)
        self._current_median.index_position = len(self._vertices) - 1

        for i, vertex in enumerate(self._vertices):
            vertex.index_position = i

        self._current_median = None

        self._update_vertices_nd()
        self._update_categories()
        self._update_path()

    # endregion

    # region Vertex Manipulation
    def unselect_path(self) -> None:
        """
        Finalizes the shape loop, clears all vertex selections, and hides the points.
        This represents the shape resting cleanly on the canvas without active focus.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._status = Shape.ShapeStatus.CLOSED
        self._state = Shape.ShapeState.DEFAULT
        self.reset_selected_vertices()
        self._update_path()
        self._hide_vertices = True

    def select_path(self) -> None:
        """
        Activates the shape for manipulation, un-hiding the vertex points.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._state = Shape.ShapeState.SELECTED
        self._hide_vertices = False

    def move_held_vertices(self, delta_x: int, delta_y: int) -> None:
        """
        Translates all vertices currently marked as 'HELD' by a specific pixel offset.

        This is my core hook for multi-vertex drag-and-drop operations.

        :param delta_x: X-axis shift.
        :type delta_x: int
        :param delta_y: Y-axis shift.
        :type delta_y: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.move(delta_x, delta_y)
            self._update_vertices_nd(vertex.index_position)
        self._update_path()

    def move_held_vertices_to_point(self, position: QPoint) -> None:
        """
        Forces all 'HELD' vertices to snap to an exact, absolute coordinate.

        Mostly used when a single vertex is grabbed, or when I'm enforcing grid-snapping.

        :param position: The target absolute coordinate.
        :type position: QPoint
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.position = position
            self._update_vertices_nd(vertex.index_position)
        self._update_path()

    def select_content(self, area: QRect) -> None:
        """
        Highlights and selects all vertices that fall within the bounds of a dragging selection box.

        :param area: The bounding box drawn by the user.
        :type area: QRect
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._vertices:
            if area.contains(vertex.position):
                self.select_vertex(vertex, unselect_others = False)

    def hold_selection(self) -> None:
        """
        Upgrades all currently 'SELECTED' vertices into the 'HELD' state in preparation for a mouse drag.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._categories[Vertex.VertexState.SELECTED]:
            self.hold_vertex(vertex)

    def select_all(self) -> None:
        """
        Forces every vertex in this shape into the active 'SELECTED' group.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._switch_category_state(Vertex.VertexState.DEFAULT, Vertex.VertexState.SELECTED)
        self._switch_category_state(Vertex.VertexState.HOVERED, Vertex.VertexState.SELECTED)
        self._update_categories()

    # endregion

    # region State Manipulation
    def hover_vertex(self, vertex: Vertex) -> None:
        """
        Escalates a vertex to its hover state so I can render visual feedback when the cursor passes over it.

        :param vertex: The target vertex.
        :type vertex: Vertex
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        match vertex.state:
            case Vertex.VertexState.DEFAULT:
                vertex.state = Vertex.VertexState.HOVERED
            case Vertex.VertexState.SELECTED:
                vertex.state = Vertex.VertexState.HOVERED_SELECTED
        self._update_categories()

    def select_vertex(self, vertex: Vertex, unselect_others: bool = False) -> None:
        """
        Marks a specific vertex as selected, giving me the option to purge the rest of the selection group.

        :param vertex: The target vertex.
        :type vertex: Vertex
        :param unselect_others: True to clear existing selections, False to append to them.
        :type unselect_others: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if unselect_others: self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        vertex.state = Vertex.VertexState.SELECTED
        self._update_categories()

    def hold_vertex(self, vertex: Vertex, unselect_others: bool = False) -> None:
        """
        Locks a vertex into the 'HELD' drag state.

        :param vertex: The target vertex.
        :type vertex: Vertex
        :param unselect_others: True to drop all other held items.
        :type unselect_others: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if unselect_others: self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        vertex.state = Vertex.VertexState.HELD
        self._update_categories()

    def release_all(self) -> None:
        """
        Drops all dragged vertices back down into standard 'SELECTED' states. Called on mouse release.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.state = Vertex.VertexState.SELECTED
        self._update_categories()

    def reset_selected_vertices(self) -> None:
        """
        Purges the active selection group and resets those vertices back to DEFAULT.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        self._update_categories()

    def reset_hovered_vertices(self) -> None:
        """
        Clears out temporary hover states and drops vertices back to their underlying state.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._switch_category_state(Vertex.VertexState.HOVERED, Vertex.VertexState.DEFAULT)
        self._switch_category_state(Vertex.VertexState.HOVERED_SELECTED, Vertex.VertexState.SELECTED)
        self._update_categories()

    # endregion

    def is_over_shape(self, position: QPoint) -> bool:
        """
        Hit-testing function to check if the mouse is hovering inside the filled polygon bounds.

        :param position: The mouse coordinates.
        :type position: QPoint
        :return: True if inside the shape path.
        :rtype: bool

        - Generated by Gemini
        """
        self._state = Shape.ShapeState.DEFAULT
        if self._path.contains(position):
            return True
        return False

    def highlight(self, for_deletion: bool = False) -> None:
        """
        Flags the shape for visual highlighting. Turns it red if the user is holding the delete modifier.

        :param for_deletion: Trigger the destructive visual cue.
        :type for_deletion: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if for_deletion:
            self._state = Shape.ShapeState.HOVERED_DELETE
            return
        self._state = Shape.ShapeState.HOVERED

    def delete_selected_vertices(self) -> None:
        """
        Strips the selected vertices out of the polygon sequence and re-indexes the remainder.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if not self._vertices: return
        self._vertices = [vertex for vertex in self._vertices if vertex.state != Vertex.VertexState.SELECTED and
                          vertex.state != Vertex.VertexState.HOVERED_SELECTED]

        for new_index, vertex in enumerate(self._vertices):
            vertex.index_position = new_index

        self._update_vertices_nd()
        self._update_categories()
        self._update_path()

    def translate(self, delta_x: int, delta_y: int) -> None:
        """
        Shifts the entire shape globally across the canvas. Used heavily during resize events
        to keep the drawing centered.

        :param delta_x: X-axis shift.
        :type delta_x: int
        :param delta_y: Y-axis shift.
        :type delta_y: int
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if not self._vertices: return
        for vertex in self._vertices:
            vertex.position += QPoint(delta_x, delta_y)
        self._vertices_nd += np.array([[delta_x, delta_y]] * self._vertices_nd.shape[0], dtype = int)
        self._update_path()

    def scale_selected(self, factor: float | int, start_verts: list[QPoint], center: QPoint) -> None:
        """
        Applies a proportional scale matrix to the active selection group relative to a specified center point.

        :param factor: The scaling multiplier.
        :type factor: float | int
        :param start_verts: The baseline positions before the drag started.
        :type start_verts: list[QPoint]
        :param center: The origin pivot for the scale.
        :type center: QPoint
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            relative_x = start_pos.x() - center.x()
            relative_y = start_pos.y() - center.y()

            vertex.position = QPoint(int(center.x() + relative_x * factor),
                                     int(center.y() + relative_y * factor))

        self.clean_update()

    def rotate_selected(self, delta: float | int, start_verts: list[QPoint], center: QPoint) -> None:
        """
        Applies a rotation matrix to the active selection group around a pivot.

        I calculate the new angle via arctan2 off the initial positions so the rotation smoothly
        follows the mouse cursor without snapping violently.

        :param delta: The angle delta in radians.
        :type delta: float | int
        :param start_verts: Baseline positions.
        :type start_verts: list[QPoint]
        :param center: The origin pivot.
        :type center: QPoint
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            relative_x = start_pos.x() - center.x()
            relative_y = start_pos.y() - center.y()

            norm = math.sqrt(relative_x ** 2 + relative_y ** 2)
            start_angle = math.atan2(relative_y, relative_x)
            new_angle = start_angle + delta

            new_x = center.x() + norm * math.cos(new_angle)
            new_y = center.y() + norm * math.sin(new_angle)

            vertex.position = QPoint(int(new_x), int(new_y))

        self.clean_update()

    def move_selected_to_delta(self, delta: QPoint, start_verts: list[QPoint]) -> None:
        """
        Translates the selection group using a clean mouse-drag delta calculation.

        :param delta: The (X,Y) shift vector.
        :type delta: QPoint
        :param start_verts: The baseline layout.
        :type start_verts: list[QPoint]
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            vertex.position = QPoint(start_pos + delta)

        self.clean_update()

    def is_in_delete_rect(self, rect: QRect) -> bool:
        """
        Fast numpy-based bounding box intersection check to see if the shape falls inside the delete marquee.

        :param rect: The selection box.
        :type rect: QRect
        :return: True if the shape overlaps the box.
        :rtype: bool

        - Generated by Gemini
        """
        self._state = Shape.ShapeState.DEFAULT
        x_coords = self._vertices_nd[:, 0]
        y_coords = self._vertices_nd[:, 1]

        normalized_rect = rect.normalized()

        left, top, right, bottom = normalized_rect.get_coords()
        inside_x = (left <= x_coords) & (x_coords <= right)
        inside_y = (top <= y_coords) & (y_coords <= bottom)

        if np.any(inside_x & inside_y):
            self._state = Shape.ShapeState.HOVERED_DELETE
            return True
        return False

    # region Near Vertex Logic
    def near_vertex(self, position: QPoint) -> Vertex | None:
        """
        Checks if the mouse cursor is close enough to snap to an existing vertex.

        :param position: The mouse coordinates.
        :type position: QPoint
        :return: The closest vertex within the hit radius.
        :rtype: Vertex | None

        - Generated by Gemini
        """
        return self._near_point(position, self._vertices_nd, self._vertices)

    def update_near_median(self, position: QPoint) -> None:
        """
        Hit-tests the mouse against my calculated median points. If the user hovers one,
        I generate the crosshair painter path to signal that they can subdivide the segment here.

        :param position: The mouse coordinates.
        :type position: QPoint
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._median_vertices is None: return
        median = self._near_point(position, self._median_vertices_nd, self._median_vertices)
        if median:
            median.state = Vertex.VertexState.MEDIAN
            self._current_median = median

            # Visuals
            self._current_median_path = QPainterPath()
            cross_line_length = 7
            cross_line_1 = QLine(QPoint(median.position.x() - cross_line_length // 2,
                                        median.position.y() - cross_line_length // 2),
                                 QPoint(median.position.x() + cross_line_length // 2,
                                        median.position.y() + cross_line_length // 2))
            cross_line_2 = QLine(QPoint(median.position.x() - cross_line_length // 2,
                                        median.position.y() + cross_line_length // 2),
                                 QPoint(median.position.x() + cross_line_length // 2,
                                        median.position.y() - cross_line_length // 2))
            self._current_median_path.move_to(cross_line_1.p1())
            self._current_median_path.line_to(cross_line_1.p2())
            self._current_median_path.move_to(cross_line_2.p1())
            self._current_median_path.line_to(cross_line_2.p2())

        else:
            self._current_median = None

    def _near_point(self, position: QPoint, nd_data: np.ndarray, vertices_data: list[Vertex]) -> Vertex | None:
        """
        Internal numpy vectorizer to rapidly find the closest point in an array within my designated hit radius.

        :param position: The target mouse coordinates.
        :type position: QPoint
        :param nd_data: The numpy array of coordinates to search against.
        :type nd_data: np.ndarray
        :param vertices_data: The corresponding list of Vertex objects.
        :type vertices_data: list[Vertex]
        :return: The closest valid Vertex.
        :rtype: Vertex | None

        - Generated by Gemini
        """
        if nd_data.size < 1: return None
        target_pos = np.array([position.x(), position.y()])
        distances = np.linalg.norm(nd_data - target_pos, axis = 1)
        nearest_index = np.argmin(distances)
        nearest_pos = distances[nearest_index]

        if nearest_pos < self._vertex_max_radius:
            return vertices_data[nearest_index]
        return None

    # endregion

    def get_pixel_data(self, width: int, height: int) -> np.ndarray:
        """
        Rasterizes the internal vector shape out to a boolean pixel map.

        I use this to feed the actual rigid boundaries into the fluid simulation matrix.
        It draws the path pure white onto a temporary image and extracts the byte coordinates.

        :param width: Target grid width.
        :type width: int
        :param height: Target grid height.
        :type height: int
        :return: The isolated boundary coordinates.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        image = QImage(width, height, QImage.Format.Format_Grayscale8)
        image.fill(0)

        painter = QPainter(image)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)
        painter.set_pen(QPen(QColor(255, 255, 255)))
        painter.set_brush(QBrush(QColor(255, 255, 255)))
        painter.draw_path(self._path)
        painter.end()

        data = image.const_bits()
        bytes_per_line = image.bytes_per_line()  # gets the real stored width of the image in bytes including ghost bytes
        padded_pixels = np.frombuffer(data, dtype = np.uint8).reshape((height, bytes_per_line))
        pixels = padded_pixels[:, :width]
        shape_pixels = np.argwhere(pixels == 255)

        return np.fliplr(shape_pixels)

    # region Update Methods
    def _update_categories(self) -> None:
        """
        Re-sorts the vertices into their state buckets so my rendering loops remain optimized.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for state in Vertex.VertexState:
            self._categories[state] = []
        for vertex in self._vertices:
            self._categories[vertex.state].append(vertex)

    def _update_path(self) -> None:
        """
        Re-bakes the internal QPainterPath geometry whenever vertices are moved or added.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._update_median_positions()
        qt_points = [QPoint(x, y) for x, y in self._vertices_nd]
        polygon = QPolygonF(qt_points)
        path = QPainterPath()
        path.add_polygon(polygon)
        self._path: QPainterPath = path

    def _update_vertices_nd(self, index_position: int = None) -> None:
        """
        Synchronizes the numpy coordinate cache with the underlying Python objects.

        :param index_position: If provided, only updates that specific slice of the array.
        :type index_position: int | None
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if not self._vertices:
            self._vertices_nd = np.empty((0, 2), dtype = int)
            return

        if index_position is not None:
            self._vertices_nd[index_position] = [self._vertices[index_position].position.x(),
                                                 self._vertices[index_position].position.y()]
            return

        self._vertices_nd = np.array([[vertex.position.x(), vertex.position.y()] for vertex in self._vertices],
                                     dtype = int)

    def _update_median_positions(self) -> None:
        """
        Calculates the midpoint between every adjacent vertex to allow structural subdivisions.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        # Currently updating the whole median list, even when not needed.
        if not self._vertices or len(self._vertices) < 2:
            self._median_vertices = None
            return

        self._median_vertices = None
        for i, vertex in enumerate(self._vertices):
            right_vert = self._vertices[i + 1] if i + 1 < len(self._vertices) else self._vertices[0]
            left_vert = vertex

            delta_x = right_vert.position.x() - left_vert.position.x()
            delta_y = right_vert.position.y() - left_vert.position.y()
            median_vertex = Vertex(position = QPoint(left_vert.position.x() + delta_x // 2,
                                                     left_vert.position.y() + delta_y // 2),
                                   state = Vertex.VertexState.MEDIAN,
                                   index_position = vertex.index_position)
            if i == 0:
                self._median_vertices = [median_vertex]
            else:
                self._median_vertices.append(median_vertex)

        self._median_vertices_nd = np.array([[vertex.position.x(), vertex.position.y()]
                                             for vertex in self._median_vertices])

    def _update_vertices_obj(self) -> None:
        """
        Reverse-syncs the Python objects out of the numpy coordinate cache.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if not self._vertices_nd.any():
            return

        self._vertices = [Vertex(position = QPoint(x, y), state = Vertex.VertexState.DEFAULT, index_position = i)
                          for i, (x, y) in enumerate(self._vertices_nd)]

    def clean_update(self) -> None:
        """
        Fires a full synchronization pass across the path geometry and numpy arrays.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._update_vertices_nd()
        self._update_path()

    # endregion

    def change_shape_nd(self, vertices: np.ndarray) -> None:
        """
        Hot-swaps the underlying shape geometry from a raw numpy array injection.

        :param vertices: The new geometric coordinates.
        :type vertices: np.ndarray
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._vertices_nd = vertices
        self._update_vertices_obj()
        self._update_categories()
        self._update_path()

    def _switch_category_state(self, category: Vertex.VertexState, state: Vertex.VertexState) -> None:
        """
        Bulk updates the state flag across an entire grouping of vertices.

        :param category: The group to target.
        :type category: Vertex.VertexState
        :param state: The destination state.
        :type state: Vertex.VertexState
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        for vertex in self._categories[category]:
            vertex.state = state

    @property
    def selected_vertices(self) -> list[Vertex]:
        """
        Returns the pool of currently active/selected vertices.

        :return: List of selected vertices.
        :rtype: list[Vertex]

        - Generated by Gemini
        """
        return self._categories[Vertex.VertexState.SELECTED]

    @property
    def vertices(self) -> list[Vertex]:
        """
        Returns the full sequence of vertices for this shape.

        :return: List of all vertices.
        :rtype: list[Vertex]

        - Generated by Gemini
        """
        return self._vertices

    @property
    def current_median(self) -> Vertex | None:
        """
        Returns the actively hovered subdivision midpoint, if any.

        :return: The hovered median vertex.
        :rtype: Vertex | None

        - Generated by Gemini
        """
        return self._current_median

    @property
    def status(self) -> ShapeStatus:
        """
        Returns the overall structural mode of the shape (drawing or closed).

        :return: Shape's structural status.
        :rtype: Shape.ShapeStatus

        - Generated by Gemini
        """
        return self._status

    @property
    def vertices_nd(self) -> np.ndarray:
        """
        Returns the raw numpy array backing the vertex coordinates.

        :return: A 2D array of coordinates.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        return self._vertices_nd


