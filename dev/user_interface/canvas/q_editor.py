    def get_vertices(self) -> np.ndarray:
        """
        Extracts the full boolean pixel map of all valid shapes collapsed into one array.
        I send this array straight to the physics simulation engine.

        :return: The concatenated bounding coordinates.
        :rtype: np.ndarray

        - Generated by Gemini
        """
        vertices = np.empty((0, 2), dtype = int)
        for shape in self._shapes:
            vertices = np.concatenate((vertices, shape.get_pixel_data(self.width, self.height)), axis = 0)

        return vertices

    def get_pixmap(self, width: int, height: int) -> QPixmap:
        """
        Bakes out a clean snapshot of the canvas layout for preview icons or UI thumbnails.

        :param width: Target width.
        :type width: int
        :param height: Target height.
        :type height: int
        :return: The rendered frame.
        :rtype: QPixmap

        - Generated by Gemini
        """
        canvas = QPixmap(QSize(width, height))
        canvas.fill(Qt.GlobalColor.transparent)

        painter = QPainter(canvas)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)
        painter.fill_rect(canvas.rect(), QColor(34, 34, 34))

        cell_size = self._cell_width
        tile = QPixmap(cell_size, cell_size)
        tile.fill(Qt.GlobalColor.transparent)

        tile_painter = QPainter(tile)
        grid_pen = QPen(QColor(75, 75, 75, 75))
        grid_pen.set_width(2)
        tile_painter.set_pen(grid_pen)
        tile_painter.draw_line(0, 0, cell_size, 0)
        tile_painter.draw_line(0, 0, 0, cell_size)
        tile_painter.end()

        painter.draw_tiled_pixmap(canvas.rect(), tile)

        self._draw_shapes(painter)
        painter.end()

        return canvas

    def get_base64_image(self, width: int, height: int) -> str:
        """
        Pulls a quick preview frame and encodes it directly to base64 for embedding into my JSON saves.

        :param width: Internal render width.
        :type width: int
        :param height: Internal render height.
        :type height: int
        :return: The base64 PNG string.
        :rtype: str

        - Generated by Gemini
        """
        canvas = self.get_pixmap(1920, int(1920 * (1 / 2.39)))

        pixmap = canvas.scaled(width, height, Qt.AspectRatioMode.KeepAspectRatio,
                               Qt.TransformationMode.SmoothTransformation)

        return self._pixmap_to_base64(pixmap)

    @staticmethod
    def _pixmap_to_base64(pixmap: QPixmap) -> str:
        """
        Helper method dumping a QPixmap directly into a text buffer so I don't touch the disk.

        :param pixmap: Target Qt image.
        :type pixmap: QPixmap
        :return: The encoded string.
        :rtype: str

        - Generated by Gemini
        """
        byte_array = QByteArray()
        buffer = QBuffer(byte_array)
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        pixmap.save(buffer, "PNG")

        return byte_array.to_base64().data().decode("utf-8")

    def save_data(self, include_shape_status: bool = True, include_preview: bool = True) -> dict:
        """
        Serializes the entire structural layout of the canvas into a JSON-friendly dictionary.

        :param include_shape_status: Whether to bake down the open/closed status.
        :type include_shape_status: bool
        :param include_preview: If True, bundles a base64 thumbnail into the payload.
        :type include_preview: bool
        :return: The structured layout packet.
        :rtype: dict

        - Generated by Gemini
        """
        shapes_data = []
        for shape in self._shapes:
            vertices = [{"x": vertex.position.x(), "y": vertex.position.y()} for vertex in shape.vertices]
            status = shape.status.value
            if include_shape_status:
                shape_data = {"Vertices": vertices, "Status": status}
            else:
                shape_data = {"Vertices": vertices}
            shapes_data.append(shape_data)

        if include_preview:
            preview = self.get_base64_image(400, int(400 * (1 / 2.39)))
            return {"Shapes": shapes_data, "Preview": preview}
        else:
            return {"Shapes": shapes_data}

    def load_data(self, data: dict) -> None:
        """
        Tears down the existing canvas and re-inflates the geometry directly from a saved dictionary block.

        :param data: The layout JSON data to parse.
        :type data: dict
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._exit_current_shape(False)
        self._shapes = []

        for shape_data in data.get("Data", {}).get("Shapes", []):
            self.add_shape(shape_data, False)

        self.update()

