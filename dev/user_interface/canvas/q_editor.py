    def get_pixel_data(self, width: int, height: int) -> np.ndarray:
        """
        Generates pixel data representing the filled regions of a drawn path
        in a grayscale image. The function utilizes a QPainter to render
        the path on a temporary QImage, extracts the pixel data as a numpy
        array, and returns the coordinates of the white (255-value) pixels. - Generated by OpenAI's GPT-5.5

        :param width: The width of the QImage canvas.
        :param height: The height of the QImage canvas.
        :return: A numpy array of coordinates, where each coordinate is a
            pair (x, y) of the white pixels (value 255) in the rendered image.
        :rtype: np.ndarray
        """
        image = QImage(width, height, QImage.Format.Format_Grayscale8)
        image.fill(0)

        painter = QPainter(image)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)
        painter.set_pen(QPen(QColor(255, 255, 255)))
        painter.set_brush(QBrush(QColor(255, 255, 255)))
        painter.draw_path(self._path)
        painter.end()

        data = image.const_bits()
        bytes_per_line = image.bytes_per_line() # gets the real stored width of the image in bytes including ghost bytes
        padded_pixels = np.frombuffer(data, dtype=np.uint8).reshape((height, bytes_per_line))
        pixels = padded_pixels[:, :width]
        shape_pixels = np.argwhere(pixels == 255)

        return np.fliplr(shape_pixels)

