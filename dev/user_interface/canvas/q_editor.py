    def add_shape(self, data: dict):
        """
        Adds a new shape to the collection of shapes based on the provided data. Each shape is
        composed of vertices, which are created from the input data. If a current shape is
        already active, it is exited before adding the new shape. Depending on the shape's
        status, it may be selected or unselected after being created. - Generated by OpenAI's GPT-5.5

        :param data: A dictionary containing shape configuration. It must include a "Vertices"
            key with a list of vertex coordinates. Each vertex is a dictionary with "x" and
            "y" keys specifying its position. Optionally, it may include a "Status" key that
            determines whether the shape is closed or open.
        :type data: dict
        :return: None
        """
        vertices = []

        for index, vertex_data in enumerate(data.get("Vertices", [])):
            position = QPoint(vertex_data.get("x"), vertex_data.get("y"))
            vertices.append(Vertex(position=position, state=Vertex.VertexState.DEFAULT, index_position=index))

        if not vertices: return

        new_shape = Shape(vertices)

        if self._current_shape is not None:
            self._exit_current_shape()

        if "Status" in data and data.get("Status") == Shape.ShapeStatus.CLOSED.value:
            new_shape.unselect_path()
        else:
            self._current_shape = new_shape
            new_shape.unselect_path()
            new_shape.select_path()
            self._update_selected_rect()

        self._shapes.append(new_shape)
        self.update()

