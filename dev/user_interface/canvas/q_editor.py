    def get_pixmap(self, width: int, height: int) -> QPixmap:
        """
        Generates a QPixmap object based on the specified dimensions.

        This method creates a QPixmap canvas with the given width and height,
        fills it with a transparent background color, and applies a grid pattern
        using custom drawing logic. Shapes are then drawn over the grid using
        specific internal logic. The resulting pixmap is returned for further use. - Generated by OpenAI's GPT 5.5

        :param width: The width of the QPixmap in pixels.
        :type width: int
        :param height: The height of the QPixmap in pixels.
        :type height: int
        :return: A QPixmap object with the specified dimensions and a custom grid
                 pattern, along with additional shapes drawn on top.
        :rtype: QPixmap
        """
        canvas = QPixmap(QSize(width, height))
        canvas.fill(Qt.GlobalColor.transparent)

        painter = QPainter(canvas)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)
        painter.fill_rect(canvas.rect(), QColor(34, 34, 34))

        cell_size = self._cell_width
        tile = QPixmap(cell_size, cell_size)
        tile.fill(Qt.GlobalColor.transparent)

        tile_painter = QPainter(tile)
        grid_pen = QPen(QColor(75, 75, 75, 75))
        grid_pen.set_width(2)
        tile_painter.set_pen(grid_pen)
        tile_painter.draw_line(0, 0, cell_size, 0)
        tile_painter.draw_line(0, 0, 0, cell_size)
        tile_painter.end()

        painter.draw_tiled_pixmap(canvas.rect(), tile)

        self._draw_shapes(painter)
        painter.end()

        return canvas

    def get_base64_image(self, width: int, height: int) -> str:
        """
        Generates a Base64 string representation of a scaled image derived from a canvas.

        The method creates an image canvas with a specific background and draws a grid on it.
        Subsequently, custom shapes are rendered on the canvas, and the resulting image is
        scaled to the specified dimensions. Finally, the image is encoded in Base64 format
        for use in applications requiring such formats (e.g., web-based rendering). - Generated by OpenAI's GPT 5.4

        :param width: The width of the final scaled image.
        :type width: int
        :param height: The height of the final scaled image.
        :type height: int
        :return: A Base64 string representation of the scaled image.
        :rtype: str
        """
        canvas = self.get_pixmap(1920, int(1920 * (1 / 2.39)))

        pixmap = canvas.scaled(width, height, Qt.AspectRatioMode.KeepAspectRatio,
                               Qt.TransformationMode.SmoothTransformation)

        return self._pixmap_to_base64(pixmap)

    @staticmethod
    def _pixmap_to_base64(pixmap: QPixmap) -> str:
        byte_array = QByteArray()
        buffer = QBuffer(byte_array)
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        pixmap.save(buffer, "PNG")

        return byte_array.to_base64().data().decode("utf-8")

