    def _get_shape_base64(self, shape: Shape) -> str:
        """
        Generates a Base64 string representation of a shape's preview image.

        This function creates a visual preview of the given shape as a QPixmap
        and converts it into a Base64-encoded string. The preview includes a
        scaled and centered rendering of the shape's outline and its vertices. - Generated by OpenAI's GPT-5.5

        :param shape: A Shape object whose preview image will be generated.
        :type shape: Shape
        :return: A Base64-encoded string representing the generated preview image.
        :rtype: str
        """
        target_size = self._prefab_preview_size
        margin = 15

        points = [vertex.position for vertex in shape.vertices]

        min_x = min(point.x() for point in points)
        max_x = max(point.x() for point in points)
        min_y = min(point.y() for point in points)
        max_y = max(point.y() for point in points)

        width = max(max_x - min_x, 1)
        height = max(max_y - min_y, 1)

        available_space = target_size - (margin * 2)
        scale = min(available_space / width, available_space / height)

        scaled_width = width * scale
        scaled_height = height * scale
        offset_x = (target_size - scaled_width)/2 - (min_x*scale)
        offset_y = ((target_size - scaled_height)/2 - (min_y*scale))

        preview = QPixmap(target_size, target_size)
        preview.fill(Qt.GlobalColor.transparent)

        painter = QPainter(preview)
        painter.set_render_hint(QPainter.RenderHint.Antialiasing)

        # Shape drawing (cuz it's highlighted by the user when he is hovering over it)
        path = QPainterPath()
        for i, point in enumerate(points):
            correct_x = point.x() * scale + offset_x
            correct_y = point.y() * scale + offset_y

            if i == 0:
                path.move_to(correct_x, correct_y)
            else:
                path.line_to(correct_x, correct_y)

        if shape.status.value == 1:
            path.close_subpath()

        painter.set_pen(QPen(QColor(245, 245, 245), 2))
        painter.set_brush(QBrush(QColor(220, 220, 220, 100)))
        painter.draw_path(path)

        # Vertices drawing
        painter.set_pen(QPen(QColor(77, 142, 255), 6))
        painter.set_brush(QBrush(QColor(245, 245, 245)))

        vertex_radius = 14

        for point in points:
            correct_x = point.x() * scale + offset_x
            correct_y = point.y() * scale + offset_y
            painter.draw_ellipse(QPointF(correct_x, correct_y), vertex_radius, vertex_radius)
        painter.end()

        return self._pixmap_to_base64(preview)

