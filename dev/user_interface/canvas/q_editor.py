@dataclass
class Vertex:
    """
    Represents a vertex in a graphical or logical system.

    This class encapsulates a vertex with attributes such as position, state, and index position,
    allowing for operations such as movement and interaction tracking. It provides a clear structure
    to manage individual vertices and their states in larger systems, like graphs or user_interface elements.
    - Generated by Claude Haiku 4.5

    :ivar position: The current position of the vertex in a 2D space.
    :type position: QPoint
    :ivar state: The current state of the vertex, represented by the VertexState enumeration.
    :type state: Vertex.VertexState
    :ivar index_position: An integer value representing the index or order of the vertex within a
                          collection or sequence. Defaults to -1, indicating no specific index.
    :type index_position: int
    """

    class VertexState(Enum):
        """
        Represents the different states a vertex can have in a graphical or logical
        context. It defines constant values that can be used to indicate and differentiate
        the vertex's interactions or conditions. - Generated by Claude Haiku 4.5

        This class provides an enumeration to handle and manage vertex states in a clean and
        organized manner, making the code more readable and maintainable. - Generated by Claude Haiku 4.5

        :ivar DEFAULT: The default state of the vertex when no interaction or condition
                       is applied.
        :type DEFAULT: int
        :ivar SELECTED: Indicates that the vertex is currently selected.
        :type SELECTED: int
        :ivar HOVERED: Indicates that the vertex is being hovered over, typically by a cursor.
        :type HOVERED: int
        :ivar HELD: Indicates that the vertex is being held, such as during a drag operation.
        :type HELD: int
        :ivar HOVERED_SELECTED: Indicates that the vertex is both hovered over and selected
                                at the same time.
        :type HOVERED_SELECTED: int
        :ivar MEDIAN: Represents a special state where the vertex is identified as a median
                      or central point in a particular context.
        :type MEDIAN: int
        """
        DEFAULT = 0
        SELECTED = 1
        HOVERED = 2
        HELD = 3
        HOVERED_SELECTED = 4
        MEDIAN = 5

    position: QPoint
    state: VertexState = VertexState.DEFAULT
    index_position: int = -1

    def move(self, delta_x: int, delta_y: int) -> None:
        """
        Updates the position of an object by a specified offset in the x and y directions. - Generated by Claude Haiku
        4.5

        :param delta_x: The offset to add to the current x-coordinate.
        :type delta_x: int
        :param delta_y: The offset to add to the current y-coordinate.
        :type delta_y: int
        :return: None
        """
        self.position.set_x(self.position.x() + delta_x)
        self.position.set_y(self.position.y() + delta_y)


class Shape:
    """
    Represents a geometric shape defined by vertices and rendering configurations.

    This class encapsulates the creation, management, and rendering of geometric
    shapes consisting of multiple vertices. It manages the visual state, categories,
    median positions, and other rendering-related aspects, ensuring dynamic updates
    as the shape is interacted with or modified. - Generated by Claude Haiku 4.5

    :ivar _state: The current state of the shape, such as selected or hovered.
    :type _state: Shape.ShapeState
    :ivar _status: The current status of the shape, such as default or closed.
    :type _status: Shape.ShapeStatus
    :ivar _vertices: A list of vertices defining the geometric structure of the shape.
    :type _vertices: list[Vertex]
    :ivar _path: The graphical path drawn for the shape, optimized for rendering.
    :type _path: QPainterPath or None
    :ivar _categories: Categorization of vertices based on their states.
    :type _categories: dict
    :ivar _hide_vertices: A flag indicating whether to hide the vertices during rendering.
    :type _hide_vertices: bool
    :ivar _median_vertices: A list of calculated median positions between vertices, if applicable.
    :type _median_vertices: list[Vertex] or None
    """

    class ShapeState(Enum):
        """
        Represents possible states of a shape in an application.

        Defines an enumeration to represent distinct states that a shape object
        can have. These states are intended to capture the various interactions
        and statuses a shape may experience, such as being selected, hovered over,
        or being in a default state. - Generated by Claude Haiku 4.5

        :ivar DEFAULT: The default state of the shape, indicating no interaction or
            specific status is active.
        :type DEFAULT: int
        :ivar SELECTED: Indicates the shape is selected.
        :type SELECTED: int
        :ivar HOVERED: Indicates the shape is hovered over, typically by a pointer
            or cursor.
        :type HOVERED: int
        :ivar HOVERED_DELETE: Indicates the shape is hovered with an intention to
            delete it.
        :type HOVERED_DELETE: int
        """
        DEFAULT = 0
        SELECTED = 1
        HOVERED = 2
        HOVERED_DELETE = 3

    class ShapeStatus(Enum):
        """
        Represents the status of a shape.

        This enumeration defines the possible statuses that a shape can have,
        such as a default or closed state. It can be used to specify or check
        the current state of a shape in a program. - Generated by Claude Haiku 4.5

        :cvar DEFAULT: Represents the default state of a shape.
        :cvar CLOSED: Represents a closed state of a shape.
        """
        DEFAULT = 0
        CLOSED = 1

    def __init__(self, vertices: list[Vertex]) -> None:
        """
        Represents a geometric shape composed of multiple vertices and their associated visual details. The class
        manages vertex states, categories, paths, median positions, and various rendering configurations for the
        shape and its vertices. - Generated by Claude Haiku 4.5

        :param vertices: A list of Vertex objects that represent points defining the shape.
        :type vertices: list[Vertex]
        """
        self._vertex_min_radius = 5
        self._vertex_max_radius = 7

        # States
        self._state = Shape.ShapeState.SELECTED
        self._status = Shape.ShapeStatus.DEFAULT

        # Vertices
        self._vertices = vertices
        self._vertices_nd = np.empty((0, 2), dtype=int)
        self._update_vertices_nd()

        # Path & image data
        self._path: QPainterPath | None = None # QPainterPath for not having to re-make a QPolygonF every time

        # Categories
        self._categories = {state: [] for state in Vertex.VertexState}
        self._update_categories()

        # Settings
        self._hide_vertices = False

        # Median positions
        self._median_vertices: list[Vertex] | None = None # The positions in between the vertices
        self._median_vertices_nd: np.ndarray | None = None
        self._current_median: Vertex | None = None
        self._current_median_path: QPainterPath | None = None

        # region Pens and brushes
        self._default_vertex_pen = QPen(QColor(179, 208, 255))  # light blue
        self._default_vertex_pen.set_width(2)
        self._selected_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._selected_vertex_pen.set_width(4)
        self._hovered_vertex_pen = QPen(QColor(179, 208, 255))  # light blue
        self._hovered_vertex_pen.set_width(2)
        self._held_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._held_vertex_pen.set_width(4)
        self._hovered_selected_vertex_pen = QPen(QColor(77, 142, 255))  # dark blue
        self._hovered_selected_vertex_pen.set_width(4)

        self._default_vertex_brush = QBrush(QColor(245, 245, 245))  # white
        self._selected_vertex_brush = QBrush(QColor(245, 245, 245))  # white
        self._hovered_vertex_brush = QBrush(QColor(204, 204, 204))  # light gray
        self._held_vertex_brush = QBrush(QColor(171, 171, 171))  # dark gray
        self._hovered_selected_vertex_brush = QBrush(QColor(204, 204, 204))  # light gray

        self._shape_pen = QPen(QColor(245, 245, 245))
        self._shape_pen.set_width(2)
        self._shape_brush = QBrush(QColor(220, 220, 220, 100))
        self._shape_hover_pen = QPen(QColor(0, 124, 217))
        self._shape_hover_pen.set_width(4)
        self._shape_hover_brush = QBrush(QColor(119, 197, 255, 100))
        self._shape_hover_delete_pen = QPen(QColor(225, 0, 0))
        self._shape_hover_delete_pen.set_width(4)
        self._shape_hover_delete_brush = QBrush(QColor(225, 0, 0, 100))

        self._median_vertex_pen = QPen(QColor(179, 208, 255))
        self._median_vertex_pen.set_width(4)
        self._median_vertex_brush = QBrush(QColor(179, 208, 255))

        self._painter_configs = {
            Vertex.VertexState.DEFAULT: (self._default_vertex_pen, self._default_vertex_brush, self._vertex_min_radius),
            Vertex.VertexState.SELECTED: (self._selected_vertex_pen, self._selected_vertex_brush,
                                          self._vertex_max_radius),
            Vertex.VertexState.HOVERED: (self._hovered_vertex_pen, self._hovered_vertex_brush, self._vertex_min_radius),
            Vertex.VertexState.HELD: (self._held_vertex_pen, self._held_vertex_brush, self._vertex_max_radius),
            Vertex.VertexState.HOVERED_SELECTED: (self._hovered_selected_vertex_pen,
                                                  self._hovered_selected_vertex_brush, self._vertex_max_radius),
        }
        # endregion

    #region Painting Logic
    def draw(self, painter: QPainter) -> None:
        """
        Draws the shape onto the provided QPainter object. The method adapts its
        behavior based on the current state and status of the shape, applying
        appropriate pens and brushes to represent the shape's visual styles. If
        the shape is in a closed status, the path is closed before being
        rendered. Additionally, vertices are drawn unless explicitly set to
        be hidden. - Generated by Claude Haiku 4.5

        :param painter: An instance of QPainter used to render the shape.
        :type painter: QPainter
        :return: None
        """
        if self._path is None: self._update_path()
        if self._state == Shape.ShapeState.HOVERED:
            painter.set_pen(self._shape_hover_pen)
            painter.set_brush(self._shape_hover_brush)
        elif self._state == Shape.ShapeState.HOVERED_DELETE:
            painter.set_pen(self._shape_hover_delete_pen)
            painter.set_brush(self._shape_hover_delete_brush)
        else:
            painter.set_pen(self._shape_pen)
            painter.set_brush(self._shape_brush)

        if self._status == Shape.ShapeStatus.CLOSED:
            self._path.close_subpath()
        painter.draw_path(self._path)

        if not self._hide_vertices: self._draw_vertices(painter)

    def _draw_vertices(self, painter: QPainter) -> None:
        """
        Draws vertices on the given QPainter object based on predefined configurations and categories.
        Also, if a median vertex is defined, it is drawn with specific attributes. - Generated by Claude Haiku 4.5

        :param painter: QPainter object used to render the vertices.
        :type painter: QPainter
        """
        if self._vertices:
            for state, (pen, brush, radius) in self._painter_configs.items():
                painter.set_pen(pen)
                painter.set_brush(brush)

                for vertex in self._categories[state]:
                    painter.draw_ellipse(vertex.position, radius, radius)

            painter.set_pen(self._median_vertex_pen)
            painter.set_brush(self._median_vertex_brush)
            if self._current_median is not None:
                painter.draw_path(self._current_median_path)

    #endregion

    #region Vertex Addition
    def add_point(self, position: QPoint) -> None:
        """
        Adds a new point to the shape if the shape is not closed. The point is added as
        a vertex to the shape with a default state of selected. Updates the internal
        representation of vertices and updates the shape's path and category status. - Generated by Claude Haiku 4.5

        :param position: The position of the new vertex to be added.
        :type position: QPoint
        :return: None
        """
        if self._status == Shape.ShapeStatus.CLOSED: return
        # Unselecting all vertices
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)

        # Adding the vertex to the shape at the end of the lists
        self._vertices.append(Vertex(position=position, state=Vertex.VertexState.SELECTED,
                                     index_position=len(self._vertices)))
        self._vertices_nd = np.append(self._vertices_nd, [[position.x(), position.y()]], axis=0)

        self._update_categories()
        self._update_path()

    def add_median_vertex(self) -> None:
        """
        Adds the current median vertex to the shape if it exists and the shape is in a
        CLOSED status. The median vertex is inserted into the vertex list and marked as
        selected. The method updates the index positions of all vertices in the list
        and ensures the internal state of the shape remains consistent. - Generated by Claude Haiku 4.5

        :raises RuntimeError: If the shape's status is not Shape.ShapeStatus.CLOSED.
        """
        if not self._current_median or self._status != Shape.ShapeStatus.CLOSED: return
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        self._current_median.state = Vertex.VertexState.SELECTED

        self._vertices.insert(self._current_median.index_position + 1, self._current_median)
        self._current_median.index_position = len(self._vertices) - 1

        for i, vertex in enumerate(self._vertices):
            vertex.index_position = i

        self._current_median = None

        self._update_vertices_nd()
        self._update_categories()
        self._update_path()

    #endregion

    #region Vertex Manipulation
    def unselect_path(self) -> None:
        """
        Unselects the current path and resets its state.

        This method closes the shape's path, resets the state to default, clears
        the selection of vertices, updates the path representation, and hides the
        vertices. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._status = Shape.ShapeStatus.CLOSED
        self._state = Shape.ShapeState.DEFAULT
        self.reset_selected_vertices()
        self._update_path()
        self._hide_vertices = True

    def select_path(self) -> None:
        """
        Selects and changes the current state of a shape to 'SELECTED' while ensuring
        that vertices are visible. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._state = Shape.ShapeState.SELECTED
        self._hide_vertices = False

    def move_held_vertices(self, delta_x: int, delta_y: int) -> None:
        """
        Moves all vertices currently in the 'held' state by specified deltas along the x and y axes. This
        operation adjusts the positions of the held vertices and updates their related data. - Generated by Claude Haiku
        4.5

        :param delta_x: The amount to move the held vertices along the x-axis.
        :type delta_x: int
        :param delta_y: The amount to move the held vertices along the y-axis.
        :type delta_y: int
        :return: None
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.move(delta_x, delta_y)
            self._update_vertices_nd(vertex.index_position)
        self._update_path()

    def move_held_vertices_to_point(self, position: QPoint) -> None:
        """
        Moves all held vertices to a specified position and updates their properties.

        This method iterates through all vertices in the "held" state, moves them
        to the given position, updates the necessary properties for each vertex,
        and then refreshes the connected path to ensure consistency. - Generated by Claude Haiku 4.5

        :param position: The target position to move the held vertices to. Represented as a QPoint.
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.position = position
            self._update_vertices_nd(vertex.index_position)
        self._update_path()

    def select_content(self, area: QRect) -> None:
        """
        Selects and highlights vertices within the given rectangular area.

        This method checks all existing vertices and selects only those whose positions are
        within the boundaries of the specified area. The selection is performed incrementally,
        allowing multiple vertices to be selected simultaneously without unselecting others. - Generated by Claude Haiku
        4.5

        :param area: The rectangular area to test for vertex selection.
        :type area: QRect
        :return: None
        """
        for vertex in self._vertices:
            if area.contains(vertex.position):
                self.select_vertex(vertex, unselect_others=False)

    def hold_selection(self) -> None:
        """
        Holds the selection by applying the `hold_vertex` method to all selected
        vertices in the current category.

        Selected vertices are identified from the specific vertex state within
        the internal data structure. - Generated by Claude Haiku 4.5

        :raises KeyError: If the `VertexState.SELECTED` category is not present
            in the categories dictionary.
        """
        for vertex in self._categories[Vertex.VertexState.SELECTED]:
            self.hold_vertex(vertex)

    def select_all(self) -> None:
        """
        Selects all vertices by switching their states to the selected state. This
        includes vertices that are in the default or hovered states. After updating
        the states, the vertex categories are refreshed to reflect the changes. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._switch_category_state(Vertex.VertexState.DEFAULT, Vertex.VertexState.SELECTED)
        self._switch_category_state(Vertex.VertexState.HOVERED, Vertex.VertexState.SELECTED)
        self._update_categories()

    #endregion

    #region State Manipulation
    def hover_vertex(self, vertex: Vertex) -> None:
        """
        Updates the state of the given vertex to reflect a 'hover' action. Changes
        the vertex state based on its current status. The function additionally
        triggers updates to related categories. - Generated by Claude Haiku 4.5

        :param vertex: The vertex whose hover state is to be updated.
        :type vertex: Vertex
        :return: None
        """
        match vertex.state:
            case Vertex.VertexState.DEFAULT:
                vertex.state = Vertex.VertexState.HOVERED
            case Vertex.VertexState.SELECTED:
                vertex.state = Vertex.VertexState.HOVERED_SELECTED
        self._update_categories()

    def select_vertex(self, vertex: Vertex, unselect_others: bool = False) -> None:
        """
        Selects the given vertex and updates its state while optionally unselecting other vertices.

        This method sets the state of the provided vertex to `SELECTED`. Additionally, if the
        `unselect_others` flag is set to `True`, all other vertices are unselected by switching
        their state to `DEFAULT`. After processing, vertex category states are updated to reflect
        the changes. - Generated by Claude Haiku 4.5

        :param vertex: The vertex instance to be selected.
        :param unselect_others: A boolean flag indicating whether all other vertices should
            be unselected. Defaults to False.
        :return: None
        """
        if unselect_others: self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        vertex.state = Vertex.VertexState.SELECTED
        self._update_categories()

    def hold_vertex(self, vertex: Vertex, unselect_others: bool = False) -> None:
        """
        Holds the given vertex by changing its state to HELD and optionally unselecting other vertices.

        This method modifies the state of a vertex and updates associated categories accordingly.
        If unselect_others is set to True, all other vertices currently selected will have their
        state switched back to the default category before holding the given vertex. - Generated by Claude Haiku 4.5

        :param vertex: The vertex object whose state is to be modified.
        :type vertex: Vertex
        :param unselect_others: A flag to determine whether to unselect all other vertices before holding the
                                specified vertex. Defaults to False.
        :type unselect_others: bool
        :return: None
        """
        if unselect_others: self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        vertex.state = Vertex.VertexState.HELD
        self._update_categories()

    def release_all(self) -> None:
        """
        Releases all vertices currently held and updates their state to `VertexState.SELECTED`.
        This method impacts internal categories of vertices and ensures they are properly updated
        afterwards. - Generated by Claude Haiku 4.5

        :return: None
        """
        for vertex in self._categories[Vertex.VertexState.HELD]:
            vertex.state = Vertex.VertexState.SELECTED
        self._update_categories()

    def reset_selected_vertices(self) -> None:
        """
        Reset the state of selected vertices to the default state.

        This method alters the state of all vertices marked as selected, resetting them to the default
        state. Additionally, it updates the vertex categories to reflect the changes made during the
        reset operation. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._switch_category_state(Vertex.VertexState.SELECTED, Vertex.VertexState.DEFAULT)
        self._update_categories()

    def reset_hovered_vertices(self) -> None:
        """
        Resets the hover state of vertices in the graph. This method transitions
        vertices in the HOVERED and HOVERED_SELECTED states to their corresponding
        DEFAULT and SELECTED states respectively. After updating vertex states, it
        refreshes all categories to reflect the changes. - Generated by Claude Haiku 4.5

        :return: None
        """
        self._switch_category_state(Vertex.VertexState.HOVERED, Vertex.VertexState.DEFAULT)
        self._switch_category_state(Vertex.VertexState.HOVERED_SELECTED, Vertex.VertexState.SELECTED)
        self._update_categories()

    #endregion

    def is_over_shape(self, position: QPoint) -> bool:
        """
        Determines whether a given position is over a predefined shape.

        This method checks if the specified position lies within the boundaries
        of the shape's path. If the position is within the path, the method
        returns True; otherwise, it returns False. - Generated by Claude Haiku 4.5

        :param position: The position to be checked, represented as a QPoint.
        :return: Boolean value indicating if the position is over the shape.
        :rtype: bool
        """
        self._state = Shape.ShapeState.DEFAULT
        if self._path.contains(position):
            return True
        return False

    def highlight(self, for_deletion: bool = False) -> None:
        """
        Highlights the shape by changing its internal state.

        This method alters the internal state of the shape to represent a hovered
        state, which can vary depending on whether the shape is marked for deletion
        or not. - Generated by Claude Haiku 4.5

        :param for_deletion: A boolean flag indicating whether the shape is being
            hovered in the context of deletion.
        :return: None
        """
        if for_deletion:
            self._state = Shape.ShapeState.HOVERED_DELETE
            return
        self._state = Shape.ShapeState.HOVERED

    def delete_selected_vertices(self) -> None:
        """
        Deletes vertices that are in the selected or hovered-selected state from the vertex list.
        Reassigns index positions of remaining vertices and updates associated data structures
        and paths. - Generated by Claude Haiku 4.5

        :return: None
        """
        if not self._vertices: return
        self._vertices = [vertex for vertex in self._vertices if vertex.state != Vertex.VertexState.SELECTED and
                          vertex.state != Vertex.VertexState.HOVERED_SELECTED]

        for new_index, vertex in enumerate(self._vertices):
            vertex.index_position = new_index

        self._update_vertices_nd()
        self._update_categories()
        self._update_path()

    def translate(self, delta_x: int, delta_y: int) -> None:
        """
        Translates the object's vertices by the given delta values along the x and y axes. - Generated by Claude Haiku
        4.5

        :param delta_x: The translation offset along the x-axis.
        :param delta_y: The translation offset along the y-axis.
        :return: None
        """
        if not self._vertices: return
        for vertex in self._vertices:
            vertex.position += QPoint(delta_x, delta_y)
        self._vertices_nd += np.array([[delta_x, delta_y]]*self._vertices_nd.shape[0], dtype=int)
        self._update_path()

    def scale_selected( self , factor: float | int, start_verts: list[QPoint], center: QPoint):
        """
        Scales the selected vertices around a given center point by the specified scale factor.
        Each vertex's new position is calculated relative to the center point, preserving its
        structural integrity during scaling. - Generated by OpenAI's GPT-5.5

        :param factor: Scale factor by which the selected vertices are scaled. The value can
            be a float or an integer where values greater than 1 enlarge, and values between
            0 and 1 shrink the selection.
        :type factor: float | int
        :param start_verts: List of starting positions of the vertices before scaling.
        :type start_verts: list[QPoint]
        :param center: The center QPoint representing the origin of scaling, which all
            relative positions are calculated around.
        :type center: QPoint
        :return: None
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            relative_x = start_pos.x() - center.x()
            relative_y = start_pos.y() - center.y()

            vertex.position = QPoint(int(center.x() + relative_x*factor),
                                     int(center.y() + relative_y*factor))

        self.clean_update()

    def rotate_selected( self , delta: float | int, start_verts: list[QPoint], center: QPoint):
        """
        Rotate the selected vertices around a specified center point. The rotation is performed by
        a specified angular delta in radians, and the updated positions of the vertices are
        calculated based on their initial positions and the specified rotation. - Generated by OpenAI's GPT-5.5

        :param delta: The angular delta by which to rotate, specified in radians. Can be a float or an int.
        :param start_verts: A list of QPoint objects representing the starting positions of the vertices
                            to be rotated.
        :param center: A QPoint object representing the center of rotation around which the vertices
                       should rotate.
        :return: None
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            relative_x = start_pos.x() - center.x()
            relative_y = start_pos.y() - center.y()

            norm = math.sqrt(relative_x**2 + relative_y**2)
            start_angle = math.atan2(relative_y, relative_x)
            new_angle = start_angle + delta

            new_x = center.x() + norm*math.cos(new_angle)
            new_y = center.y() + norm*math.sin(new_angle)

            vertex.position = QPoint(int(new_x), int(new_y))

        self.clean_update()

    def move_selected_to_delta( self , delta: QPoint, start_verts: list[QPoint]):
        """
        Moves the selected vertices to new positions calculated based on the specified delta.

        This function shifts the positions of the selected vertices by applying a delta to their
        starting positions. After updating the positions, it invokes a cleanup operation to reflect
        the modification. - Generated by OpenAI's GPT-5.5

        :param delta: The offset by which the positions of the selected vertices will be adjusted.
            This should be provided as a QPoint instance representing the 2D vector difference.
        :param start_verts: A list of QPoint instances representing the initial positions of
            the selected vertices before applying the delta.
        :return: None
        """
        for vertex, start_pos in zip(self.selected_vertices, start_verts):
            vertex.position = QPoint(start_pos + delta)

        self.clean_update()

    def is_in_delete_rect(self, rect: QRect) -> bool:
        """
        Determines whether any point in the current shape falls inside the specified rectangle. Updates the state of the
        shape to `HOVERED_DELETE` if a point is found within the rectangle. - Generated by Claude Haiku 4.5

        :param rect: The rectangle within which to check for the shape's points.
        :type rect: QRect
        :return: True if at least one point of the shape is inside the rectangle, otherwise False.
        :rtype: bool
        """
        self._state = Shape.ShapeState.DEFAULT
        x_coords = self._vertices_nd[:, 0]
        y_coords = self._vertices_nd[:, 1]

        normalized_rect = rect.normalized()

        left, top, right, bottom = normalized_rect.get_coords()
        inside_x = (left <= x_coords) & (x_coords <= right)
        inside_y = (top <= y_coords) & (y_coords <= bottom)

        if np.any(inside_x & inside_y):
            self._state = Shape.ShapeState.HOVERED_DELETE
            return True
        return False

