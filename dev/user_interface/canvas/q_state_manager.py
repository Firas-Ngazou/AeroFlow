from enum import Enum

from PySide6.QtCore import QObject, Signal, Slot


class QStateManager(QObject):
    """
    A centralized state machine managing all user interaction contexts for the editor canvas.

    By decoupling the interaction states from the rendering and physics logic,
    we prevent massive conditional nesting and allow multiple UI components
    to subscribe to state changes cleanly.

    - Generated by Gemini
    """

    class MouseState(Enum):
        """
        Tracks the active physical state of the mouse buttons.

        # Design flaw: holding MB1 and MB2 at the same time is not possible :(

        - Generated by Gemini
        """
        DEFAULT = 0
        HOLDING_MB1 = 1
        HOLDING_MB2 = 2
        HOLDING_MB3 = 3

    class MouseLocation(Enum):
        """
        Identifies the semantic geometric target directly underneath the mouse cursor.

        - Generated by Gemini
        """
        DEFAULT = 0
        OVER_VERTEX = 1
        OVER_SHAPE = 2

    class CursorState(Enum):
        """
        Dictates the global tool mode for the application, such as drawing vs standard manipulation.

        - Generated by Gemini
        """
        DEFAULT = 0
        PEN = 1
        LOCKED = 2

    cursorStateChanged = Signal(CursorState)

    class ActionState(Enum):
        """
        Monitors complex multi-step canvas operations like dragging bounds or snapping vertices.

        - Generated by Gemini
        """
        DEFAULT = 0
        SELECTING_VERTICES = 1
        MOVING_VERTEX = 2
        MOVING_VERTICES = 3

    class KeyState(Enum):
        """
        Tracks active keyboard modifiers that alter standard tool behavior.

        - Generated by Gemini
        """
        DEFAULT = 0
        HOLDING_SHIFT = 1
        HOLDING_CTRL = 2

    def __init__(self, parent: QObject | None = None) -> None:
        """
        Initializes the state manager to a clean, idle configuration.

        :param parent: Optional parent QObject for Qt's ownership hierarchy.
        :type parent: QObject | None

        - Generated by Gemini
        """
        super().__init__(parent)
        self._mouse_state: QStateManager.MouseState = QStateManager.MouseState.DEFAULT
        self._cursor_state: QStateManager.CursorState = QStateManager.CursorState.DEFAULT
        self._action_state: QStateManager.ActionState = QStateManager.ActionState.DEFAULT
        self._mouse_location: QStateManager.MouseLocation = QStateManager.MouseLocation.DEFAULT
        self._key_state: QStateManager.KeyState = QStateManager.KeyState.DEFAULT

    @property
    def mouse_state(self) -> MouseState:
        """
        Retrieves the current physical mouse button state.

        :return: Active mouse state.
        :rtype: MouseState

        - Generated by Gemini
        """
        return self._mouse_state

    @mouse_state.setter
    def mouse_state(self, state: MouseState) -> None:
        """
        Updates the internal physical mouse button state.

        :param state: New mouse state.
        :type state: MouseState

        - Generated by Gemini
        """
        self._mouse_state = state

    @Slot(CursorState)
    def set_cursor_state(self, state: CursorState) -> None:
        """
        A Qt Slot to safely update the active tool cursor state from signals.

        :param state: New cursor mode.
        :type state: CursorState

        - Generated by Gemini
        """
        self.cursor_state = state

    @property
    def cursor_state(self) -> CursorState:
        """
        Retrieves the global tool cursor mode.

        :return: Active cursor mode.
        :rtype: CursorState

        - Generated by Gemini
        """
        return self._cursor_state

    @cursor_state.setter
    def cursor_state(self, state: CursorState) -> None:
        """
        Updates the global cursor mode and immediately emits the cursorStateChanged signal
        so the UI can update its visual pointer.

        :param state: New cursor mode.
        :type state: CursorState

        - Generated by Gemini
        """
        self.cursorStateChanged.emit(state)
        self._cursor_state = state

    @property
    def action_state(self) -> ActionState:
        """
        Retrieves the current multi-step canvas operation state.

        :return: Active action state.
        :rtype: ActionState

        - Generated by Gemini
        """
        return self._action_state

    @action_state.setter
    def action_state(self, state: ActionState) -> None:
        """
        Updates the active canvas operation state.

        :param state: New action state.
        :type state: ActionState

        - Generated by Gemini
        """
        self._action_state = state

    @property
    def mouse_location(self) -> MouseLocation:
        """
        Retrieves the semantic target currently hovered by the mouse.

        :return: Active mouse location state.
        :rtype: MouseLocation

        - Generated by Gemini
        """
        return self._mouse_location

    @mouse_location.setter
    def mouse_location(self, location: MouseLocation) -> None:
        """
        Updates the semantic target currently hovered by the mouse.

        :param location: New hover state.
        :type location: MouseLocation

        - Generated by Gemini
        """
        self._mouse_location = location

    @property
    def key_state(self) -> KeyState:
        """
        Retrieves the currently held keyboard modifier.

        :return: Active keyboard modifier state.
        :rtype: KeyState

        - Generated by Gemini
        """
        return self._key_state

    @key_state.setter
    def key_state(self, state: KeyState) -> None:
        """
        Updates the tracked keyboard modifier state.

        :param state: New modifier state.
        :type state: KeyState

        - Generated by Gemini
        """
        self._key_state = state