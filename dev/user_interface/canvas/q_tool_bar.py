class QToolPB(QPushButton):
    """
    A unified push button specifically styled for my main toolbar array.

    I use this to keep all the tool icons locked to identical dimensions and CSS classes
    so the toolbar doesn't jitter when layout shifts occur.

    - Generated by Gemini
    """

    def __init__(self, icon: QIcon, checkable: bool = True, parent: QWidget | None = None) -> None:
        """
        Initializes the fixed-size tool button.

        :param icon: The icon to render.
        :type icon: QIcon
        :param checkable: True if the button acts as a toggle, False for standard clicks.
        :type checkable: bool
        :param parent: Optional parent layout.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self.icon = icon
        self.icon_size = QSize(21, 21)
        self.set_fixed_width(44)
        self.set_fixed_height(44)
        self.checkable = checkable
        self.set_property("class", "tool_pb")


class QToolBar(QWidget):
    """
    The main user interaction hub anchoring the bottom of the canvas.

    This toolbar dispatches global state changes (like swapping from the selection cursor
    to the drawing pen) and kicks off the actual fluid simulation loop. It's bound directly
    to my QStateManager so tool swaps instantly lock/unlock UI features across the whole app.

    :ivar playPressed: Triggered when the user hits the simulation start button.
    :ivar stopPressed: Triggered to kill the simulation loop.
    :ivar instanceRequested: Triggered when the user clicks a prefab icon to drop onto the canvas.

    - Generated by Gemini
    """
    playPressed = Signal()
    stopPressed = Signal()
    instanceRequested = Signal(dict)

    def __init__(self, state_manager: QStateManager, parent: QWidget | None = None) -> None:
        """
        Initializes the toolbar layout, icons, and signal hookups to the state manager.

        :param state_manager: The central hub tracking current tool mode.
        :type state_manager: QStateManager
        :param parent: The layout container.
        :type parent: QWidget | None

        - Generated by Gemini
        """
        super().__init__(parent)

        self._is_optimizing: bool = False
        self._has_drawing: bool = False
        self._cursor_state: QStateManager.CursorState = QStateManager.CursorState.DEFAULT
        self._state_manager: QStateManager = state_manager

        # setup
        primary_frame = QFrame()
        primary_frame.set_property("class", "primary_frame")
        primary_frame.set_fixed_height(56)
        primary_frame.set_fixed_width(255)
        primary_layout = QHBoxLayout(primary_frame)
        primary_layout.set_contents_margins(5, 5, 5, 5)
        self._live_edit: bool = False

        # default button
        default_icon = QIcon(":/res/cursor_icon_black.png")
        self._default_button = QToolPB(default_icon)
        self._default_button.checked = True

        # pen button
        pen_icon = QIcon(":/res/pen_icon_black.png")
        self._pen_button = QToolPB(pen_icon)

        # play button
        self._play_icon = QIcon(":/res/play_icon_black.png")
        self._stop_icon = QIcon(":/res/stop_icon_black.png")
        self._play_button = QPushButton()
        self._play_button.checkable = True
        self._play_button.set_property("class", "play_pb")
        self._play_button.icon = self._play_icon
        self._play_button.icon_size = QSize(21, 21)
        self._play_button.set_fixed_width(44)
        self._play_button.set_fixed_height(44)
        self._play_button.set_disabled(True)

        # Info button
        info_icon = QIcon(":/res/info_icon_black.png")
        self._info_button = QToolPB(info_icon, checkable = False)
        self._info_button.icon_size = QSize(32, 32)
        self._info_font = QFont("JetBrains Mono", 10)

        # prefabs
        prefabs_icon = QIcon(":/res/shapes_icon_black.png")
        self._prefabs_button = QToolPB(prefabs_icon)
        self._prefab_scroll = QPrefabScroll()
        self._prefab_scroll.hide()

        primary_layout.add_widget(self._default_button)
        primary_layout.add_widget(self._pen_button)
        primary_layout.add_widget(self._play_button)
        primary_layout.add_widget(self._prefabs_button)
        primary_layout.add_widget(self._info_button)

        root_layout = QVBoxLayout(self)
        root_layout.spacing = 5
        root_layout.add_widget(self._prefab_scroll,
                               alignment = Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignBottom)
        root_layout.add_widget(primary_frame, alignment = Qt.AlignmentFlag.AlignHCenter)
        self.set_layout(root_layout)

        # connect signals
        self._default_button.clicked.connect(self._on_cursor_button_pressed)
        self._pen_button.clicked.connect(self._on_cursor_button_pressed)
        self._prefabs_button.clicked.connect(self._on_prefabs_button_pressed)
        self._prefab_scroll.instanceRequested.connect(self.instanceRequested.emit)

        self._play_button.clicked.connect(self._on_anim_button_pressed)
        self._info_button.pressed.connect(self._on_info_pressed)

        self._state_manager.cursorStateChanged.connect(self._on_cursor_state_changed)

