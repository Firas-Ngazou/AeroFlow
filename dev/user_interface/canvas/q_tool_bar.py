    @Slot(QStateManager.CursorState)
    def _on_cursor_state_changed(self, state: QStateManager.CursorState) -> None:
        """
        Listens to the state manager; if the simulation spins up and locks the canvas,
        I forcefully disable the tool buttons unless we are specifically allowing live-editing.

        :param state: Incoming new cursor mode.
        :type state: QStateManager.CursorState
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if state == QStateManager.CursorState.LOCKED and not self.live_edit:
            self._default_button.set_disabled(True)
            self._pen_button.set_disabled(True)
            self._prefabs_button.set_disabled(True)
        else:
            self._default_button.set_disabled(False)
            self._pen_button.set_disabled(False)
            self._prefabs_button.set_disabled(False)

    @Slot()
    def _on_cursor_button_pressed(self) -> None:
        """
        Handles the logic for mutually exclusive tool toggles (Pen vs Cursor), then updates
        the global state manager.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        sender = self.sender()
        # The default cursor was pressed
        if sender == self._default_button:
            # Cursor was already set to default
            if self._cursor_state == QStateManager.CursorState.DEFAULT:
                self._default_button.checked = True
                return

            # Cursor was not set to default
            state = QStateManager.CursorState.DEFAULT
            self._default_button.checked = True
            self._pen_button.checked = False
        # The pen cursor was pressed
        elif sender == self._pen_button:
            # Cursor was already set to pen
            if self._cursor_state == QStateManager.CursorState.PEN:
                self._pen_button.checked = True
                return

            # Cursor was not set to pen
            state = QStateManager.CursorState.PEN
            self._default_button.checked = False
            self._pen_button.checked = True
        else:
            return

        self._cursor_state = state
        self._state_manager.set_cursor_state(state)

    @Slot()
    def _on_anim_button_pressed(self) -> None:
        """
        Toggles the simulation run state. If starting, it hides the prefab menu, locks the cursor,
        and blasts the play signal down to the physics thread.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        sender = self.sender()
        if sender == self._play_button:
            if self._play_button.checked:
                self._prefab_scroll.hide()

                if not self._live_edit: self._state_manager.set_cursor_state(QStateManager.CursorState.LOCKED)
                self._play_button.icon = self._stop_icon
                self.playPressed.emit()
            else:
                if self._prefabs_button.checked:
                    self._prefab_scroll.show()
                self._play_button.icon = self._play_icon
                self.stopPressed.emit()

    @Slot(QStateManager.CursorState)
    def update_cursor_state(self, state: QStateManager.CursorState) -> None:
        """
        Forces the UI toggle buttons to match an externally triggered state change.

        :param state: Desired cursor mode.
        :type state: QStateManager.CursorState
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._cursor_state = state
        self._default_button.checked = state == QStateManager.CursorState.DEFAULT
        self._pen_button.checked = state == QStateManager.CursorState.PEN

    @Slot()
    def _on_prefabs_button_pressed(self) -> None:
        """
        Expands or collapses the horizontal prefab shape browser.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        if self._prefabs_button.checked:
            self._prefab_scroll.show()
        else:
            self._prefab_scroll.hide()

    def add_prefab_to_scroll(self, data: dict) -> None:
        """
        Registers a new saved layout into the visual browser reel.

        :param data: Serialized layout data and thumbnail.
        :type data: dict
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._prefab_scroll.add_prefab(data)

    @property
    def live_edit(self) -> bool:
        """
        Checks if the timeline buffer is bypassed to allow live manipulation.

        :return: True if live edit is permitted.
        :rtype: bool

        - Generated by Gemini
        """
        return self._live_edit

    @live_edit.setter
    def live_edit(self, value: bool) -> None:
        """
        Toggles live editing permissions.

        :param value: New toggle state.
        :type value: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._live_edit = value

    @property
    def is_optimizing(self) -> bool:
        """
        Checks if the genetic optimization loop has hijacked the engine.

        :return: True if optimizing.
        :rtype: bool

        - Generated by Gemini
        """
        return self._is_optimizing

    @is_optimizing.setter
    def is_optimizing(self, value: bool) -> None:
        """
        Toggles the optimization lock, disabling the standard play button.

        :param value: Toggle state.
        :type value: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._is_optimizing = value
        self._refresh_play_button()

    @property
    def has_drawing(self) -> bool:
        """
        Checks if the canvas actually contains any geometry worth simulating.

        :return: True if valid paths exist.
        :rtype: bool

        - Generated by Gemini
        """
        return self._has_drawing

    @has_drawing.setter
    def has_drawing(self, value: bool) -> None:
        """
        Updates the canvas status, enabling the play button if geometry is present.

        :param value: Valid geometry status.
        :type value: bool
        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._has_drawing = value
        self._refresh_play_button()

    def _refresh_play_button(self) -> None:
        """
        Internal check to make sure users can't try to run physics on an empty canvas
        or interrupt an optimization batch.

        :return: None
        :rtype: None

        - Generated by Gemini
        """
        self._play_button.set_disabled(self._is_optimizing or not self._has_drawing)